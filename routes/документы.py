# routes/документы.py — жеребьёвка и технические документы соревнования
import random
from datetime import date
from flask import Blueprint, render_template, request, redirect, url_for, flash, jsonify
from models import db, Соревнование, Субъект, Команда, Спортсмен, Судья

bp_документы = Blueprint('документы', __name__)

МИН_СОСТАВ = {'R4': 4, 'R6': 6}


def _команды_сор(sor_id):
    return (Команда.query
            .filter_by(соревнование_id=sor_id)
            .order_by(Команда.нагрудный_номер)
            .all())


def _команды_готовы(команды):
    """Возвращает set id команд с достаточным составом."""
    результат = set()
    for к in команды:
        мин = МИН_СОСТАВ.get(к.класс_судна, 4)
        if len(к.спортсмены) >= мин:
            результат.add(к.id)
    return результат


def _parse_взнос(val):
    if not val:
        return None
    try:
        return float(str(val).replace(',', '.').strip())
    except ValueError:
        return None


# ── Жеребьёвка ──────────────────────────────────────────────────────────────

@bp_документы.route('/<int:sor_id>/жеребьёвка')
def жеребьёвка(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    команды = _команды_сор(sor_id)

    def сорт(список):
        return sorted(список, key=lambda к: (к.стартовый_номер_спринт or 9999, к.нагрудный_номер))

    муж_р4 = сорт([к for к in команды if к.пол == 'м' and к.класс_судна == 'R4'])
    жен_р4 = сорт([к for к in команды if к.пол == 'ж' and к.класс_судна == 'R4'])
    муж_р6 = сорт([к for к in команды if к.пол == 'м' and к.класс_судна == 'R6'])
    жен_р6 = сорт([к for к in команды if к.пол == 'ж' and к.класс_судна == 'R6'])
    return render_template('документы/жеребьёвка.html', сор=сор,
                           муж_р4=муж_р4, жен_р4=жен_р4,
                           муж_р6=муж_р6, жен_р6=жен_р6)


