@bp_документы.route('/<int:sor_id>/жеребьёвка/сохранить', methods=['POST'])
def жеребьёвка_сохранить(sor_id):
    """Сохранить порядок жеребьёвки + нагрудные номера + плановые времена старта."""
    сор = Соревнование.query.get_or_404(sor_id)

    # Порядок жеребьёвки по классам и полу
    for key in ('порядок_м_р4', 'порядок_ж_р4', 'порядок_м_р6', 'порядок_ж_р6'):
        for i, kid_str in enumerate(request.form.getlist(key), 1):
            try:
                к = Команда.query.get(int(kid_str))
                if к and к.соревнование_id == sor_id:
                    к.стартовый_номер_спринт = i
            except (ValueError, TypeError):
                pass

    # Нагрудные номера — собираем из формы
    новые_номера: dict[int, int] = {}  # kid -> новый номер
    все_команды_карта: dict[int, object] = {}
    with db.session.no_autoflush:
        for key, val in request.form.items():
            if key.startswith('номер_'):
                try:
                    kid = int(key[len('номер_'):])
                    к = Команда.query.get(kid)
                    if к and к.соревнование_id == sor_id and val.strip():
                        новые_номера[kid] = int(val)
                        все_команды_карта[kid] = к
                except (ValueError, TypeError):
                    pass

    # Проверяем уникальность внутри каждого вида (класс_судна + пол) отдельно.
    # Ключ группы: (класс_судна, пол) — номера уникальны только внутри одного вида.
    def _группа(к):
        return (к.класс_судна, к.пол)

    # Дубли внутри формы — в одной группе
    по_группам: dict = {}
    for kid, номер in новые_номера.items():
        г = _группа(все_команды_карта[kid])
        по_группам.setdefault(г, {}).setdefault(номер, []).append(kid)
    дубли_формы = {
        (г, н): kids
        for г, гр in по_группам.items()
        for н, kids in гр.items()
        if len(kids) > 1
    }

    # Конфликт с командами той же группы, НЕ обновляемыми этой формой
    занятые_по_группам: dict = {}
    for к in Команда.query.filter_by(соревнование_id=sor_id).all():
        if к.нагрудный_номер is not None and к.id not in новые_номера:
            занятые_по_группам.setdefault(_группа(к), {})[к.нагрудный_номер] = к.id
    конфликты = {
        (г, н): kid
        for kid, н in новые_номера.items()
        for г in [_группа(все_команды_карта[kid])]
        if н in занятые_по_группам.get(г, {})
    }

    if дубли_формы or конфликты:
        db.session.rollback()
        части = []
        for (г, н), kids in дубли_формы.items():
            части.append(f'номер {н} повторяется в группе {г[0]}/{г[1]} ({len(kids)} команды)')
        for (г, н) in конфликты:
            части.append(f'номер {н} уже занят в группе {г[0]}/{г[1]}')
        flash('Не удалось сохранить: ' + '; '.join(части) + '.', 'danger')
        return redirect(url_for('документы.жеребьёвка', sor_id=sor_id))

    # Двухфазное обновление через временные отрицательные значения.
    # Фаза 1: уникальные временные номера (-id), чтобы снять старые UNIQUE-конфликты.
    # Фаза 2: назначаем правильные номера.
    with db.session.no_autoflush:
        for kid, к in все_команды_карта.items():
            к.нагрудный_номер = -kid
    db.session.flush()
    for kid, номер in новые_номера.items():
        все_команды_карта[kid].нагрудный_номер = номер

    # Плановое время старта — сохраняем прямо на команде (время_старта_спринт_план),
    # чтобы оно было доступно без записи результата.
    # Также пишем в рез.время_старта для совместимости с расчётом результатов.
    дк_ids = set()
    for key in request.form:
        if key.startswith('дк_') and key[3:].isdigit():
            дк_ids.add(int(key[3:]))

    все_команды = Команда.query.filter_by(соревнование_id=sor_id).all()
    for к in все_команды:
        kid = к.id
        is_дк = kid in дк_ids
        in_form = f'вс_{kid}' in request.form or is_дк
        if not in_form:
            continue
        if not is_дк:
            parsed = _parse_time(request.form.get(f'вс_{kid}', ''))
            к.время_старта_спринт_план = _format_time(parsed) if parsed is not None else None
        рез = _получить_или_создать_рез(к, sor_id)
        рез.стартовый_номер = к.стартовый_номер_спринт
        if is_дк:
            рез.статус = СТАТУС_ДК
        else:
            рез.время_старта = parsed
            if f'с10_{kid}' in request.form:
                рез.штраф_с10 = _int0(request.form.get(f'с10_{kid}'))
            if f'с50_{kid}' in request.form:
                рез.штраф_с50 = _int0(request.form.get(f'с50_{kid}'))

    try:
        db.session.commit()
        flash('Порядок жеребьёвки сохранён.', 'success')
    except Exception:
        db.session.rollback()
        flash('Ошибка при сохранении: возможно, дублирующийся нагрудный номер.', 'danger')
    return redirect(url_for('документы.жеребьёвка', sor_id=sor_id))


