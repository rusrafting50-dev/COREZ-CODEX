_КОД_ДОПУСК = {
    'R4-м': ('R4', 'м', 'Мужчины'),
    'R4-ж': ('R4', 'ж', 'Женщины'),
    'R6-м': ('R6', 'м', 'Мужчины'),
    'R6-ж': ('R6', 'ж', 'Женщины'),
}


@bp_документы.route('/<int:sor_id>/протокол-допуска')
def протокол_допуска(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    все_команды = _команды_сор(sor_id)
    классы = sorted({к.класс_судна for к in все_команды})
    вывод = сор.вывод_допуска or 'Попарно'
    последовательность = (сор.последовательность_допуска or 'R4-м,R4-ж,R6-м,R6-ж').split(',')

    def _секции(фильтр_класс=None):
        рез = []
        for код in последовательность:
            if код not in _КОД_ДОПУСК:
                continue
            кл, пол, назв = _КОД_ДОПУСК[код]
            if фильтр_класс and кл != фильтр_класс:
                continue
            список = [к for к in все_команды if к.класс_судна == кл and к.пол == пол]
            if список:
                рез.append({'заголовок': назв, 'класс': кл, 'команды': список})
        return рез

    состав_комиссии = СоставКомиссииДопуска.query.filter_by(соревнование_id=sor_id).first()

    if вывод == 'Вместе':
        секции = _секции()
        заголовок_класс = ', '.join(классы) if классы else 'R4, R6'
    elif вывод == 'Раздельно':
        секции = _секции()
        заголовок_класс = None
    else:
        класс = request.args.get('класс', классы[0] if классы else 'R4')
        секции = _секции(класс)
        заголовок_класс = класс

    return render_template('документы/протокол_допуска.html',
                           сор=сор, секции=секции,
                           заголовок_класс=заголовок_класс,
                           вывод=вывод,
                           класс=request.args.get('класс', классы[0] if классы else 'R4'),
                           классы=классы,
                           состав_комиссии=состав_комиссии,
                           сегодня=date.today())


