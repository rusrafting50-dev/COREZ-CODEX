@bp_документы.route('/<int:sor_id>/заявки')
def заявки(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    субъекты = (Субъект.query
                .filter_by(соревнование_id=sor_id)
                .order_by(Субъект.номер_делегации)
                .all())
    взнос = request.args.get('взнос', '').strip()
    взнос_руб = _parse_взнос(взнос)
    # Агрегаты по делегациям вычисляются здесь (не в Jinja2)
    info = {}
    for с in субъекты:
        кол_сп = sum(len(к.спортсмены) for к in с.команды)
        info[с.id] = {
            'кол_спортсменов': кол_сп,
            'кол_команд': len(с.команды),
            'итого': int(взнос_руб * кол_сп) if взнос_руб else None,
        }
    return render_template('документы/заявки.html',
                           сор=сор, субъекты=субъекты,
                           взнос=взнос, взнос_руб=взнос_руб, info=info)


