# ── Акт технической комиссии ────────────────────────────────────────────────

@bp_документы.route('/<int:sor_id>/акт-тех-комиссии')
def акт_тех_комиссии(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    команды = _команды_сор(sor_id)
    судьи = Судья.query.filter_by(соревнование_id=sor_id).all()
    готовы = _команды_готовы(команды)
    # Члены технической комиссии
    РОЛИ_ТК = {'Председатель комиссии по допуску', 'Технический делегат',
               'Начальник дистанции', 'Начальник спасательной службы'}
    члены_тк = [с for с in судьи if с.должность in РОЛИ_ТК]
    муж_кол = sum(1 for к in команды if к.пол == 'м')
    жен_кол = sum(1 for к in команды if к.пол == 'ж')
    return render_template('документы/акт_тех_комиссии.html',
                           сор=сор, команды=команды,
                           члены_тк=члены_тк, готовы=готовы,
                           муж_кол=муж_кол, жен_кол=жен_кол,
                           допущено=len(готовы),
                           сегодня=date.today())
