МИН_СОСТАВ = {'R4': 4, 'R6': 6}


def _команды_сор(sor_id):
    return (Команда.query
            .filter_by(соревнование_id=sor_id)
            .order_by(Команда.нагрудный_номер)
            .all())


def _команды_готовы(команды):
    """Возвращает set id команд с достаточным составом."""
    результат = set()
    for к in команды:
        мин = МИН_СОСТАВ.get(к.класс_судна, 4)
        if len(к.спортсмены) >= мин:
            результат.add(к.id)
    return результат


def _parse_взнос(val):
    if not val:
        return None
    try:
        return float(str(val).replace(',', '.').strip())
    except ValueError:
        return None


def _parse_time(val):
    if not val or not str(val).strip():
        return None
    val = str(val).strip().replace(',', '.')
    m = re.match(r'^(\d{1,2}):(\d{2}):(\d{2})(?:\.(\d{1,2}))?$', val)
    if not m:
        return None
    h, mm, s = int(m[1]), int(m[2]), int(m[3])
    cc = int((m[4] or '').ljust(2, '0')[:2])
    return float(h * 3600 + mm * 60 + s) + cc / 100


def _format_time(secs):
    if secs is None:
        return ''
    secs = float(secs)
    h = int(secs // 3600)
    rest = secs % 3600
    m = int(rest // 60)
    sv = rest % 60
    si = int(sv)
    cc = min(99, round((sv - si) * 100))
    return f'{h:02d}:{m:02d}:{si:02d}.{cc:02d}'


def _int0(val):
    try:
        return max(0, int(val or 0))
    except (ValueError, TypeError):
        return 0


def _получить_или_создать_рез(к, sor_id):
    рез = к.результат_спринт
    if not рез:
        рез = РезультатСпринт(
            команда_id=к.id,
            соревнование_id=sor_id,
            стартовый_номер=к.стартовый_номер_спринт,
        )
        db.session.add(рез)
        db.session.flush()
    return рез


