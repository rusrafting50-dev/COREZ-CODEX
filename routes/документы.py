# ── Технические заявки ──────────────────────────────────────────────────────

@bp_документы.route('/<int:sor_id>/заявки')
def заявки(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    субъекты = (Субъект.query
                .filter_by(соревнование_id=sor_id)
                .order_by(Субъект.номер_делегации)
                .all())
    взнос = request.args.get('взнос', '').strip()
    взнос_руб = _parse_взнос(взнос)
    # Агрегаты по делегациям вычисляются здесь (не в Jinja2)
    info = {}
    for с in субъекты:
        кол_сп = sum(len(к.спортсмены) for к in с.команды)
        info[с.id] = {
            'кол_спортсменов': кол_сп,
            'кол_команд': len(с.команды),
            'итого': int(взнос_руб * кол_сп) if взнос_руб else None,
        }
    return render_template('документы/заявки.html',
                           сор=сор, субъекты=субъекты,
                           взнос=взнос, взнос_руб=взнос_руб, info=info)


@bp_документы.route('/<int:sor_id>/заявки/<int:sub_id>')
def заявка_делегации(sor_id, sub_id):
    сор = Соревнование.query.get_or_404(sor_id)
    субъект = Субъект.query.get_or_404(sub_id)
    команды = sorted(субъект.команды, key=lambda к: к.нагрудный_номер)
    взнос = request.args.get('взнос', '').strip()
    взнос_руб = _parse_взнос(взнос)
    всего_сп = sum(len(к.спортсмены) for к in команды)
    итого_руб = int(взнос_руб * всего_сп) if взнос_руб and всего_сп else None
    return render_template('документы/заявка_делегации.html',
                           сор=сор, субъект=субъект, команды=команды,
                           взнос=взнос, взнос_руб=взнос_руб,
                           всего_сп=всего_сп, итого_руб=итого_руб,
                           сегодня=date.today())


# ── Выписка из протокола комиссии по допуску ────────────────────────────────

@bp_документы.route('/<int:sor_id>/выписка-допуска')
def выписка_допуска(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    команды = _команды_сор(sor_id)
    готовы = _команды_готовы(команды)
    муж = [к for к in команды if к.пол == 'м' and к.id in готовы]
    жен = [к for к in команды if к.пол == 'ж' and к.id in готовы]
    не_допущены = [к for к in команды if к.id not in готовы]
    всего_сп = sum(len(к.спортсмены) for к in команды if к.id in готовы)
    return render_template('документы/выписка_допуска.html',
                           сор=сор, муж=муж, жен=жен,
                           не_допущены=не_допущены,
                           всего=len(команды),
                           допущено=len(готовы),
                           всего_сп=всего_сп,
                           сегодня=date.today())


