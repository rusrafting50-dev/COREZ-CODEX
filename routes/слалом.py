@bp_слалом.route('/<int:sor_id>/старт', methods=['GET', 'POST'])
def старт(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    if request.method == 'POST':
        for пол in ('м', 'ж'):
            for к in _по_посеву(sor_id, пол):
                for попытка in (1, 2):
                    вс = parse_time(request.form.get(f'вс{попытка}_{к.id}', ''))
                    if вс is not None or request.form.get(f'вс{попытка}_{к.id}', '') != '':
                        рез = _get_or_create(к, sor_id, попытка)
                        рез.время_старта = вс
        db.session.commit()
        flash('Стартовый протокол сохранён.', 'success')
        return redirect(url_for('слалом.старт', sor_id=sor_id))

    муж = _по_посеву(sor_id, 'м')
    жен = _по_посеву(sor_id, 'ж')
    мб_колонки = _дисц_мб(сор)
    виды_все = [
        ('R4-м', 'Слалом – R4, мужчины'),
        ('R4-ж', 'Слалом – R4, женщины'),
        ('R6-м', 'Слалом – R6, мужчины'),
        ('R6-ж', 'Слалом – R6, женщины'),
    ]
    текущий_порядок = (сор.последовательность_слалом or 'R4-м,R4-ж,R6-м,R6-ж').split(',')
    return render_template('слалом/старт.html',
                           сор=сор, муж=муж, жен=жен,
                           мб_колонки=мб_колонки,
                           виды_все=виды_все,
                           текущий_порядок=текущий_порядок,
                           format_time=format_time)


@bp_слалом.route('/<int:sor_id>/параметры-старт', methods=['POST'])
def параметры_старт(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    допустимые = {'R4-м', 'R4-ж', 'R6-м', 'R6-ж'}
    порядок = [request.form.get(f'порядок_{i}', '') for i in range(1, 5)]
    сор.последовательность_слалом = ','.join(к for к in порядок if к in допустимые) or None
    вывод = request.form.get('вывод_старт_слалом', 'Попарно')
    сор.вывод_старт_слалом = вывод if вывод in ('Попарно', 'Раздельно') else 'Попарно'
    db.session.commit()
    flash('Параметры стартового протокола сохранены.', 'success')
    return redirect(url_for('слалом.старт', sor_id=sor_id))


@bp_слалом.route('/<int:sor_id>/ворота/<int:attempt>', methods=['GET', 'POST'])
def ворота(sor_id, attempt):
    попытка = attempt
    if попытка not in (1, 2):
        return redirect(url_for('слалом.ворота', sor_id=sor_id, attempt=1))
    сор = Соревнование.query.get_or_404(sor_id)
    кол_ворот = сор.кол_ворот_слалом or 10

    if request.method == 'POST':
        # Обновить кол_ворот если передан
        новое_кол = _int0(request.form.get('кол_ворот', 0))
        if 1 <= новое_кол <= 20:
            сор.кол_ворот_слалом = новое_кол
            кол_ворот = новое_кол

        for пол in ('м', 'ж'):
            for к in _по_посеву(sor_id, пол):
                for воро in range(1, кол_ворот + 1):
                    val_str = request.form.get(f'в_{к.id}_{воро}', '0')
                    val = int(val_str) if val_str in ('0', '5', '50') else 0
                    ш = ШтрафВорот.query.filter_by(
                        команда_id=к.id, соревнование_id=sor_id,
                        номер_попытки=попытка, номер_ворот=воро
                    ).first()
                    if ш:
                        ш.штраф = val
                    else:
                        db.session.add(ШтрафВорот(
                            команда_id=к.id, соревнование_id=sor_id,
                            номер_попытки=попытка, номер_ворот=воро, штраф=val
                        ))
                # Пересчитать попытку
                рез = _get_result(к, попытка)
                if рез:
                    _пересчитать_попытку(рез, sor_id)
        db.session.commit()
        flash(f'Штрафы на воротах (попытка {попытка}) сохранены.', 'success')
        return redirect(url_for('слалом.ворота', sor_id=sor_id, attempt=попытка))

    муж = _по_посеву(sor_id, 'м')
    жен = _по_посеву(sor_id, 'ж')
    муж_штрафы = _штрафы_по_команде(sor_id, 'м', попытка)
    жен_штрафы = _штрафы_по_команде(sor_id, 'ж', попытка)
    return render_template('слалом/ворота.html',
                           сор=сор, попытка=попытка, кол_ворот=кол_ворот,
                           муж=муж, жен=жен,
                           муж_штрафы=муж_штрафы, жен_штрафы=жен_штрафы)


@bp_слалом.route('/<int:sor_id>/финиш', methods=['GET', 'POST'])
def финиш(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    допустимые = {s for s, _ in СТАТУСЫ_СПИСОК}

    if request.method == 'POST':
        for пол in ('м', 'ж'):
            for к in _по_посеву(sor_id, пол):
                for попытка in (1, 2):
                    рез = _get_or_create(к, sor_id, попытка)
                    вф = parse_time(request.form.get(f'вф{попытка}_{к.id}', ''))
                    ст = request.form.get(f'ст{попытка}_{к.id}', СТАТУС_ФИНИШ)
                    if ст not in допустимые:
                        ст = СТАТУС_ФИНИШ
                    рез.время_финиша = вф
                    рез.статус_попытки = ст
                    _пересчитать_попытку(рез, sor_id)
        db.session.commit()
        flash('Протокол финиша сохранён.', 'success')
        return redirect(url_for('слалом.финиш', sor_id=sor_id))

    муж = _по_посеву(sor_id, 'м')
    жен = _по_посеву(sor_id, 'ж')
    return render_template('слалом/финиш.html',
                           сор=сор, муж=муж, жен=жен,
                           format_time=format_time, format_dur=format_dur,
                           СТАТУСЫ=СТАТУСЫ_СПИСОК, СТАТУС_ФИНИШ=СТАТУС_ФИНИШ)


