@bp_слалом.route('/<int:sor_id>/старт', methods=['GET', 'POST'])
def старт(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    if request.method == 'POST':
        for пол in ('м', 'ж'):
            for к in _по_посеву(sor_id, пол):
                for попытка in (1, 2):
                    вс = parse_time(request.form.get(f'вс{попытка}_{к.id}', ''))
                    if вс is not None or request.form.get(f'вс{попытка}_{к.id}', '') != '':
                        рез = _get_or_create(к, sor_id, попытка)
                        рез.время_старта = вс
        db.session.commit()
        flash('Стартовый протокол сохранён.', 'success')
        return redirect(url_for('слалом.старт', sor_id=sor_id))

    муж = _по_посеву(sor_id, 'м')
    жен = _по_посеву(sor_id, 'ж')
    мб_колонки = _дисц_мб(сор)
    виды_все = [
        ('R4-м', 'Слалом – R4, мужчины'),
        ('R4-ж', 'Слалом – R4, женщины'),
        ('R6-м', 'Слалом – R6, мужчины'),
        ('R6-ж', 'Слалом – R6, женщины'),
    ]
    текущий_порядок = (сор.последовательность_слалом or 'R4-м,R4-ж,R6-м,R6-ж').split(',')
    return render_template('слалом/старт.html',
                           сор=сор, муж=муж, жен=жен,
                           мб_колонки=мб_колонки,
                           виды_все=виды_все,
                           текущий_порядок=текущий_порядок,
                           format_time=format_time)


