def _ps_место(к):
    """Итоговое место команды в Параллельном спринте."""
    з = (РезультатПараллельногоСпринта.query
         .filter_by(команда_id=к.id)
         .filter(РезультатПараллельногоСпринта.итоговое_место.isnot(None))
         .first())
    return з.итоговое_место if з else None


def _по_посеву(sor_id, пол, класс=None):
    """Порядок старта слалома: по сумме очков многоборья (меньше → первый старт)."""
    q = Команда.query.filter_by(соревнование_id=sor_id, пол=пол)
    if класс:
        q = q.filter_by(класс_судна=класс)
    команды = q.all()
    def ключ(к):
        рм = к.результат_многоборья
        сумма = float(рм.сумма_очков) if рм and рм.сумма_очков else 0.0
        return (сумма, к.нагрудный_номер or 9999)
    return sorted(команды, key=ключ)


def _дисц_мб(сор):
    """Колонки «Очки Многоборье»: три дисциплины всегда + Сумма."""
    return [
        {'заг': 'Спринт',                    'поле': 'очки_спринт'},
        {'заг': 'Параллельный<br>спринт',    'поле': 'очки_пс'},
        {'заг': 'Длинная<br>гонка',          'поле': 'очки_дг'},
        {'заг': 'Сумма',                     'поле': 'сумма_очков'},
    ]


def _get_result(к, попытка):
    return next((р for р in к.результат_слалом if р.номер_попытки == попытка), None)


def _get_or_create(к, sor_id, попытка):
    рез = _get_result(к, попытка)
    if not рез:
        рез = РезультатСлалома(
            команда_id=к.id, соревнование_id=sor_id, номер_попытки=попытка
        )
        db.session.add(рез)
        db.session.flush()
    return рез


def _суммировать_ворота(команда_id, sor_id, попытка):
    """Вернуть (кол_5, кол_50, суммарный_штраф) по воротам."""
    штрафы = ШтрафВорот.query.filter_by(
        команда_id=команда_id, соревнование_id=sor_id, номер_попытки=попытка
    ).all()
    н5  = sum(1 for ш in штрафы if ш.штраф == 5)
    н50 = sum(1 for ш in штрафы if ш.штраф == 50)
    return н5, н50, н5 * 5 + н50 * 50


def _пересчитать_попытку(рез, sor_id):
    """Обновить штрафное_время и результат_попытки из данных ворот и штрафов старта/финиша."""
    н5, н50, штраф_ворот = _суммировать_ворота(рез.команда_id, sor_id, рез.номер_попытки)
    рез.кол_штраф_5 = н5
    рез.кол_штраф_50 = н50
    штраф = штраф_ворот
    штраф += (рез.кол_штраф_с10 or 0) * 10
    штраф += (рез.кол_штраф_старт or 0) * 50
    штраф += (рез.кол_штраф_финиш or 0) * 50
    рез.штрафное_время = штраф
    if рез.время_старта is not None and рез.время_финиша is not None:
        рез.время_прохождения = рез.время_финиша - рез.время_старта
    if рез.статус_попытки in (СТАТУС_ДК, СТАТУС_ДНФ, СТАТУС_ДНС):
        рез.результат_попытки = None
    elif рез.время_прохождения is not None:
        рез.результат_попытки = рез.время_прохождения + рез.штрафное_время
    else:
        рез.результат_попытки = None


def _штрафы_по_команде(sor_id, пол, попытка):
    """Все штрафы ворот для пола и попытки: {команда_id: {номер_ворот: штраф}}."""
    ids = {к.id for к in Команда.query.filter_by(соревнование_id=sor_id, пол=пол).all()}
    все = ШтрафВорот.query.filter_by(соревнование_id=sor_id, номер_попытки=попытка)\
                          .filter(ШтрафВорот.команда_id.in_(ids)).all()
    result = {}
    for ш in все:
        result.setdefault(ш.команда_id, {})[ш.номер_ворот] = ш.штраф
    return result


def _рассчитать_итог(sor_id, пол, класс=None):
    """Рассчитать итоговые места. Вернуть (с_местом, без_места, разряды, попытки_dict)."""
    сор = Соревнование.query.get(sor_id)
    код = сор.код_соревнований if сор else None
    команды = _по_посеву(sor_id, пол, класс)

    с_местом = []
    без_места = []
    попытки = {}  # команда_id → {1: рез1, 2: рез2}

    for к in команды:
        рез1 = _get_result(к, 1)
        рез2 = _get_result(к, 2)
        if рез1:
            _пересчитать_попытку(рез1, sor_id)
        if рез2:
            _пересчитать_попытку(рез2, sor_id)
        попытки[к.id] = {1: рез1, 2: рез2}

        candidates = []
        for рез in (рез1, рез2):
            if рез and рез.результат_попытки is not None and рез.статус_попытки == СТАТУС_ФИНИШ:
                candidates.append((рез.результат_попытки, рез))

        if candidates:
            best_val, best_рез = min(candidates, key=lambda x: x[0])
            best_рез.лучший_результат = best_val
            с_местом.append((best_val, к, best_рез))
        elif рез1 or рез2:
            без_места.append((рез1 or рез2))

    с_местом.sort(key=lambda x: x[0])
    разряды = {}

    for i, (_, к, рез) in enumerate(с_местом, 1):
        рез.место = i
        оч = ТаблицаОчков.query.filter_by(дистанция='СЛАЛОМ', место=i).first()
        рез.очки = оч.очки if оч else 0
        if код:
            р = ТаблицаРазрядов.query.filter_by(тип='С', место=i, статус_код=код).first()
            разряды[к.id] = р.разряд if р and р.разряд and р.разряд != '-' else '—'

    db.session.commit()
    return [рез for _, _, рез in с_местом], [р for р in без_места], разряды, попытки


