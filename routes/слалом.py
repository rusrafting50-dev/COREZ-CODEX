def _ps_место(к):
    """Итоговое место команды в Параллельном спринте."""
    з = (РезультатПараллельногоСпринта.query
         .filter_by(команда_id=к.id)
         .filter(РезультатПараллельногоСпринта.итоговое_место.isnot(None))
         .first())
    return з.итоговое_место if з else None


def _кол_ворот_из_дистанции(sor_id, fallback=14):
    """Получить количество ворот из параметров дистанции (п.6); иначе fallback."""
    д = (ПараметрыДистанции.query
         .filter_by(соревнование_id=sor_id, тип='слалом')
         .order_by(ПараметрыДистанции.порядок)
         .first())
    if д and д.кол_ворот:
        try:
            return max(1, int(д.кол_ворот))
        except (ValueError, TypeError):
            pass
    return fallback


def _последняя_дисц_перед_слалом(сор, класс, пол):
    """Вернуть дисциплину, непосредственно предшествующую Слалому, для данного вида."""
    try:
        виды = json.loads(сор.виды_список) if сор and сор.виды_список else []
    except (ValueError, TypeError):
        виды = []
    for вид in виды:
        if класс and вид.get('дисциплина', '').upper() != класс.upper():
            continue
        if _пол_вида(вид.get('пол_возраст', '')) != пол:
            continue
        посл_str = вид.get('последовательность', '')
        посл = ['Спринт'] + [p.strip() for p in посл_str.split(',') if p.strip()]
        if 'Слалом' in посл:
            idx = посл.index('Слалом')
            if idx > 0:
                return посл[idx - 1]
    return None


def _по_посеву(sor_id, пол, класс=None):
    """Порядок старта слалома: по сумме очков многоборья (меньше → первый старт).

    Правила:
    1. По сумме очков всех предшествующих дисциплин (возрастание).
    2. При равенстве суммы — по очкам первого столбца слева от «Сумма»
       (последняя дисциплина в _МБ_ПОРЯДОК среди отображаемых, возрастание).
    3. При равенстве — по нагрудному номеру.
    """
    q = Команда.query.filter_by(соревнование_id=sor_id, пол=пол)
    if класс:
        q = q.filter_by(класс_судна=класс)
    команды = q.all()

    сор = Соревнование.query.get(sor_id)

    _кэш_тай: dict = {}

    def _поле_тай(кл, п):
        key = (кл, п)
        if key not in _кэш_тай:
            колонки = _дисц_мб_для_вида(сор, кл, п)
            # колонки[-1] = Сумма (поле=None), колонки[-2] = последняя дисциплина
            if len(колонки) >= 2 and колонки[-2].get('поле'):
                _кэш_тай[key] = колонки[-2]['поле']
            else:
                _кэш_тай[key] = None
        return _кэш_тай[key]

    def ключ(к):
        рм = к.результат_многоборья
        сумма = float(рм.сумма_очков) if рм and рм.сумма_очков else 0.0
        поле = _поле_тай(к.класс_судна, к.пол)
        тай = float(getattr(рм, поле) or 0) if поле and рм else 0.0
        return (сумма, тай, к.нагрудный_номер or 9999)

    return sorted(команды, key=ключ)


_МБ_ДИСЦ_MAP = {
    'Спринт':              {'заг': 'Спринт',                 'поле': 'очки_спринт'},
    'Параллельный спринт': {'заг': 'Параллельный<br>спринт', 'поле': 'очки_пс'},
    'Длинная гонка':       {'заг': 'Длинная<br>гонка',       'поле': 'очки_дг'},
}
_МБ_ПОРЯДОК = ['Спринт', 'Параллельный спринт', 'Длинная гонка']
_МБ_ЖЕНСКИЕ = ('Женщин', 'Юниорки', 'Девушки')


def _пол_вида(пол_возраст):
    return 'ж' if any(k in пол_возраст for k in _МБ_ЖЕНСКИЕ) else 'м'


def _дисц_мб_для_вида(сор, класс, пол):
    """Колонки Очки Многоборье для конкретного вида (класс судна + пол).

    Определяет дисциплины, идущие ДО Слалома в последовательности данного вида.
    Если виды_список не задан — использует фактически заполненные очки.
    """
    перед_слалом = set()
    найден_слалом = False
    try:
        виды = json.loads(сор.виды_список) if сор and сор.виды_список else []
    except (ValueError, TypeError):
        виды = []

    for вид in виды:
        if вид.get('дисциплина', '').upper() != класс.upper():
            continue
        if _пол_вида(вид.get('пол_возраст', '')) != пол:
            continue
        посл_str = вид.get('последовательность', '')
        посл = ['Спринт'] + [p.strip() for p in посл_str.split(',') if p.strip()]
        if 'Слалом' in посл:
            найден_слалом = True
            idx = посл.index('Слалом')
            for д in посл[:idx]:
                if д in _МБ_ДИСЦ_MAP:
                    перед_слалом.add(д)

    if not найден_слалом and сор:
        # виды_список не настроен — определяем по фактически заполненным очкам
        результаты = (РезультатМногоборья.query
                      .join(Команда, Команда.id == РезультатМногоборья.команда_id)
                      .filter(Команда.соревнование_id == сор.id,
                              Команда.класс_судна == класс,
                              Команда.пол == пол)
                      .all())
        if any(р.очки_спринт for р in результаты):
            перед_слалом.add('Спринт')
        if any(р.очки_пс for р in результаты):
            перед_слалом.add('Параллельный спринт')
        if any(р.очки_дг for р in результаты):
            перед_слалом.add('Длинная гонка')

    колонки = [_МБ_ДИСЦ_MAP[д] for д in _МБ_ПОРЯДОК if д in перед_слалом]
    if колонки:
        колонки.append({'заг': 'Сумма', 'поле': None})
    return колонки


def _дисц_мб_по_коду(сор):
    """Возвращает dict {вид_код: колонки} для четырёх групп."""
    return {
        'R4-м': _дисц_мб_для_вида(сор, 'R4', 'м'),
        'R4-ж': _дисц_мб_для_вида(сор, 'R4', 'ж'),
        'R6-м': _дисц_мб_для_вида(сор, 'R6', 'м'),
        'R6-ж': _дисц_мб_для_вида(сор, 'R6', 'ж'),
    }


def _get_result(к, попытка):
    return next((р for р in к.результат_слалом if р.номер_попытки == попытка), None)


def _get_or_create(к, sor_id, попытка):
    рез = _get_result(к, попытка)
    if not рез:
        рез = РезультатСлалома(
            команда_id=к.id, соревнование_id=sor_id, номер_попытки=попытка
        )
        db.session.add(рез)
        db.session.flush()
    return рез


def _суммировать_ворота(команда_id, sor_id, попытка):
    """Вернуть (кол_5, кол_50, суммарный_штраф) по воротам."""
    штрафы = ШтрафВорот.query.filter_by(
        команда_id=команда_id, соревнование_id=sor_id, номер_попытки=попытка
    ).all()
    н5  = sum(1 for ш in штрафы if ш.штраф == 5)
    н50 = sum(1 for ш in штрафы if ш.штраф == 50)
    return н5, н50, н5 * 5 + н50 * 50


def _пересчитать_попытку(рез, sor_id):
    """Обновить штрафное_время и результат_попытки из данных ворот и штрафов старта/финиша."""
    н5, н50, штраф_ворот = _суммировать_ворота(рез.команда_id, sor_id, рез.номер_попытки)
    рез.кол_штраф_5 = н5
    рез.кол_штраф_50 = н50
    штраф = штраф_ворот
    штраф += (рез.кол_штраф_с10 or 0) * 10
    штраф += (рез.кол_штраф_старт or 0) * 50
    штраф += (рез.кол_штраф_финиш or 0) * 50
    рез.штрафное_время = штраф
    if рез.время_старта is not None and рез.время_финиша is not None:
        рез.время_прохождения = рез.время_финиша - рез.время_старта
    if рез.статус_попытки in (СТАТУС_ДК, СТАТУС_ДНФ, СТАТУС_ДНС, СТАТУС_ПЛВ):
        рез.результат_попытки = None
    elif рез.время_прохождения is not None:
        рез.результат_попытки = рез.время_прохождения + рез.штрафное_время
    else:
        рез.результат_попытки = None


def _штрафы_по_команде(sor_id, пол, попытка):
    """Все штрафы ворот для пола и попытки: {команда_id: {номер_ворот: штраф}}."""
    ids = {к.id for к in Команда.query.filter_by(соревнование_id=sor_id, пол=пол).all()}
    все = ШтрафВорот.query.filter_by(соревнование_id=sor_id, номер_попытки=попытка)\
                          .filter(ШтрафВорот.команда_id.in_(ids)).all()
    result = {}
    for ш in все:
        result.setdefault(ш.команда_id, {})[ш.номер_ворот] = ш.штраф
    return result


