from models import (db, Соревнование, Команда, РезультатМногоборья,
                    ТаблицаОчков, ТаблицаРазрядов)
from нормативы import получить_норматив
from docx_utils import create_результаты_мн_docx

bp_многоборье = Blueprint('многоборье', __name__)

_МБ_ВСЕ_ДИСЦИПЛИНЫ = ('Спринт', 'Параллельный спринт', 'Слалом', 'Длинная гонка')
_МБ_ЖЕНСКИЕ = ('Женщин', 'Юниорки', 'Девушки')


def _пол_вида(пол_возраст):
    return 'ж' if any(k in пол_возраст for k in _МБ_ЖЕНСКИЕ) else 'м'


def _дисциплины_вида(сор, класс, пол):
    """Дисциплины, входящие в программу многоборья для вида (класс+пол).

    Берётся из виды_список (Спринт + позиции 2-4 последовательности).
    Если вид не настроен в виды_список (организатор не заполнял таблицу
    «Виды программы») — определяем дисциплины по фактически введённым
    результатам, как это уже делают routes/слалом.py и routes/дг.py для
    колонок «Очки Многоборье». Так соревнования без явно настроенной
    программы (например только Спринт+Слалом) не требуют результатов
    по дисциплинам, которых в этом соревновании вообще нет.
    """
    try:
        виды = json.loads(сор.виды_список) if сор and сор.виды_список else []
    except (ValueError, TypeError):
        виды = []

    for вид in виды:
        if вид.get('дисциплина', '').upper() != класс.upper():
            continue
        if _пол_вида(вид.get('пол_возраст', '')) != пол:
            continue
        посл_str = вид.get('последовательность', '')
        return ['Спринт'] + [p.strip() for p in посл_str.split(',') if p.strip()]

    if not сор:
        return list(_МБ_ВСЕ_ДИСЦИПЛИНЫ)

    результаты = (РезультатМногоборья.query
                  .join(Команда, Команда.id == РезультатМногоборья.команда_id)
                  .filter(Команда.соревнование_id == сор.id,
                          Команда.класс_судна == класс,
                          Команда.пол == пол)
                  .all())
    дисциплины = []
    if any(р.очки_спринт for р in результаты):
        дисциплины.append('Спринт')
    if any(р.очки_пс for р in результаты):
        дисциплины.append('Параллельный спринт')
    if any(р.очки_слалом for р in результаты):
        дисциплины.append('Слалом')
    if any(р.очки_дг for р in результаты):
        дисциплины.append('Длинная гонка')
    return дисциплины


def обновить_мб_очки(sor_id):
    """Пересчитать очки_* и сумма_очков в РезультатМногоборья по текущим результатам дисциплин.

    Вызывается автоматически после пересчёта любой дисциплины.
    """
    команды = Команда.query.filter_by(соревнование_id=sor_id).all()
    for к in команды:
        оч_сп, оч_пс, оч_сл, оч_дг = _очки_команды(к)
        сумма = оч_сп + оч_пс + оч_сл + оч_дг
        if сумма == 0 and not к.результат_многоборья:
            continue
        рм = к.результат_многоборья
        if not рм:
            рм = РезультатМногоборья(команда_id=к.id, соревнование_id=sor_id)
            db.session.add(рм)
        рм.очки_спринт = оч_сп
        рм.очки_пс     = оч_пс
        рм.очки_слалом = оч_сл
        рм.очки_дг     = оч_дг
        рм.сумма_очков  = сумма
    db.session.commit()


def _очки_команды(к):
    """Вернуть (оч_сп, оч_пс, оч_сл, оч_дг) для команды."""
    оч_сп = float(к.результат_спринт.очки) if к.результат_спринт else 0.0
    оч_пс = next(
        (float(р.очки) for р in к.результат_пс if р.итоговое_место is not None and р.очки),
        0.0
    )
    оч_сл = next(
        (float(р.очки) for р in к.результат_слалом if р.место is not None and р.очки),
        0.0
    )
    оч_дг = float(к.результат_дг.очки) if к.результат_дг else 0.0
    return оч_сп, оч_пс, оч_сл, оч_дг


def _имеет_все_результаты(к, дисциплины):
    """Проверить, что у команды есть результаты по всем дисциплинам её программы."""
    if not дисциплины:
        return False
    if 'Спринт' in дисциплины and not к.результат_спринт:
        return False
    if 'Длинная гонка' in дисциплины and (not к.результат_дг or к.результат_дг.место is None):
        return False
    if 'Параллельный спринт' in дисциплины and not any(
            р for р in к.результат_пс if р.итоговое_место is not None):
        return False
    if 'Слалом' in дисциплины and not any(р for р in к.результат_слалом if р.место is not None):
        return False
    return True


def _имеет_хотя_бы_один_результат(к, дисциплины):
    """Проверить, что у команды есть результат хотя бы по одной дисциплине её программы."""
    if 'Спринт' in дисциплины and к.результат_спринт:
        return True
    if 'Длинная гонка' in дисциплины and к.результат_дг and к.результат_дг.место is not None:
        return True
    if 'Параллельный спринт' in дисциплины and any(
            р for р in к.результат_пс if р.итоговое_место is not None):
        return True
    if 'Слалом' in дисциплины and any(р for р in к.результат_слалом if р.место is not None):
        return True
    return False


def _рассчитать(sor_id, пол, класс=None):
    """Рассчитать и сохранить многоборье для группы. Вернуть (записи, разряды)."""
    сор = Соревнование.query.get(sor_id)
    код = сор.код_соревнований if сор else None
    q = Команда.query.filter_by(соревнование_id=sor_id, пол=пол)
    if класс:
        q = q.filter_by(класс_судна=класс)
    команды = q.all()

    дисциплины = _дисциплины_вида(сор, класс, пол) if класс else _МБ_ВСЕ_ДИСЦИПЛИНЫ

    entries = []
    for к in команды:
        if not _имеет_хотя_бы_один_результат(к, дисциплины):
            continue
        оч_сп, оч_пс, оч_сл, оч_дг = _очки_команды(к)
        сумма = оч_сп + оч_пс + оч_сл + оч_дг

        рм = к.результат_многоборья
        if not рм:
            рм = РезультатМногоборья(команда_id=к.id, соревнование_id=sor_id)
            db.session.add(рм)

        рм.очки_спринт = оч_сп
        рм.очки_пс     = оч_пс
        рм.очки_слалом = оч_сл
        рм.очки_дг     = оч_дг
        рм.сумма_очков  = сумма
        entries.append((сумма, к, рм))

    entries.sort(key=lambda x: -x[0])
    разряды = {}

    # Официальное место и очки многоборья (используются в командном зачёте субъектов)
    # присваиваются только командам с полным комплектом результатов — промежуточные
    # команды остаются в списке для отображения текущей суммы, но без места.
    место = 1
    for _, к, рм in entries:
        if _имеет_все_результаты(к, дисциплины):
            рм.место = место
            оч = ТаблицаОчков.query.filter_by(дистанция='МНОГОБОРЬЕ', место=место).first()
            рм.очки_многоборье = оч.очки if оч else 0
            разряды[к.id] = получить_норматив(код, сор.возрастная_группа if сор else None, 'М', место)
            место += 1
        else:
            рм.место = None
            рм.очки_многоборье = 0

    db.session.commit()
    return [рм for _, _, рм in entries], разряды


@bp_многоборье.route('/<int:sor_id>/результаты')
def результаты(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    муж_р4_рез, муж_р4_разр = _рассчитать(sor_id, 'м', 'R4')
    муж_р6_рез, муж_р6_разр = _рассчитать(sor_id, 'м', 'R6')
    жен_р4_рез, жен_р4_разр = _рассчитать(sor_id, 'ж', 'R4')
    жен_р6_рез, жен_р6_разр = _рассчитать(sor_id, 'ж', 'R6')
    return render_template('многоборье/результаты.html',
                           сор=сор,
                           муж_р4_рез=муж_р4_рез, муж_р4_разр=муж_р4_разр,
                           муж_р6_рез=муж_р6_рез, муж_р6_разр=муж_р6_разр,
                           жен_р4_рез=жен_р4_рез, жен_р4_разр=жен_р4_разр,
                           жен_р6_рез=жен_р6_рез, жен_р6_разр=жен_р6_разр,
                           сегодня=date.today(),
                           готов_наград=сор.готов_наград_мб)


@bp_многоборье.route('/<int:sor_id>/протокол')
def протокол(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    кл = request.args.get('класс', 'R4')
    муж_рез, муж_разр = _рассчитать(sor_id, 'м', кл)
    жен_рез, жен_разр = _рассчитать(sor_id, 'ж', кл)
    итоговый = request.args.get('итоговый', '0') == '1'
    портрет  = request.args.get('портрет',  '1') == '1'
    return render_template('многоборье/протокол.html',
                           сор=сор,
                           муж_рез=муж_рез, муж_разр=муж_разр,
                           жен_рез=жен_рез, жен_разр=жен_разр,
                           итоговый=итоговый,
                           портрет=портрет,
                           класс=кл,
                           сегодня=date.today())


@bp_многоборье.route('/<int:sor_id>/протокол-word')
def протокол_word(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    кл      = request.args.get('класс',    'R4')
    итоговый = request.args.get('итоговый', '0') == '1'
    портрет  = request.args.get('портрет',  '1') == '1'
    муж_рез, муж_разр = _рассчитать(sor_id, 'м', кл)
    жен_рез, жен_разр = _рассчитать(sor_id, 'ж', кл)
    return create_результаты_мн_docx(
        сор, муж_рез, жен_рез, муж_разр, жен_разр, кл,
        f'протокол_мн_{кл}_{sor_id}.docx',
        итоговый=итоговый, портрет=портрет)
