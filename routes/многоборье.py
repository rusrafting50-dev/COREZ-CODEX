# routes/многоборье.py — дистанция МНОГОБОРЬЕ: сумма очков по 4 дистанциям
from datetime import date
from flask import Blueprint, render_template, request
from models import (db, Соревнование, Команда, РезультатМногоборья,
                    ТаблицаОчков, ТаблицаРазрядов)
from нормативы import получить_норматив

bp_многоборье = Blueprint('многоборье', __name__)


def _очки_команды(к):
    """Вернуть (оч_сп, оч_пс, оч_сл, оч_дг) для команды."""
    оч_сп = float(к.результат_спринт.очки) if к.результат_спринт else 0.0
    оч_пс = next(
        (float(р.очки) for р in к.результат_пс if р.итоговое_место is not None and р.очки),
        0.0
    )
    оч_сл = next(
        (float(р.очки) for р in к.результат_слалом if р.место is not None and р.очки),
        0.0
    )
    оч_дг = float(к.результат_дг.очки) if к.результат_дг else 0.0
    return оч_сп, оч_пс, оч_сл, оч_дг


def _рассчитать(sor_id, пол, класс=None):
    """Рассчитать и сохранить многоборье для группы. Вернуть (записи, разряды)."""
    сор = Соревнование.query.get(sor_id)
    код = сор.код_соревнований if сор else None
    q = Команда.query.filter_by(соревнование_id=sor_id, пол=пол)
    if класс:
        q = q.filter_by(класс_судна=класс)
    команды = q.all()

    entries = []
    for к in команды:
        оч_сп, оч_пс, оч_сл, оч_дг = _очки_команды(к)
        сумма = оч_сп + оч_пс + оч_сл + оч_дг

        рм = к.результат_многоборья
        if not рм:
            рм = РезультатМногоборья(команда_id=к.id, соревнование_id=sor_id)
            db.session.add(рм)

        рм.очки_спринт = оч_сп
        рм.очки_пс     = оч_пс
        рм.очки_слалом = оч_сл
        рм.очки_дг     = оч_дг
        рм.сумма_очков  = сумма
        entries.append((сумма, к, рм))

    entries.sort(key=lambda x: -x[0])
    разряды = {}

    for место, (_, к, рм) in enumerate(entries, 1):
        рм.место = место
        оч = ТаблицаОчков.query.filter_by(дистанция='МНОГОБОРЬЕ', место=место).first()
        рм.очки_многоборье = оч.очки if оч else 0
        разряды[к.id] = получить_норматив(код, сор.возрастная_группа if сор else None, 'М', место)

    db.session.commit()
    return [рм for _, _, рм in entries], разряды


@bp_многоборье.route('/<int:sor_id>/результаты')
def результаты(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    муж_р4_рез, муж_р4_разр = _рассчитать(sor_id, 'м', 'R4')
    муж_р6_рез, муж_р6_разр = _рассчитать(sor_id, 'м', 'R6')
    жен_р4_рез, жен_р4_разр = _рассчитать(sor_id, 'ж', 'R4')
    жен_р6_рез, жен_р6_разр = _рассчитать(sor_id, 'ж', 'R6')
    return render_template('многоборье/результаты.html',
                           сор=сор,
                           муж_р4_рез=муж_р4_рез, муж_р4_разр=муж_р4_разр,
                           муж_р6_рез=муж_р6_рез, муж_р6_разр=муж_р6_разр,
                           жен_р4_рез=жен_р4_рез, жен_р4_разр=жен_р4_разр,
                           жен_р6_рез=жен_р6_рез, жен_р6_разр=жен_р6_разр,
                           сегодня=date.today(),
                           готов_наград=сор.готов_наград_мб)


@bp_многоборье.route('/<int:sor_id>/протокол')
def протокол(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    кл = request.args.get('класс', 'R4')
    муж_рез, муж_разр = _рассчитать(sor_id, 'м', кл)
    жен_рез, жен_разр = _рассчитать(sor_id, 'ж', кл)
    итоговый = request.args.get('итоговый', '0') == '1'
    портрет  = request.args.get('портрет',  '0') == '1'
    return render_template('многоборье/протокол.html',
                           сор=сор,
                           муж_рез=муж_рез, муж_разр=муж_разр,
                           жен_рез=жен_рез, жен_разр=жен_разр,
                           итоговый=итоговый,
                           портрет=портрет,
                           класс=кл,
                           сегодня=date.today())
