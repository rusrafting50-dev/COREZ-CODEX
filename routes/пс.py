def _начальный_брак(sor_id, пол, класс=None):
    """Брак для стартового протокола. Возвращает (брак, стадии, посев_map, предв, time_records, stage_heats)."""
    посев = _посев(sor_id, пол, класс)
    n = len(посев)
    посев_map = {к.id: i + 1 for i, к in enumerate(посев)}

    if n < 2 or n not in ТАБЛИЦА_СОСТАВ:
        return {}, [], посев_map, {}, {}, {}

    стадии = _ожидаемые_стадии(n)
    все = _все_записи_пола(sor_id, пол, класс)
    брак = {ст: {} for ст in стадии}
    предв = {}
    time_records: dict = {}
    stage_heats: dict = {}
    нужен_commit = False
    состав_т = ТАБЛИЦА_СОСТАВ[n]
    стадии_т = ТАБЛИЦА_СТАДИИ[n]
    финальные = {'Финал_А', 'Финал_Б'}

    if not все:
        first_ст = стадии[0]
        уч = []
        for lh in sorted(состав_т.keys()):
            if стадии_т[lh] != first_ст or 'П' in состав_т[lh]:
                continue
            parts = состав_т[lh].split('-')
            уч.append((посев[int(parts[0]) - 1], None))
            уч.append((посев[int(parts[1]) - 1], None))
        предв[first_ст] = уч
        for lh in sorted(состав_т.keys()):
            if 'П' not in состав_т[lh]:
                continue
            ст = стадии_т[lh]
            for part in состав_т[lh].split('-'):
                team, label = _разрешить_часть_для_предв(part, посев, {}, {}, стадии_т, {})
                предв.setdefault(ст, []).append((team, label))
        return брак, стадии, посев_map, предв, {}, {}

    ids = _ids_пола(sor_id, пол, класс)
    стадии_бд = {з.стадия for з in все}
    for ст in стадии:
        if ст in стадии_бд:
            брак[ст] = _в_заезды([з for з in все if з.стадия == ст])

    позиции = _позиции_в_стадиях(n)
    по_db = _в_заезды(все)
    db_to_local, local_to_db = _построить_mapping(n, посев, все)
    existing_locals = set(local_to_db.keys())

    for ст in стадии[1:]:
        stage_recs = [з for з in все if з.стадия == ст]
        if not stage_recs and ст in финальные:
            пи = 0 if ст == 'Финал_А' else -1
            заглушка = РезультатПараллельногоСпринта(
                команда_id=посев[пи].id, соревнование_id=sor_id,
                стадия=ст, номер_заезда=0, дорожка='заглушка',
            )
            db.session.add(заглушка)
            db.session.flush()
            stage_recs = [заглушка]
            нужен_commit = True
        time_rec = next((з for з in stage_recs if з.номер_заезда == 0), None)
        if time_rec is None and stage_recs:
            time_rec = stage_recs[0]
        if time_rec:
            time_records[ст] = time_rec

    # Все производные заезды (с 'П') — всегда показываем как «ожидаемые» на стартовом протоколе
    pending_by_stage: dict = {}
    for lh in sorted(состав_т.keys()):
        if 'П' not in состав_т[lh]:
            continue
        ст = стадии_т[lh]
        if ст not in финальные:
            pending_by_stage.setdefault(ст, []).append(lh)

    # Начальные заезды (прямые посевные пары без 'П'), ещё не созданные в БД
    initial_by_stage: dict = {}
    for lh in sorted(состав_т.keys()):
        if lh in existing_locals or 'П' in состав_т[lh]:
            continue
        ст = стадии_т[lh]
        if ст not in финальные:
            initial_by_stage.setdefault(ст, []).append(lh)

    pending_уч: dict = {}
    for ст, pending_lhs in pending_by_stage.items():
        уч = []
        for lh in pending_lhs:
            comp = состав_т[lh]
            parts = comp.split('-')
            лок_уч = []
            for part in parts:
                # Передаём пустые словари, чтобы всегда получать подписи, а не фактические команды:
                # стартовый протокол не должен меняться при вводе результатов
                team, label = _разрешить_часть_для_предв(
                    part, посев, {}, {}, стадии_т, позиции)
                уч.append((team, label))
                лок_уч.append((team, label))
            pending_уч[lh] = лок_уч
        предв[ст] = уч

    # Предв для финалов (в _начальный_брак финалы исключены из pending_by_stage)
    for lh in sorted(состав_т.keys()):
        if 'П' not in состав_т[lh]:
            continue
        ст = стадии_т[lh]
        if ст not in финальные or ст in предв:
            continue
        for part in состав_т[lh].split('-'):
            team, label = _разрешить_часть_для_предв(
                part, посев, {}, {}, стадии_т, позиции)
            предв.setdefault(ст, []).append((team, label))

    # Создать заглушки для ожидаемых промежуточных и начальных заездов (для ввода времени старта)
    # Только для тех, у которых ещё нет реального заезда в БД
    незав_pending = {lh for lhs in pending_by_stage.values() for lh in lhs if lh not in existing_locals}
    для_заглушек = (
        [(ст, [lh for lh in lhs if lh in незав_pending]) for ст, lhs in pending_by_stage.items()]
        + list(initial_by_stage.items())
    )
    for ст, lhs in для_заглушек:
        if ст in финальные:
            continue
        for lh in lhs:
            exists = (РезультатПараллельногоСпринта.query
                      .filter_by(соревнование_id=sor_id, стадия=ст, номер_заезда=-lh, дорожка='заглушка')
                      .filter(РезультатПараллельногоСпринта.команда_id.in_(ids))
                      .first())
            if not exists:
                used = {з.команда_id for з in (РезультатПараллельногоСпринта.query
                        .filter_by(соревнование_id=sor_id, стадия=ст)
                        .filter(РезультатПараллельногоСпринта.команда_id.in_(ids))
                        .all())}
                кид = next((к.id for к in посев if к.id not in used), посев[0].id)
                db.session.add(РезультатПараллельногоСпринта(
                    команда_id=кид, соревнование_id=sor_id,
                    стадия=ст, номер_заезда=-lh, дорожка='заглушка',
                ))
                db.session.flush()
                нужен_commit = True

    for ст in стадии:
        if ст in финальные:
            continue
        heats_in_stage = []
        for db_num, records in брак.get(ст, {}).items():
            if db_num == 0:
                continue
            lh = db_to_local.get(db_num)
            # Только начальные заезды (без 'П') показываем как реальные
            if lh is not None and 'П' not in состав_т.get(lh, 'П'):
                heats_in_stage.append({'local': lh, 'тип': 'real', 'db': db_num, 'записи': records})
        for lh in pending_by_stage.get(ст, []):
            if lh in local_to_db:
                # Реальный заезд есть в БД — берём время из него
                rdb = local_to_db[lh]
                recs = брак.get(ст, {}).get(rdb, [])
                time_rec = recs[0] if recs else None
            else:
                time_rec = (РезультатПараллельногоСпринта.query
                            .filter_by(соревнование_id=sor_id, стадия=ст, номер_заезда=-lh, дорожка='заглушка')
                            .filter(РезультатПараллельногоСпринта.команда_id.in_(ids))
                            .first())
            heats_in_stage.append({'local': lh, 'тип': 'pending', 'уч': pending_уч.get(lh, []), 'time_rec': time_rec})
        for lh in initial_by_stage.get(ст, []):
            time_rec = (РезультатПараллельногоСпринта.query
                        .filter_by(соревнование_id=sor_id, стадия=ст, номер_заезда=-lh, дорожка='заглушка')
                        .filter(РезультатПараллельногоСпринта.команда_id.in_(ids))
                        .first())
            parts = состав_т[lh].split('-')
            уч_пара = [(посев[int(parts[0]) - 1], None), (посев[int(parts[1]) - 1], None)]
            heats_in_stage.append({'local': lh, 'тип': 'pending', 'уч': уч_пара, 'time_rec': time_rec})
        heats_in_stage.sort(key=lambda x: x['local'])
        if heats_in_stage:
            stage_heats[ст] = heats_in_stage

    if нужен_commit:
        db.session.commit()

    return брак, стадии, посев_map, предв, time_records, stage_heats


