def _начальный_брак(sor_id, пол, класс=None):
    """Брак для стартового протокола: первая стадия из БД, последующие — из начального посева.
    Возвращает (брак, стадии, посев_map, предв, time_records).
    time_records: {стадия: запись_для_поля_времени}."""
    посев = _посев(sor_id, пол, класс)
    n = len(посев)
    посев_map = {к.id: i + 1 for i, к in enumerate(посев)}

    if n < 2:
        return {}, [], посев_map, {}, {}

    стадии = _ожидаемые_стадии(n)
    все = _все_записи_пола(sor_id, пол, класс)

    if not все:
        брак = {ст: {} for ст in стадии}
        предв = {}
        first_ст = стадии[0]
        if n == 3:
            пары = [(посев[1], посев[2])]
        else:
            пары_raw = _сформировать_пары(list(посев))
            пары = [(л, п) for л, п in пары_raw if п is not None]
        уч = []
        for л, п in пары:
            уч.append((л, None))
            уч.append((п, None))
        предв[first_ст] = уч
        return брак, стадии, посев_map, предв, {}

    first_ст = стадии[0]
    first_записи = [з for з in все if з.стадия == first_ст]
    брак = {ст: {} for ст in стадии}
    брак[first_ст] = _в_заезды(first_записи)

    # BYE-команды из начального посева (только для первой последующей стадии)
    пары_initial = _сформировать_пары(list(посев))
    byes = [л for л, п in пары_initial if п is None]

    предв = {}
    time_records = {}  # стадия -> запись БД для поля времени старта
    нужен_commit = False

    for i, ст in enumerate(стадии):
        if i == 0:
            continue

        # Ищем запись для поля времени: сначала BYE (номер=0), затем любую
        stage_recs = [з for з in все if з.стадия == ст]

        # Финальная стадия без записей — создаём заглушку «на лету»
        if not stage_recs and ст in ('Финал_А', 'Финал_Б'):
            посев_idx = 0 if ст == 'Финал_А' else -1
            заглушка = РезультатПараллельногоСпринта(
                команда_id=посев[посев_idx].id,
                соревнование_id=sor_id,
                стадия=ст,
                номер_заезда=0,
                дорожка='заглушка',
            )
            db.session.add(заглушка)
            db.session.flush()
            stage_recs = [заглушка]
            нужен_commit = True

        time_rec = next((з for з in stage_recs if з.номер_заезда == 0), None)
        if time_rec is None and stage_recs:
            time_rec = stage_recs[0]
        if time_rec:
            time_records[ст] = time_rec

        # Строим предв из начального посева.
        # Финал А: участники приходят из ½ финала, а не из Финал Б —
        # поэтому пропускаем Финал_Б при поиске предыдущей стадии.
        пред_ст = стадии[i - 1]
        if ст == 'Финал_А' and пред_ст == 'Финал_Б' and i >= 2:
            пред_ст = стадии[i - 2]
        пред_данные = брак.get(пред_ст, {})
        реальных = sorted(р for р in пред_данные if р != 0)
        назв_пред = НАЗВАНИЯ.get(пред_ст, пред_ст)
        уч = []

        if ст == 'Финал_Б':
            for j, _ in enumerate(реальных, 1):
                уч.append((None, f'Проигравший заезда {j}, {назв_пред}'))
        else:
            this_byes = byes if i == 1 else []
            for к in this_byes:
                уч.append((к, None))
            for j, _ in enumerate(реальных, 1):
                уч.append((None, f'Победитель заезда {j}, {назв_пред}'))

        предв[ст] = уч

    if нужен_commit:
        db.session.commit()

    return брак, стадии, посев_map, предв, time_records


