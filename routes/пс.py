def _стадии_по_командам(sor_id, пол):
    """Dict {команда_id: {стадия: запись}} excluding BYE entries."""
    все = _все_записи_пола(sor_id, пол)
    result = {}
    for з in все:
        if з.дорожка == 'бай':
            continue
        result.setdefault(з.команда_id, {})[з.стадия] = з
    return result


