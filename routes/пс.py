def _в_заезды(записи):
    """Группировать записи по номеру заезда → dict {номер: [left, right]}."""
    по_заезду = {}
    for з in записи:
        по_заезду.setdefault(з.номер_заезда, []).append(з)
    result = {}
    for номер in sorted(по_заезду.keys()):
        пара = sorted(по_заезду[номер],
                      key=lambda z: 0 if z.дорожка == 'левая' else (1 if z.дорожка == 'правая' else 2))
        result[номер] = пара
    return result


def _стадии_в_бд(sor_id, пол):
    return {з.стадия for з in _все_записи_пола(sor_id, пол)}


def _позиции_в_стадиях(n):
    """Для каждого локального номера заезда — его 1-based позиция внутри стадии."""
    стадии_т = ТАБЛИЦА_СТАДИИ.get(n, {})
    by_stage = {}
    for lh in sorted(стадии_т.keys()):
        by_stage.setdefault(стадии_т[lh], []).append(lh)
    pos = {}
    for heats in by_stage.values():
        for i, lh in enumerate(heats, 1):
            pos[lh] = i
    return pos


def _построить_mapping(n, посев, все):
    """Строит {db_num→local_num} и {local_num→db_num} по совпадению посевных пар."""
    if n not in ТАБЛИЦА_СОСТАВ:
        return {}, {}
    состав = ТАБЛИЦА_СОСТАВ[n]
    посев_map = {к.id: i + 1 for i, к in enumerate(посев)}
    по_db = _в_заезды(все)
    db_to_local: dict = {}
    local_to_db: dict = {}

    # Проход 1: сопоставить начальные заезды по посевным номерам
    for db_num in sorted(по_db.keys()):
        if db_num == 0:
            continue
        пара = по_db[db_num]
        seeds = {посев_map.get(з.команда_id) for з in пара if з.дорожка not in ('заглушка', 'бай')}
        seeds.discard(None)
        if len(seeds) != 2:
            continue
        s1, s2 = sorted(seeds)
        for lh, comp in состав.items():
            if lh in local_to_db or 'П' in comp:
                continue
            parts = comp.split('-')
            cs = sorted(int(x) for x in parts)
            if cs == [s1, s2]:
                db_to_local[db_num] = lh
                local_to_db[lh] = db_num
                break

    # Проход 2: итеративно сопоставить производные заезды
    changed = True
    while changed:
        changed = False
        for lh, comp in sorted(состав.items()):
            if lh in local_to_db or 'П' not in comp:
                continue
            parts = comp.split('-')

            def _resolve_id(part):
                if part.startswith('ПБ'):
                    ref = int(part[2:])
                    rdb = local_to_db.get(ref)
                    if rdb is None:
                        return None
                    return next((з.команда_id for з in по_db.get(rdb, [])
                                 if з.победитель is True and з.дорожка != 'заглушка'), None)
                elif part.startswith('ПР'):
                    ref = int(part[2:])
                    rdb = local_to_db.get(ref)
                    if rdb is None:
                        return None
                    return next((з.команда_id for з in по_db.get(rdb, [])
                                 if з.победитель is False), None)
                else:
                    s = int(part)
                    return посев[s - 1].id if s <= len(посев) else None

            t1_id = _resolve_id(parts[0])
            t2_id = _resolve_id(parts[1])
            if t1_id is None or t2_id is None:
                continue
            expected = {t1_id, t2_id}
            for db_num in sorted(по_db.keys()):
                if db_num == 0 or db_num in db_to_local:
                    continue
                actual = {з.команда_id for з in по_db[db_num]
                          if з.дорожка not in ('заглушка', 'бай')}
                if actual == expected:
                    db_to_local[db_num] = lh
                    local_to_db[lh] = db_num
                    changed = True
                    break

    # Проход 3: позиционный фолбэк для заездов, которые не удалось сопоставить по составу.
    # Внутри каждой стадии начальные заезды (без 'П') всегда создаются раньше производных,
    # поэтому имеют меньшие номера в БД. Это позволяет восстановить соответствие по позиции.
    стадии_т = ТАБЛИЦА_СТАДИИ.get(n, {})
    по_стадии_несопост: dict = {}  # стадия → sorted list of unmapped positive db_nums
    for з in все:
        if з.дорожка in ('заглушка', 'бай') or з.номер_заезда <= 0:
            continue
        if з.номер_заезда not in db_to_local:
            по_стадии_несопост.setdefault(з.стадия, set()).add(з.номер_заезда)
    for стадия, несопост_db in по_стадии_несопост.items():
        нач_lhs = sorted(lh for lh, comp in состав.items()
                         if стадии_т.get(lh) == стадия and lh not in local_to_db and 'П' not in comp)
        пр_lhs = sorted(lh for lh, comp in состав.items()
                        if стадии_т.get(lh) == стадия and lh not in local_to_db and 'П' in comp)
        remaining_lhs = нач_lhs + пр_lhs
        for db_num, lh in zip(sorted(несопост_db), remaining_lhs):
            db_to_local[db_num] = lh
            local_to_db[lh] = db_num

    return db_to_local, local_to_db


def _разрешить_часть_для_предв(part, посев, local_to_db, по_db, стадии_т, позиции):
    """Возвращает (команда, None) если участник известен, иначе (None, метка)."""
    if part.startswith('ПБ'):
        ref_lh = int(part[2:])
        j = ref_lh
        назв = НАЗВАНИЯ.get(стадии_т.get(ref_lh, ''), стадии_т.get(ref_lh, ''))
        rdb = local_to_db.get(ref_lh)
        if rdb is not None:
            w = next((з.команда for з in по_db.get(rdb, [])
                      if з.победитель is True and з.дорожка != 'заглушка'), None)
            if w:
                return w, None
        return None, f'Победитель заезда {j}, {назв}'
    elif part.startswith('ПР'):
        ref_lh = int(part[2:])
        j = ref_lh
        назв = НАЗВАНИЯ.get(стадии_т.get(ref_lh, ''), стадии_т.get(ref_lh, ''))
        rdb = local_to_db.get(ref_lh)
        if rdb is not None:
            l = next((з.команда for з in по_db.get(rdb, [])
                      if з.победитель is False), None)
            if l:
                return l, None
        return None, f'Проигравший заезда {j}, {назв}'
    else:
        s = int(part)
        team = посев[s - 1] if s <= len(посев) else None
        return team, None


def _создать_возможные_заезды(sor_id, пол, класс=None):
    """Создать все заезды, участники которых уже определены (по таблице Excel)."""
    посев = _посев(sor_id, пол, класс)
    n = len(посев)
    if n < 2 or n not in ТАБЛИЦА_СОСТАВ:
        return False
    все = _все_записи_пола(sor_id, пол, класс)
    if not все:
        return False
    состав = ТАБЛИЦА_СОСТАВ[n]
    стадии_т = ТАБЛИЦА_СТАДИИ[n]
    ids = _ids_пола(sor_id, пол, класс)
    позиции = _позиции_в_стадиях(n)
    db_to_local, local_to_db = _построить_mapping(n, посев, все)
    if not local_to_db:
        return False  # не удалось сопоставить — старые данные, откат к прежней логике
    по_db = _в_заезды(все)
    existing_locals = set(local_to_db.keys())
    created = False
    for lh in sorted(состав.keys()):
        if lh in existing_locals:
            continue
        comp = состав[lh]
        if 'П' not in comp:
            continue  # начальные заезды уже созданы
        ст = стадии_т[lh]
        parts = comp.split('-')
        t1, _ = _разрешить_часть_для_предв(parts[0], посев, local_to_db, по_db, стадии_т, позиции)
        t2, _ = _разрешить_часть_для_предв(parts[1], посев, local_to_db, по_db, стадии_т, позиции)
        if t1 is None or t2 is None:
            continue
        # Сохранить время заглушки и удалить её
        saved_time = None
        # Сначала ищем заглушку конкретного ожидаемого заезда (номер_заезда = -lh)
        загл = (РезультатПараллельногоСпринта.query
                .filter_by(соревнование_id=sor_id, стадия=ст, номер_заезда=-lh, дорожка='заглушка')
                .filter(РезультатПараллельногоСпринта.команда_id.in_(ids))
                .all())
        if not загл:
            # Запасная: заглушка финальной стадии (номер_заезда = 0)
            загл = (РезультатПараллельногоСпринта.query
                    .filter_by(соревнование_id=sor_id, стадия=ст, номер_заезда=0, дорожка='заглушка')
                    .filter(РезультатПараллельногоСпринта.команда_id.in_(ids))
                    .all())
        if загл:
            saved_time = загл[0].время_старта
            for з in загл:
                db.session.delete(з)
            db.session.flush()
        _добавить_заезды(sor_id, ст, [(t1, t2)], пол)
        if saved_time:
            db.session.flush()
            for rec in (РезультатПараллельногоСпринта.query
                        .filter_by(соревнование_id=sor_id, стадия=ст)
                        .filter(РезультатПараллельногоСпринта.команда_id.in_(ids)).all()):
                if rec.номер_заезда > 0:
                    rec.время_старта = saved_time
        # Обновить маппинг
        все = _все_записи_пола(sor_id, пол, класс)
        по_db = _в_заезды(все)
        db_to_local, local_to_db = _построить_mapping(n, посев, все)
        existing_locals = set(local_to_db.keys())
        created = True
    if created:
        db.session.commit()
    return created


def _добавить_заезды(sor_id, стадия, пары, пол):
    """
    пары: list of (left_команда, right_команда | None)
    None = bye for left_команда
    Нумерация — независимая для каждого пола, сквозная через все стадии.
    race_num = (кол-во уже созданных заездов этого пола) + 1
    """
    db.session.flush()
    кол = (db.session.query(
               db.func.count(db.func.distinct(РезультатПараллельногоСпринта.номер_заезда)))
           .join(Команда, РезультатПараллельногоСпринта.команда_id == Команда.id)
           .filter(РезультатПараллельногоСпринта.соревнование_id == sor_id,
                   Команда.пол == пол,
                   РезультатПараллельногоСпринта.номер_заезда > 0)
           .scalar()) or 0
    race_num = кол + 1
    for кл, кп in пары:
        if кп is None:
            db.session.add(РезультатПараллельногоСпринта(
                команда_id=кл.id, соревнование_id=sor_id,
                стадия=стадия, номер_заезда=0, дорожка='бай',
                победитель=True,
            ))
        else:
            for дор, к in [('левая', кл), ('правая', кп)]:
                db.session.add(РезультатПараллельногоСпринта(
                    команда_id=к.id, соревнование_id=sor_id,
                    стадия=стадия, номер_заезда=race_num, дорожка=дор,
                    статус=СТАТУС_ФИНИШ,
                ))
            race_num += 1


def _сформировать_пары(seeded):
    """Стандартное разбиение на пары: seed1 vs seedN, seed2 vs seedN-1, ...
    Для нечётных: топ-посев получает бай."""
    n = len(seeded)
    пары = []
    if n % 2 == 1:
        пары.append((seeded[0], None))  # бай для первого посева
        seeded = seeded[1:]
        n = len(seeded)
    for i in range(n // 2):
        пары.append((seeded[i], seeded[n - 1 - i]))
    return пары


def _формировать_начало(sor_id, пол, класс=None):
    """Сформировать начальные заезды сетки по таблице Excel."""
    seeded = _посев(sor_id, пол, класс)
    n = len(seeded)
    if n < 2:
        return False

    ids = _ids_пола(sor_id, пол, класс)

    if n not in ТАБЛИЦА_СОСТАВ:
        РезультатПараллельногоСпринта.query \
            .filter_by(соревнование_id=sor_id) \
            .filter(РезультатПараллельногоСпринта.команда_id.in_(ids)) \
            .delete(synchronize_session='fetch')
        return False

    состав = ТАБЛИЦА_СОСТАВ[n]
    стадии_т = ТАБЛИЦА_СТАДИИ[n]

    # Сохранить время старта из заглушек начальных заездов перед удалением
    saved_times = {}  # lh → время_старта
    for lh, comp in состав.items():
        if 'П' in comp:
            continue
        ст = стадии_т[lh]
        загл = (РезультатПараллельногоСпринта.query
                .filter_by(соревнование_id=sor_id, стадия=ст, номер_заезда=-lh, дорожка='заглушка')
                .filter(РезультатПараллельногоСпринта.команда_id.in_(ids))
                .first())
        if загл and загл.время_старта:
            saved_times[lh] = загл.время_старта

    РезультатПараллельногоСпринта.query \
        .filter_by(соревнование_id=sor_id) \
        .filter(РезультатПараллельногоСпринта.команда_id.in_(ids)) \
        .delete(synchronize_session='fetch')

    # Создать начальные заезды (прямые посевные пары: нет «П» в составе)
    for lh in sorted(состав.keys()):
        comp = состав[lh]
        if 'П' in comp:
            continue
        ст = стадии_т[lh]
        parts = comp.split('-')
        s1, s2 = int(parts[0]), int(parts[1])
        _добавить_заезды(sor_id, ст, [(seeded[s1 - 1], seeded[s2 - 1])], пол)
        # Восстановить сохранённое время старта в только что созданных записях
        if lh in saved_times:
            db.session.flush()
            все_ст = (РезультатПараллельногоСпринта.query
                      .filter_by(соревнование_id=sor_id, стадия=ст)
                      .filter(РезультатПараллельногоСпринта.команда_id.in_(ids))
                      .all())
            max_rn = max((r.номер_заезда for r in все_ст if r.номер_заезда > 0), default=None)
            if max_rn:
                for r in все_ст:
                    if r.номер_заезда == max_rn:
                        r.время_старта = saved_times[lh]

    # Заглушки для финалов (для ввода времени старта заранее)
    for ст_ф, пи in [('Финал_А', 0), ('Финал_Б', -1)]:
        if any(v == ст_ф for v in стадии_т.values()):
            db.session.add(РезультатПараллельногоСпринта(
                команда_id=seeded[пи].id, соревнование_id=sor_id,
                стадия=ст_ф, номер_заезда=0, дорожка='заглушка',
            ))

    db.session.commit()
    return True


def _победители_стадии(sor_id, пол, стадия, класс=None):
    """Определить победителей/проигравших заездов стадии.
    Обновить поля победитель. Вернуть (winners, losers) отсортированные по результату."""
    записи = _записи_стадии(sor_id, пол, стадия, класс)
    по_заезду = _в_заезды(записи)

    победители = []
    проигравшие = []

    for номер, пара in по_заезду.items():
        # Бай
        if len(пара) == 1 and пара[0].дорожка == 'бай':
            победители.append(пара[0])
            continue

        valid = [(з, з.результат) for з in пара if з.результат is not None]
        dsq = [з for з in пара if з.статус in (СТАТУС_ДК, СТАТУС_ДНФ, СТАТУС_ДНС)]

        if len(valid) == 2:
            сорт = sorted(valid, key=lambda x: x[1])
            сорт[0][0].победитель = True
            сорт[1][0].победитель = False
            победители.append(сорт[0][0])
            проигравшие.append(сорт[1][0])
        elif len(valid) == 1:
            valid[0][0].победитель = True
            победители.append(valid[0][0])
            if dsq:
                dsq[0].победитель = False
                проигравшие.append(dsq[0])

    def сорт_кл(з):
        return з.результат if з.результат is not None else float('inf')

    победители.sort(key=сорт_кл)
    проигравшие.sort(key=сорт_кл)
    return победители, проигравшие


def _перейти_к_следующей(sor_id, пол, стадия, класс=None):
    """Рассчитать победителей стадии и сформировать следующую."""
    победители, проигравшие = _победители_стадии(sor_id, пол, стадия, класс)
    db.session.commit()

    посев = _посев(sor_id, пол, класс)
    n = len(посев)
    if n in ТАБЛИЦА_СОСТАВ:
        _создать_возможные_заезды(sor_id, пол, класс)

    db.session.commit()
    return True


def _рассчитать_итоговые(sor_id, пол, класс=None):
    """Присвоить итоговые места и очки. Вернуть список записей с местами."""
    все = _все_записи_пола(sor_id, пол, класс)
    if not все:
        return []

    # Сбросить предыдущие результаты
    for з in все:
        з.итоговое_место = None
        з.очки = 0

    # Финальные стадии не имеют следующего этапа, победитель не выставляется
    # автоматически — вычислить здесь
    стадии_бд = {з.стадия for з in все}
    for стадия_ф in ('Финал_А', 'Финал_Б'):
        if стадия_ф in стадии_бд:
            _победители_стадии(sor_id, пол, стадия_ф, класс)

    # Для каждой команды найти запись из последней стадии.
    # Финал_Б БАЙ (единственный проигравший 1/2 при 3 командах) пропускаем —
    # такая команда получит место через start_places['1/2'].
    индекс_ст = {ст: i for i, ст in enumerate(ПОРЯДОК_СТАДИЙ)}
    последняя = {}
    for з in все:
        if з.стадия == 'Финал_Б' and з.дорожка == 'бай':
            continue
        cid = з.команда_id
        prev = последняя.get(cid)
        if prev is None or индекс_ст.get(з.стадия, -1) > индекс_ст.get(prev.стадия, -1):
            последняя[cid] = з

    # Финал А
    for з in последняя.values():
        if з.стадия == 'Финал_А' and з.победитель is not None:
            з.итоговое_место = 1 if з.победитель else 2

    # Финал Б
    for з in последняя.values():
        if з.стадия == 'Финал_Б' and з.победитель is not None:
            з.итоговое_место = 3 if з.победитель else 4

    # Проигравшие в промежуточных стадиях → места по стадии
    start_places = {'1/2': 3, '1/4': 5, '1/8': 9}
    по_стадии = {}
    for з in последняя.values():
        if з.итоговое_место is None and з.победитель is False:
            по_стадии.setdefault(з.стадия, []).append(з)

    for стадия, лузеры in по_стадии.items():
        start = start_places.get(стадия)
        if start is None:
            continue
        лузеры.sort(key=lambda з: (з.результат is None, з.результат or float('inf')))
        for i, з in enumerate(лузеры):
            з.итоговое_место = start + i

    # Защита: место не может превышать число реальных участников
    n_участников = len(последняя)
    for з in последняя.values():
        if з.итоговое_место is not None and з.итоговое_место > n_участников:
            з.итоговое_место = None

    # ДК в любом заезде → команда места не получает; остальные места сдвигаются вверх
    дк_команды = {з.команда_id for з in все if з.статус == СТАТУС_ДК}
    for cid in дк_команды:
        if cid in последняя:
            последняя[cid].итоговое_место = None
    if дк_команды:
        размещённые = sorted(
            (з for з in последняя.values() if з.итоговое_место is not None),
            key=lambda з: з.итоговое_место,
        )
        for i, з in enumerate(размещённые, 1):
            з.итоговое_место = i

    db.session.commit()

    # Очки
    с_местом = [з for з in последняя.values() if з.итоговое_место]
    for з in с_местом:
        оч = ТаблицаОчков.query.filter_by(
            дистанция='ПАРАЛЛЕЛЬНЫЙ_СПРИНТ', место=з.итоговое_место).first()
        з.очки = оч.очки if оч else 0

    db.session.commit()
    from routes.многоборье import обновить_мб_очки
    обновить_мб_очки(sor_id)
    с_местом.sort(key=lambda з: з.итоговое_место)

    # ДК-команды добавляем в конец списка (для отображения на странице Результаты)
    # Берём запись с наибольшей стадией где стоит ДК
    дк_отображение = {}
    for з in все:
        if з.статус == СТАТУС_ДК:
            cid = з.команда_id
            prev = дк_отображение.get(cid)
            if prev is None or индекс_ст.get(з.стадия, -1) > индекс_ст.get(prev.стадия, -1):
                дк_отображение[cid] = з
    дк_записи = sorted(дк_отображение.values(), key=lambda з: з.команда_id)
    return с_местом + дк_записи


