ПОРЯДОК_СТАДИЙ = ['1/8', '1/4', '1/2', 'Финал_А', 'Финал_Б']
СЛЕДУЮЩАЯ = {'1/8': '1/4', '1/4': '1/2', '1/2': 'Финал_А'}
