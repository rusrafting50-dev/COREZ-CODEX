@bp_пс.route('/<int:sor_id>/сетка', methods=['GET', 'POST'])
def сетка(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)

    if request.method == 'POST':
        пол = request.form.get('пол', 'м')
        ok = _формировать_начало(sor_id, пол)
        if ok:
            пол_слово = 'мужских' if пол == 'м' else 'женских'
            flash(f'Сетка {пол_слово} экипажей сформирована по посеву Спринта.', 'success')
        else:
            flash('Недостаточно команд (нужно ≥ 2) для формирования сетки.', 'warning')
        return redirect(url_for('пс.сетка', sor_id=sor_id))

    муж_брак, муж_стадии, муж_посев = _брак_данные(sor_id, 'м')
    жен_брак, жен_стадии, жен_посев = _брак_данные(sor_id, 'ж')
    n_муж = len(_посев(sor_id, 'м'))
    n_жен = len(_посев(sor_id, 'ж'))

    return render_template('пс/сетка.html',
                           сор=сор,
                           муж_брак=муж_брак, муж_стадии=муж_стадии, муж_посев=муж_посев,
                           жен_брак=жен_брак, жен_стадии=жен_стадии, жен_посев=жен_посев,
                           n_муж=n_муж, n_жен=n_жен,
                           НАЗВАНИЯ=НАЗВАНИЯ,
                           format_dur=_format_dur)


@bp_пс.route('/<int:sor_id>/заезды', methods=['GET', 'POST'])
def заезды(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)

    if request.method == 'POST':
        # Сохранить результаты заездов
        все = (РезультатПараллельногоСпринта.query
               .filter_by(соревнование_id=sor_id).all())

        for з in все:
            if з.дорожка == 'бай':
                continue
            if f'вр_{з.id}' not in request.form:
                continue
            вр = _parse_dur(request.form.get(f'вр_{з.id}', ''))
            ш50 = _int0(request.form.get(f'ш50_{з.id}', 0))
            ст = request.form.get(f'ст_{з.id}', СТАТУС_ФИНИШ)
            if ст not in (СТАТУС_ФИНИШ, СТАТУС_ДК, СТАТУС_ДНФ, СТАТУС_ДНС):
                ст = СТАТУС_ФИНИШ
            з.время = вр
            з.штрафное_время = ш50 * 50
            з.статус = ст
            if вр is not None and ст == СТАТУС_ФИНИШ:
                з.результат = вр + з.штрафное_время
            else:
                з.результат = None

        db.session.commit()
        flash('Результаты заездов сохранены.', 'success')
        return redirect(url_for('пс.заезды', sor_id=sor_id))

    # GET
    def _данные(пол):
        все = _все_записи_пола(sor_id, пол)
        стадии_бд = {з.стадия for з in все}
        стадии = [ст for ст in ПОРЯДОК_СТАДИЙ if ст in стадии_бд]
        данные = {}
        завершены = {}
        for ст in стадии:
            записи = [з for з in все if з.стадия == ст]
            данные[ст] = _в_заезды(записи)
            # Стадия завершена если все реальные заезды имеют результат или дисквалификацию
            реальные = [з for з in записи if з.дорожка != 'бай']
            завершены[ст] = bool(реальные) and all(
                з.результат is not None or з.статус in (СТАТУС_ДК, СТАТУС_ДНФ, СТАТУС_ДНС)
                for з in реальные
            )
        return стадии, данные, завершены

    муж_стадии, муж_данные, муж_завершены = _данные('м')
    жен_стадии, жен_данные, жен_завершены = _данные('ж')

    return render_template('пс/заезды.html',
                           сор=сор,
                           муж_стадии=муж_стадии, муж_данные=муж_данные, муж_завершены=муж_завершены,
                           жен_стадии=жен_стадии, жен_данные=жен_данные, жен_завершены=жен_завершены,
                           НАЗВАНИЯ=НАЗВАНИЯ,
                           ПОРЯДОК_СТАДИЙ=ПОРЯДОК_СТАДИЙ,
                           СЛЕДУЮЩАЯ=СЛЕДУЮЩАЯ,
                           СТАТУС_ФИНИШ=СТАТУС_ФИНИШ,
                           СТАТУС_ДК=СТАТУС_ДК,
                           format_dur=_format_dur)


@bp_пс.route('/<int:sor_id>/перейти', methods=['POST'])
def перейти(sor_id):
    Соревнование.query.get_or_404(sor_id)
    стадия = request.form.get('стадия', '')
    пол = request.form.get('пол', 'м')
    if стадия in ПОРЯДОК_СТАДИЙ:
        ok = _перейти_к_следующей(sor_id, пол, стадия)
        if ok:
            flash('Следующий этап сформирован.', 'success')
        else:
            flash('Не удалось сформировать следующий этап.', 'warning')
    return redirect(url_for('пс.заезды', sor_id=sor_id))


