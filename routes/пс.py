def _ожидаемые_стадии(n):
    """Все стадии турнира для n команд (в порядке ПОРЯДОК_СТАДИЙ)."""
    if n < 2 or n not in ТАБЛИЦА_СТАДИИ:
        return []
    использованные = set(ТАБЛИЦА_СТАДИИ[n].values())
    return [ст for ст in ПОРЯДОК_СТАДИЙ if ст in использованные]


def _брак_данные(sor_id, пол, класс=None):
    """Данные сетки для отображения (включая будущие пустые стадии)."""
    посев = _посев(sor_id, пол, класс)
    n = len(посев)
    посев_map = {к.id: i + 1 for i, к in enumerate(посев)}

    if n < 2 or n not in ТАБЛИЦА_СОСТАВ:
        return {}, [], посев_map, {}, {}

    стадии = _ожидаемые_стадии(n)
    все = _все_записи_пола(sor_id, пол, класс)
    брак = {ст: {} for ст in стадии}
    предв = {}
    stage_heats: dict = {}
    состав_т = ТАБЛИЦА_СОСТАВ[n]
    стадии_т = ТАБЛИЦА_СТАДИИ[n]
    финальные = {'Финал_А', 'Финал_Б'}

    if not все:
        first_ст = стадии[0]
        уч = []
        for lh in sorted(состав_т.keys()):
            if стадии_т[lh] != first_ст or 'П' in состав_т[lh]:
                continue
            parts = состав_т[lh].split('-')
            уч.append((посев[int(parts[0]) - 1], None))
            уч.append((посев[int(parts[1]) - 1], None))
        предв[first_ст] = уч
        for lh in sorted(состав_т.keys()):
            if 'П' not in состав_т[lh]:
                continue
            ст = стадии_т[lh]
            for part in состав_т[lh].split('-'):
                team, label = _разрешить_часть_для_предв(part, посев, {}, {}, стадии_т, {})
                предв.setdefault(ст, []).append((team, label))
        return брак, стадии, посев_map, предв, {}

    стадии_бд = {з.стадия for з in все}
    for ст in стадии:
        if ст in стадии_бд:
            брак[ст] = _в_заезды([з for з in все if з.стадия == ст])

    позиции = _позиции_в_стадиях(n)
    по_db = _в_заезды(все)
    db_to_local, local_to_db = _построить_mapping(n, посев, все)
    existing_locals = set(local_to_db.keys())

    pending_by_stage: dict = {}
    for lh in sorted(состав_т.keys()):
        if lh in existing_locals or 'П' not in состав_т[lh]:
            continue
        ст = стадии_т[lh]
        pending_by_stage.setdefault(ст, []).append(lh)

    # Начальные заезды (прямые посевные пары без 'П'), ещё не созданные в БД
    initial_by_stage: dict = {}
    for lh in sorted(состав_т.keys()):
        if lh in existing_locals or 'П' in состав_т[lh]:
            continue
        ст = стадии_т[lh]
        if ст not in финальные:
            initial_by_stage.setdefault(ст, []).append(lh)

    pending_уч: dict = {}
    for ст, pending_lhs in pending_by_stage.items():
        уч = []
        for lh in pending_lhs:
            comp = состав_т[lh]
            parts = comp.split('-')
            лок_уч = []
            for part in parts:
                team, label = _разрешить_часть_для_предв(
                    part, посев, local_to_db, по_db, стадии_т, позиции)
                уч.append((team, label))
                лок_уч.append((team, label))
            pending_уч[lh] = лок_уч
        предв[ст] = уч

    for ст in стадии:
        if ст in финальные:
            continue
        heats_in_stage = []
        for db_num, records in брак.get(ст, {}).items():
            if db_num == 0:
                continue
            lh = db_to_local.get(db_num)
            if lh is not None:
                heats_in_stage.append({'local': lh, 'тип': 'real', 'db': db_num, 'записи': records})
        for lh in pending_by_stage.get(ст, []):
            heats_in_stage.append({'local': lh, 'тип': 'pending', 'уч': pending_уч.get(lh, []), 'time_rec': None})
        for lh in initial_by_stage.get(ст, []):
            parts = состав_т[lh].split('-')
            уч_пара = [(посев[int(parts[0]) - 1], None), (посев[int(parts[1]) - 1], None)]
            heats_in_stage.append({'local': lh, 'тип': 'pending', 'уч': уч_пара, 'time_rec': None})
        heats_in_stage.sort(key=lambda x: x['local'])
        if heats_in_stage:
            stage_heats[ст] = heats_in_stage

    return брак, стадии, посев_map, предв, stage_heats


def _метки_записей(sor_id, пол, класс=None):
    """Метка для каждой записи — точно как столбец «Стадия, место» на странице Результаты заездов."""
    все = _все_записи_пола(sor_id, пол, класс)
    СЛЕД = {'1/16': '1/8', '1/8': '1/4', '1/4': '1/2', '1/2': 'Финал_А'}
    реальных_12 = len({з.номер_заезда for з in все if з.стадия == '1/2' and з.номер_заезда > 0})
    метки = {}
    start_places = {'1/4': 5, '1/8': 9, '1/16': 17}
    по_стадии_лузеры: dict = {}

    for з in все:
        if з.дорожка in ('бай', 'заглушка'):
            continue
        if з.победитель is True:
            if з.стадия in ('1/16', '1/8', '1/4', '1/2'):
                след = СЛЕД.get(з.стадия, '')
                метки[з.id] = '→ ' + НАЗВАНИЯ.get(след, след)
            elif з.стадия == 'Финал_А':
                метки[з.id] = '1 место'
            elif з.стадия == 'Финал_Б':
                метки[з.id] = '3 место'
        elif з.победитель is False:
            if з.стадия == '1/2' and реальных_12 == 1:
                метки[з.id] = '3 место'
            elif з.стадия == '1/2':
                метки[з.id] = '→ Финал Б'
            elif з.стадия == 'Финал_А':
                метки[з.id] = '2 место'
            elif з.стадия == 'Финал_Б':
                метки[з.id] = '4 место'
            elif з.стадия in start_places:
                по_стадии_лузеры.setdefault(з.стадия, []).append(з)

    # Назначить места проигравшим в промежуточных стадиях по результату (меньше = лучше)
    for стадия, лузеры in по_стадии_лузеры.items():
        лузеры.sort(key=lambda з: (з.результат is None, з.результат or float('inf')))
        start = start_places[стадия]
        for i, з in enumerate(лузеры):
            метки[з.id] = f'{start + i} место'

    return метки


