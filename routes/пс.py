def _фио_инициалы(фио):
    if not фио:
        return ''
    p = фио.split()
    if len(p) >= 3:
        return f'{p[0]} {p[1][0]}.{p[2][0]}.'
    if len(p) == 2:
        return f'{p[0]} {p[1][0]}.'
    return фио

def _судья_строка(судья):
    if not судья:
        return ''
    части = [_фио_инициалы(судья.фамилия_имя_отчество)]
    if судья.квалификация:
        части.append(судья.квалификация)
    if судья.субъект_рф:
        части.append(судья.субъект_рф)
    return ', '.join(части)

def _судьи_ход_пс(сор, sor_id):
    судья_старта = сор.старший_судья_старта_пс or _судья_строка(_судья_должность(sor_id, 'старта'))
