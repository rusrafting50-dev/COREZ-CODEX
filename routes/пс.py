def _посев(sor_id, пол, класс=None):
    """Команды по посевному месту (место спринта → результат спринта → нагрудный номер)."""
    q = Команда.query.filter_by(соревнование_id=sor_id, пол=пол)
    if класс:
        q = q.filter_by(класс_судна=класс)
    команды = q.all()
    def ключ(к):
        рез = к.результат_спринт
        if рез and рез.место:
            return (0, рез.место, 0.0)
        if рез and рез.результат:
            return (1, 0, рез.результат)
        return (2, 0, float(к.нагрудный_номер or 9999))
    return sorted(команды, key=ключ)


def _первая_стадия(n):
    if n <= 2:   return 'Финал_А'
    if n <= 4:   return '1/2'
    if n <= 8:   return '1/4'
    if n <= 16:  return '1/8'
    return '1/16'


def _ids_пола(sor_id, пол, класс=None):
    q = Команда.query.filter_by(соревнование_id=sor_id, пол=пол)
    if класс:
        q = q.filter_by(класс_судна=класс)
    return {к.id for к in q.all()}


def _все_записи_пола(sor_id, пол, класс=None):
    ids = _ids_пола(sor_id, пол, класс)
    if not ids:
        return []
    return (РезультатПараллельногоСпринта.query
            .filter_by(соревнование_id=sor_id)
            .filter(РезультатПараллельногоСпринта.команда_id.in_(ids))
            .all())


def _записи_стадии(sor_id, пол, стадия, класс=None):
    ids = _ids_пола(sor_id, пол, класс)
    if not ids:
        return []
    return (РезультатПараллельногоСпринта.query
            .filter_by(соревнование_id=sor_id, стадия=стадия)
            .filter(РезультатПараллельногоСпринта.команда_id.in_(ids))
            .order_by(РезультатПараллельногоСпринта.номер_заезда)
            .all())


def _в_заезды(записи):
    """Группировать записи по номеру заезда → dict {номер: [left, right]}."""
    по_заезду = {}
    for з in записи:
        по_заезду.setdefault(з.номер_заезда, []).append(з)
    result = {}
    for номер in sorted(по_заезду.keys()):
        пара = sorted(по_заезду[номер],
                      key=lambda z: 0 if z.дорожка == 'левая' else (1 if z.дорожка == 'правая' else 2))
        result[номер] = пара
    return result


def _стадии_в_бд(sor_id, пол):
    return {з.стадия for з in _все_записи_пола(sor_id, пол)}


def _добавить_заезды(sor_id, стадия, пары, пол):
    """
    пары: list of (left_команда, right_команда | None)
    None = bye for left_команда
    Нумерация — независимая для каждого пола, сквозная через все стадии.
    race_num = (кол-во уже созданных заездов этого пола) + 1
    """
    db.session.flush()
    кол = (db.session.query(
               db.func.count(db.func.distinct(РезультатПараллельногоСпринта.номер_заезда)))
           .join(Команда, РезультатПараллельногоСпринта.команда_id == Команда.id)
           .filter(РезультатПараллельногоСпринта.соревнование_id == sor_id,
                   Команда.пол == пол,
                   РезультатПараллельногоСпринта.номер_заезда > 0)
           .scalar()) or 0
    race_num = кол + 1
    for кл, кп in пары:
        if кп is None:
            db.session.add(РезультатПараллельногоСпринта(
                команда_id=кл.id, соревнование_id=sor_id,
                стадия=стадия, номер_заезда=0, дорожка='бай',
                победитель=True,
            ))
        else:
            for дор, к in [('левая', кл), ('правая', кп)]:
                db.session.add(РезультатПараллельногоСпринта(
                    команда_id=к.id, соревнование_id=sor_id,
                    стадия=стадия, номер_заезда=race_num, дорожка=дор,
                    статус=СТАТУС_ФИНИШ,
                ))
            race_num += 1


def _сформировать_пары(seeded):
    """Стандартное разбиение на пары: seed1 vs seedN, seed2 vs seedN-1, ...
    Для нечётных: топ-посев получает бай."""
    n = len(seeded)
    пары = []
    if n % 2 == 1:
        пары.append((seeded[0], None))  # бай для первого посева
        seeded = seeded[1:]
        n = len(seeded)
    for i in range(n // 2):
        пары.append((seeded[i], seeded[n - 1 - i]))
    return пары


def _формировать_начало(sor_id, пол, класс=None):
    """Сформировать первый этап сетки на основе посева Спринта."""
    seeded = _посев(sor_id, пол, класс)
    n = len(seeded)
    if n < 2:
        return False

    first_stage = _первая_стадия(n)

    # Удалить существующую сетку для этого пола и класса
    ids = _ids_пола(sor_id, пол, класс)
    РезультатПараллельногоСпринта.query \
        .filter_by(соревнование_id=sor_id) \
        .filter(РезультатПараллельногоСпринта.команда_id.in_(ids)) \
        .delete(synchronize_session='fetch')

    if n == 3:
        # seed1 получает бай в 1/2, ожидает в финале А
        _добавить_заезды(sor_id, first_stage, [(seeded[0], None), (seeded[1], seeded[2])], пол)
        # BYE-заглушка в Финале А — позволяет вводить время старта заранее
        _добавить_заезды(sor_id, 'Финал_А', [(seeded[0], None)], пол)
    else:
        _добавить_заезды(sor_id, first_stage, _сформировать_пары(seeded), пол)
        # Заглушки финалов — позволяют вводить время старта до завершения ½ финала
        стадии_все = _ожидаемые_стадии(n)
        for стадия_ф, посев_idx in [('Финал_А', 0), ('Финал_Б', -1)]:
            if стадия_ф in стадии_все:
                db.session.add(РезультатПараллельногоСпринта(
                    команда_id=seeded[посев_idx].id,
                    соревнование_id=sor_id,
                    стадия=стадия_ф,
                    номер_заезда=0,
                    дорожка='заглушка',
                ))
    db.session.commit()
    return True


def _победители_стадии(sor_id, пол, стадия, класс=None):
    """Определить победителей/проигравших заездов стадии.
    Обновить поля победитель. Вернуть (winners, losers) отсортированные по результату."""
    записи = _записи_стадии(sor_id, пол, стадия, класс)
    по_заезду = _в_заезды(записи)

    победители = []
    проигравшие = []

    for номер, пара in по_заезду.items():
        # Бай
        if len(пара) == 1 and пара[0].дорожка == 'бай':
            победители.append(пара[0])
            continue

        valid = [(з, з.результат) for з in пара if з.результат is not None]
        dsq = [з for з in пара if з.статус in (СТАТУС_ДК, СТАТУС_ДНФ, СТАТУС_ДНС)]

        if len(valid) == 2:
            сорт = sorted(valid, key=lambda x: x[1])
            сорт[0][0].победитель = True
            сорт[1][0].победитель = False
            победители.append(сорт[0][0])
            проигравшие.append(сорт[1][0])
        elif len(valid) == 1:
            valid[0][0].победитель = True
            победители.append(valid[0][0])
            if dsq:
                dsq[0].победитель = False
                проигравшие.append(dsq[0])

    def сорт_кл(з):
        return з.результат if з.результат is not None else float('inf')

    победители.sort(key=сорт_кл)
    проигравшие.sort(key=сорт_кл)
    return победители, проигравшие


def _перейти_к_следующей(sor_id, пол, стадия, класс=None):
    """Рассчитать победителей стадии и сформировать следующую."""
    победители, проигравшие = _победители_стадии(sor_id, пол, стадия, класс)
    db.session.commit()

    if стадия == '1/2':
        ids = _ids_пола(sor_id, пол, класс)

        def _сохранить_время_заглушки(стадия_ф):
            rec = (РезультатПараллельногоСпринта.query
                   .filter_by(соревнование_id=sor_id, стадия=стадия_ф, номер_заезда=0)
                   .filter(РезультатПараллельногоСпринта.команда_id.in_(ids))
                   .first())
            return rec.время_старта if rec else None

        def _удалить_заглушки(стадия_ф):
            (РезультатПараллельногоСпринта.query
             .filter_by(соревнование_id=sor_id, стадия=стадия_ф)
             .filter(РезультатПараллельногоСпринта.команда_id.in_(ids))
             .delete(synchronize_session='fetch'))

        def _восстановить_время(стадия_ф, время):
            if not время:
                return
            db.session.flush()
            for rec in (РезультатПараллельногоСпринта.query
                        .filter_by(соревнование_id=sor_id, стадия=стадия_ф)
                        .filter(РезультатПараллельногоСпринта.команда_id.in_(ids)).all()):
                rec.время_старта = время

        saved_fa_time = _сохранить_время_заглушки('Финал_А')
        saved_fb_time = _сохранить_время_заглушки('Финал_Б')
        _удалить_заглушки('Финал_А')
        _удалить_заглушки('Финал_Б')

        # Победители → Финал А, проигравшие → Финал Б
        if len(победители) >= 2:
            _добавить_заезды(sor_id, 'Финал_А',
                             [(победители[0].команда, победители[1].команда)], пол)
        elif len(победители) == 1:
            _добавить_заезды(sor_id, 'Финал_А', [(победители[0].команда, None)], пол)
        _восстановить_время('Финал_А', saved_fa_time)

        if len(проигравшие) >= 2:
            _добавить_заезды(sor_id, 'Финал_Б',
                             [(проигравшие[0].команда, проигравшие[1].команда)], пол)
            _восстановить_время('Финал_Б', saved_fb_time)
        # Один проигравший → 3-е место без Финала Б (через start_places)

    elif стадия in СЛЕДУЮЩАЯ:
        следующая = СЛЕДУЮЩАЯ[стадия]
        n = len(победители)
        if n < 1:
            return False
        # Пере-посев победителей для следующей стадии
        пары = _сформировать_пары(победители)
        _добавить_заезды(sor_id, следующая,
                         [(з.команда, (зп.команда if зп else None)) for з, зп in пары], пол)

    db.session.commit()
    return True


def _рассчитать_итоговые(sor_id, пол, класс=None):
    """Присвоить итоговые места и очки. Вернуть список записей с местами."""
    все = _все_записи_пола(sor_id, пол, класс)
    if not все:
        return []

    # Сбросить предыдущие результаты
    for з in все:
        з.итоговое_место = None
        з.очки = 0

    # Финальные стадии не имеют следующего этапа, победитель не выставляется
    # автоматически — вычислить здесь
    стадии_бд = {з.стадия for з in все}
    for стадия_ф in ('Финал_А', 'Финал_Б'):
        if стадия_ф in стадии_бд:
            _победители_стадии(sor_id, пол, стадия_ф, класс)

    # Для каждой команды найти запись из последней стадии.
    # Финал_Б БАЙ (единственный проигравший 1/2 при 3 командах) пропускаем —
    # такая команда получит место через start_places['1/2'].
    индекс_ст = {ст: i for i, ст in enumerate(ПОРЯДОК_СТАДИЙ)}
    последняя = {}
    for з in все:
        if з.стадия == 'Финал_Б' and з.дорожка == 'бай':
            continue
        cid = з.команда_id
        prev = последняя.get(cid)
        if prev is None or индекс_ст.get(з.стадия, -1) > индекс_ст.get(prev.стадия, -1):
            последняя[cid] = з

    # Финал А
    for з in последняя.values():
        if з.стадия == 'Финал_А' and з.победитель is not None:
            з.итоговое_место = 1 if з.победитель else 2

    # Финал Б
    for з in последняя.values():
        if з.стадия == 'Финал_Б' and з.победитель is not None:
            з.итоговое_место = 3 if з.победитель else 4

    # Проигравшие в промежуточных стадиях → места по стадии
    start_places = {'1/2': 3, '1/4': 5, '1/8': 9}
    по_стадии = {}
    for з in последняя.values():
        if з.итоговое_место is None and з.победитель is False:
            по_стадии.setdefault(з.стадия, []).append(з)

    for стадия, лузеры in по_стадии.items():
        start = start_places.get(стадия)
        if start is None:
            continue
        лузеры.sort(key=lambda з: (з.штрафное_время or 0, з.время or float('inf')))
        for i, з in enumerate(лузеры):
            з.итоговое_место = start + i

    # Защита: место не может превышать число реальных участников
    n_участников = len(последняя)
    for з in последняя.values():
        if з.итоговое_место is not None and з.итоговое_место > n_участников:
            з.итоговое_место = None

    # ДК в любом заезде → команда места не получает; остальные места сдвигаются вверх
    дк_команды = {з.команда_id for з in все if з.статус == СТАТУС_ДК}
    for cid in дк_команды:
        if cid in последняя:
            последняя[cid].итоговое_место = None
    if дк_команды:
        размещённые = sorted(
            (з for з in последняя.values() if з.итоговое_место is not None),
            key=lambda з: з.итоговое_место,
        )
        for i, з in enumerate(размещённые, 1):
            з.итоговое_место = i

    db.session.commit()

    # Очки
    с_местом = [з for з in последняя.values() if з.итоговое_место]
    for з in с_местом:
        оч = ТаблицаОчков.query.filter_by(
            дистанция='ПАРАЛЛЕЛЬНЫЙ_СПРИНТ', место=з.итоговое_место).first()
        з.очки = оч.очки if оч else 0

    db.session.commit()
    с_местом.sort(key=lambda з: з.итоговое_место)

    # ДК-команды добавляем в конец списка (для отображения на странице Результаты)
    # Берём запись с наибольшей стадией где стоит ДК
    дк_отображение = {}
    for з in все:
        if з.статус == СТАТУС_ДК:
            cid = з.команда_id
            prev = дк_отображение.get(cid)
            if prev is None or индекс_ст.get(з.стадия, -1) > индекс_ст.get(prev.стадия, -1):
                дк_отображение[cid] = з
    дк_записи = sorted(дк_отображение.values(), key=lambda з: з.команда_id)
    return с_местом + дк_записи


