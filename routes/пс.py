def _ожидаемые_стадии(n):
    """Все стадии турнира для n команд (включая незаполненные)."""
    if n < 2:
        return []
    первая = _первая_стадия(n)
    idx = ПОРЯДОК_СТАДИЙ.index(первая)
    стадии = ПОРЯДОК_СТАДИЙ[idx:]
    if n <= 3:
        стадии = [ст for ст in стадии if ст != 'Финал_Б']
    return стадии


def _брак_данные(sor_id, пол, класс=None):
    """Данные сетки для отображения (включая будущие пустые стадии)."""
    посев = _посев(sor_id, пол, класс)
    n = len(посев)
    посев_map = {к.id: i + 1 for i, к in enumerate(посев)}

    if n < 2:
        return {}, [], посев_map, {}

    стадии = _ожидаемые_стадии(n)
    все = _все_записи_пола(sor_id, пол, класс)

    if not все:
        # Сетка ещё не сформирована — показываем ожидаемые пары первой стадии по посеву
        брак = {ст: {} for ст in стадии}
        предв = {}
        first_ст = стадии[0]
        if n == 3:
            пары = [(посев[1], посев[2])]
        else:
            пары_raw = _сформировать_пары(list(посев))
            пары = [(л, п) for л, п in пары_raw if п is not None]
        уч = []
        for л, п in пары:
            уч.append((л, None))
            уч.append((п, None))
        предв[first_ст] = уч
        return брак, стадии, посев_map, предв

    стадии_бд = {з.стадия for з in все}
    стадии = _ожидаемые_стадии(n) or [ст for ст in ПОРЯДОК_СТАДИЙ if ст in стадии_бд]
    брак = {}
    for ст in стадии:
        if ст in стадии_бд:
            записи = [з for з in все if з.стадия == ст]
            брак[ст] = _в_заезды(записи)
        else:
            брак[ст] = {}

    # Предварительные участники для пустых стадий:
    # список (команда_or_None, метка_or_None)
    предв = {}
    for i, стадия in enumerate(стадии):
        реальные_заезды = {к: v for к, v in брак[стадия].items() if к != 0}
        if реальные_заезды or i == 0:
            continue
        пред = стадии[i - 1]
        # Финал А: участники из ½ финала, а не из Финал Б
        if стадия == 'Финал_А' and пред == 'Финал_Б' and i >= 2:
            пред = стадии[i - 2]
        пред_данные = брак.get(пред, {})
        реальных = [к for к in пред_данные if к != 0]
        участники = []

        if стадия == 'Финал_Б':
            # Проигравшие реальных заездов предыдущей стадии
            назв_пред = НАЗВАНИЯ.get(пред, пред)
            for i, номер in enumerate(sorted(реальных), 1):
                пара = пред_данные[номер]
                проигр = next((з for з in пара if з.победитель is False), None)
                if проигр:
                    участники.append((проигр.команда, None))
                else:
                    участники.append((None, f'Проигравший заезда {i}, {назв_пред}'))
        else:
            # BYE-команды идут напрямую в следующую стадию (заглушки игнорируем)
            for з in пред_данные.get(0, []):
                if з.дорожка != 'заглушка':
                    участники.append((з.команда, None))
            # Победители реальных заездов
            назв_пред = НАЗВАНИЯ.get(пред, пред)
            for i, номер in enumerate(sorted(реальных), 1):
                пара = пред_данные[номер]
                побед = next((з for з in пара if з.победитель is True), None)
                if побед:
                    участники.append((побед.команда, None))
                else:
                    участники.append((None, f'Победитель заезда {i}, {назв_пред}'))

        предв[стадия] = участники

    return брак, стадии, посев_map, предв


def _метки_записей(sor_id, пол, класс=None):
    """Метка для каждой записи — точно как столбец «Стадия, место» на странице Результаты заездов."""
    все = _все_записи_пола(sor_id, пол, класс)
    СЛЕД = {'1/16': '1/8', '1/8': '1/4', '1/4': '1/2', '1/2': 'Финал_А'}
    реальных_12 = len({з.номер_заезда for з in все if з.стадия == '1/2' and з.номер_заезда > 0})
    метки = {}
    for з in все:
        if з.дорожка == 'бай':
            continue
        if з.победитель is True:
            if з.стадия in ('1/16', '1/8', '1/4', '1/2'):
                след = СЛЕД.get(з.стадия, '')
                метки[з.id] = '→ ' + НАЗВАНИЯ.get(след, след)
            elif з.стадия == 'Финал_А':
                метки[з.id] = '1 место'
            elif з.стадия == 'Финал_Б':
                метки[з.id] = '3 место'
        elif з.победитель is False:
            if з.стадия == '1/2' and реальных_12 == 1:
                метки[з.id] = '3 место'
            elif з.стадия == '1/2':
                метки[з.id] = '→ Финал Б'
            elif з.стадия == 'Финал_А':
                метки[з.id] = '2 место'
            elif з.стадия == 'Финал_Б':
                метки[з.id] = '4 место'
    return метки


