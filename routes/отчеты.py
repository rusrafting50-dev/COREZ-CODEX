def _топ3_место(команды_пола, attr, место_attr):
    """Топ-3 (место, команда) по указанному атрибуту результата."""
    ranked = []
    for к in команды_пола:
        р = getattr(к, attr, None)
        if р is None:
            continue
        if isinstance(р, list):
            for x in р:
                м = getattr(x, место_attr, None)
                if м:
                    ranked.append((м, к))
                    break
        else:
            м = getattr(р, место_attr, None)
            if м:
                ranked.append((м, к))
    return sorted(ranked, key=lambda x: x[0])[:3]


def _дисциплины_фрр(муж, жен, сор):
    """Top-3 по каждой дисциплине для отчёта ФРР."""
    класс = сор.класс_судна or ''
    виды = [
        ('Спринт',              'результат_спринт',     'место'),
        ('Параллельный спринт', 'результат_пс',         'итоговое_место'),
        ('Слалом',              'результат_слалом',     'место'),
        ('Длинная гонка',       'результат_дг',         'место'),
        ('Многоборье',          'результат_многоборья', 'место'),
    ]
    результаты = []
    for вид, attr, место_attr in виды:
        т_муж = _топ3_место(муж, attr, место_attr)
        т_жен = _топ3_место(жен, attr, место_attr)
        if т_муж or т_жен:
            результаты.append({'вид': вид, 'класс': класс,
                                'муж': т_муж, 'жен': т_жен})
    return результаты


def _дисциплины_отчёт(муж, жен, сор):
    """Дисциплины для п.13: плоский список по классу → полу → дисциплине."""
    классы = [к.strip() for к in (сор.класс_судна or 'R4').split() if к.strip()]
    виды = [
        ('Спринт',              'результат_спринт',     'место'),
        ('Параллельный спринт', 'результат_пс',         'итоговое_место'),
        ('Слалом',              'результат_слалом',     'место'),
        ('Длинная гонка',       'результат_дг',         'место'),
        ('Многоборье',          'результат_многоборья', 'место'),
    ]
    результаты = []
    for кл in классы:
        муж_кл = [к for к in муж if к.класс_судна == кл]
        жен_кл = [к for к in жен if к.класс_судна == кл]
        for пол_список, пол_назв in [(муж_кл, 'мужчины'), (жен_кл, 'женщины')]:
            for вид, attr, место_attr in виды:
                топ = _топ3_место(пол_список, attr, место_attr)
                if топ:
                    результаты.append(
                        {'вид': вид, 'класс': кл, 'пол': пол_назв, 'топ': топ}
                    )
    return результаты


def _медальный_зачёт_фрр(команды, дисциплины_отчёт):
    """Медальный зачёт по командам из дисциплин_отчёт (вид×класс×пол = таблицы п.13).

    Медаль определяется позицией в топ-3 (0=золото, 1=серебро, 2=бронза),
    а не значением поля место — это гарантирует равенство итогов Золото=Серебро=Бронза
    и соответствие количеству таблиц в п.13.
    """
    медали: dict = {}

    def _ключ(к):
        return (к.название or '').strip().lower()

    _МЕДАЛЬ = ['золото', 'серебро', 'бронза']

    for д in дисциплины_отчёт:
        for позиция, (место, к) in enumerate(д['топ'][:3]):
            key = _ключ(к)
            if key not in медали:
                медали[key] = {'название': к.название or '—',
                               'субъект': к.субъект,
                               'золото': 0, 'серебро': 0, 'бронза': 0}
            медали[key][_МЕДАЛЬ[позиция]] += 1

    # добавляем команды без медалей (чтобы все попали в таблицу)
    for к in команды:
        key = _ключ(к)
        if key not in медали:
            медали[key] = {'название': к.название or '—',
                           'субъект': к.субъект,
                           'золото': 0, 'серебро': 0, 'бронза': 0}

    return sorted(медали.values(),
                  key=lambda x: (-x['золото'], -x['серебро'], -x['бронза']))


