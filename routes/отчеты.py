# routes/отчеты.py — отчётные формы ФРР и ФЦПСР
from datetime import date
from flask import Blueprint, render_template
from models import (Соревнование, Команда, Спортсмен, Судья,
                    РезультатСпринт, РезультатПараллельногоСпринта,
                    РезультатСлалома, РезультатДлиннойГонки, РезультатМногоборья,
                    ТаблицаРазрядов)
from routes.многоборье import _очки_команды

bp_отчеты = Blueprint('отчеты', __name__)


def _стат(sor_id):
    """Собрать статистику для отчётов."""
    сор = Соревнование.query.get(sor_id)
    команды = Команда.query.filter_by(соревнование_id=sor_id).all()
    спортсмены = Спортсмен.query.join(Команда).filter(
        Команда.соревнование_id == sor_id
    ).all()
    судьи = Судья.query.filter_by(соревнование_id=sor_id).all()

    муж = [к for к in команды if к.пол == 'м']
    жен = [к for к in команды if к.пол == 'ж']

    # Топ-3 по многоборью
    топ_муж = sorted(
        [к for к in муж if к.результат_многоборья and к.результат_многоборья.место],
        key=lambda к: к.результат_многоборья.место
    )[:3]
    топ_жен = sorted(
        [к for к in жен if к.результат_многоборья and к.результат_многоборья.место],
        key=lambda к: к.результат_многоборья.место
    )[:3]

    # Разряды присвоены
    разряды_мс  = sum(1 for с in спортсмены if с.разряд in ('МС', 'МСМК'))
    разряды_кмс = sum(1 for с in спортсмены if с.разряд == 'КМС')
    разряды_1   = sum(1 for с in спортсмены if с.разряд == 'I')

    код = сор.код_соревнований if сор else None
    субъекты = сор.субъекты if сор else []

    return {
        'сор':          сор,
        'команды':      команды,
        'муж':          муж,
        'жен':          жен,
        'спортсмены':   спортсмены,
        'судьи':        судьи,
        'субъекты':     субъекты,
        'топ_муж':      топ_муж,
        'топ_жен':      топ_жен,
        'разряды_мс':   разряды_мс,
        'разряды_кмс':  разряды_кмс,
        'разряды_1':    разряды_1,
        'кол_экипажей': len(команды),
        'кол_муж':      len(муж),
        'кол_жен':      len(жен),
        'кол_спортсменов': len(спортсмены),
        'кол_судей':    len(судьи),
        'кол_субъектов': len(субъекты),
    }


@bp_отчеты.route('/<int:sor_id>/фрр')
def фрр(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    ст = _стат(sor_id)
    return render_template('отчеты/фрр.html', **ст, сегодня=date.today())


@bp_отчеты.route('/<int:sor_id>/фцпср')
def фцпср(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    ст = _стат(sor_id)
    return render_template('отчеты/фцпср.html', **ст, сегодня=date.today())
