def _топ3_место(команды_пола, attr, место_attr):
    """Топ-3 (место, команда) по указанному атрибуту результата."""
    ranked = []
    for к in команды_пола:
        р = getattr(к, attr, None)
        if р is None:
            continue
        if isinstance(р, list):
            for x in р:
                м = getattr(x, место_attr, None)
                if м:
                    ranked.append((м, к))
                    break
        else:
            м = getattr(р, место_attr, None)
            if м:
                ranked.append((м, к))
    return sorted(ranked, key=lambda x: x[0])[:3]


def _дисциплины_фрр(муж, жен, сор):
    """Top-3 по каждой дисциплине для отчёта ФРР."""
    класс = сор.класс_судна or ''
    виды = [
        ('Спринт',              'результат_спринт',     'место'),
        ('Параллельный спринт', 'результат_пс',         'итоговое_место'),
        ('Слалом',              'результат_слалом',     'место'),
        ('Длинная гонка',       'результат_дг',         'место'),
        ('Многоборье',          'результат_многоборья', 'место'),
    ]
    результаты = []
    for вид, attr, место_attr in виды:
        т_муж = _топ3_место(муж, attr, место_attr)
        т_жен = _топ3_место(жен, attr, место_attr)
        if т_муж or т_жен:
            результаты.append({'вид': вид, 'класс': класс,
                                'муж': т_муж, 'жен': т_жен})
    return результаты


def _медальный_зачёт_фрр(команды, дисциплины):
    """Медальный зачёт по командам."""
    медали = {}
    for д in дисциплины:
        for пол_рез in [д['муж'], д['жен']]:
            for место, к in пол_рез:
                if к.id not in медали:
                    медали[к.id] = {'к': к, 'золото': 0, 'серебро': 0, 'бронза': 0}
                if место == 1:
                    медали[к.id]['золото'] += 1
                elif место == 2:
                    медали[к.id]['серебро'] += 1
                elif место == 3:
                    медали[к.id]['бронза'] += 1
    for к in команды:
        if к.id not in медали:
            медали[к.id] = {'к': к, 'золото': 0, 'серебро': 0, 'бронза': 0}
    return sorted(медали.values(),
                  key=lambda x: (-x['золото'], -x['серебро'], -x['бронза']))


