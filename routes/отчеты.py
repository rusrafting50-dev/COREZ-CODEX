# Весовые коэффициенты для сравнения разрядов (выше = старше)
_РАНГ_ВЕС = {'МСМК': 8, 'МС': 7, 'КМС': 6, 'I': 5, 'II': 4, 'III': 3, 'Iю': 2, 'IIю': 1, 'IIIю': 0}


def _ранг_в(r):
    return _РАНГ_ВЕС.get((r or '').strip(), -1)


def _age_col(инстансы):
    """Определить наименьшую (младшую) возрастную колонку для спортсмена."""
    best_weight = 2
    best_col = None
    for с in инстансы:
        пол = с.пол or (с.команда.пол if с.команда else 'м')
        вг = (с.возрастная_группа or
              (с.команда.возрастная_группа if с.команда else '') or '').strip().lower()
        вг_н = вг.replace('ё', 'е')
        if 'юниор' in вг_н:
            col = 'юниорки' if пол == 'ж' else 'юниоры'
            w = 1
        elif 'юн' in вг_н:
            col = 'девушки' if пол == 'ж' else 'юноши'
            w = 0
        else:
            col = 'женщины' if пол == 'ж' else 'мужчины'
            w = 2
        if w < best_weight:
            best_weight, best_col = w, col
    if best_col is None:
        пол0 = инстансы[0].пол if инстансы else 'м'
        best_col = 'женщины' if пол0 == 'ж' else 'мужчины'
    return best_col


def _стат(sor_id):
    """Собрать статистику для отчётов."""
    сор = Соревнование.query.get(sor_id)
    команды = Команда.query.filter_by(соревнование_id=sor_id).all()
    спортсмены = Спортсмен.query.join(Команда).filter(
        Команда.соревнование_id == sor_id
    ).all()
    судьи = Судья.query.filter_by(соревнование_id=sor_id).all()

    муж = [к for к in команды if к.пол == 'м']
    жен = [к for к in команды if к.пол == 'ж']

    # Топ-3 по многоборью
    топ_муж = sorted(
        [к for к in муж if к.результат_многоборья and к.результат_многоборья.место],
        key=lambda к: к.результат_многоборья.место
    )[:3]
    топ_жен = sorted(
        [к for к in жен if к.результат_многоборья and к.результат_многоборья.место],
        key=lambda к: к.результат_многоборья.место
    )[:3]

    # Иногородние судьи (субъект РФ судьи ≠ субъект РФ места проведения)
    субъект_места = (сор.субъект_рф_название or '').strip()
    иногородних = sum(
        1 for с in судьи
        if с.субъект_рф and субъект_места and с.субъект_рф.strip() != субъект_места
    )

    код = сор.код_соревнований if сор else None
    субъекты = сор.субъекты if сор else []

    _кат_школ = ('ДЮСШ', 'СДЮСШОР', 'СШ', 'СШОР', 'ЦСП', 'УОР')
    школы = {к: 0 for к in _кат_школ}
    школы['другие'] = 0

    # ── Проход 1: канонический ключ имя → (имя, дата) ──────────────────────────
    _имя_ключ: dict = {}
    for с in спортсмены:
        имя = с.фамилия_имя_отчество.strip().lower()
        дата = с.дата_рождения
        if имя not in _имя_ключ:
            _имя_ключ[имя] = (имя, дата)
        elif дата and _имя_ключ[имя][1] is None:
            _имя_ключ[имя] = (имя, дата)

    # ── Проход 2: лучший орг + все экземпляры по ключу ─────────────────────────
    _все_по_ключу: dict = {}   # key → [Спортсмен, ...]
    _athlete_best_org: dict = {}
    for с in спортсмены:
        имя = с.фамилия_имя_отчество.strip().lower()
        key = _имя_ключ[имя]
        _все_по_ключу.setdefault(key, []).append(с)
        орг = (с.команда.принадлежность_к_орг or '').strip()
        prev = _athlete_best_org.get(key, '')
        if орг in _кат_школ:
            _athlete_best_org[key] = орг
        elif орг and prev not in _кат_школ:
            _athlete_best_org[key] = орг
        elif key not in _athlete_best_org:
            _athlete_best_org[key] = ''

    for орг in _athlete_best_org.values():
        if орг in школы:
            школы[орг] += 1
        elif орг:
            школы['другие'] += 1

    # ── Проход 3: уникальные спортсмены (предпочитаем запись с датой) ───────────
    _уник: dict = {}
    for с in спортсмены:
        имя = с.фамилия_имя_отчество.strip().lower()
        key = _имя_ключ[имя]
        if key not in _уник or (с.дата_рождения and not _уник[key].дата_рождения):
            _уник[key] = с
    уник_спортсмены = list(_уник.values())

    # ── Проход 4: квалификационная таблица с учётом возрастных групп ────────────
    _РАНГИ_КВ = ['МСМК', 'МС', 'КМС', 'I', 'II', 'III', 'Iю', 'IIю', 'IIIю']
    _КОЛОНКИ   = ['мужчины', 'женщины', 'юниоры', 'юниорки', 'юноши', 'девушки']
    квал_уник = {кол: {р: 0 for р in _РАНГИ_КВ} for кол in _КОЛОНКИ}
    for key, с in _уник.items():
        if с.разряд and с.разряд in _РАНГИ_КВ:
            инстансы = _все_по_ключу.get(key, [с])
            кол = _age_col(инстансы)
            квал_уник[кол][с.разряд] += 1

    # ── Проход 5: выполнение / подтверждение нормативов из итоговых протоколов ─
    _athlete_best_result: dict = {}   # key → best achieved rank string

    if код:
        for к in команды:
            # Спринт
            р = к.результат_спринт
            if р and р.место:
                тр = ТаблицаРазрядов.query.filter_by(
                    тип='С', место=р.место, статус_код=код).first()
                if тр and тр.разряд and тр.разряд != '-':
                    for с in к.спортсмены:
                        _key = _имя_ключ.get(с.фамилия_имя_отчество.strip().lower())
                        if _key and _ранг_в(тр.разряд) > _ранг_в(_athlete_best_result.get(_key, '')):
                            _athlete_best_result[_key] = тр.разряд

            # Слалом (берём первую попытку с установленным местом)
            for р_сл in (к.результат_слалом or []):
                if р_сл.место:
                    тр = ТаблицаРазрядов.query.filter_by(
                        тип='С', место=р_сл.место, статус_код=код).first()
                    if тр and тр.разряд and тр.разряд != '-':
                        for с in к.спортсмены:
                            _key = _имя_ключ.get(с.фамилия_имя_отчество.strip().lower())
                            if _key and _ранг_в(тр.разряд) > _ранг_в(_athlete_best_result.get(_key, '')):
                                _athlete_best_result[_key] = тр.разряд
                    break

            # Длинная гонка
            р = к.результат_дг
            if р and р.место:
                тр = ТаблицаРазрядов.query.filter_by(
                    тип='Д', место=р.место, статус_код=код).first()
                if тр and тр.разряд and тр.разряд != '-':
                    for с in к.спортсмены:
                        _key = _имя_ключ.get(с.фамилия_имя_отчество.strip().lower())
                        if _key and _ранг_в(тр.разряд) > _ранг_в(_athlete_best_result.get(_key, '')):
                            _athlete_best_result[_key] = тр.разряд

            # Многоборье
            р = к.результат_многоборья
            if р and р.место:
                тр = ТаблицаРазрядов.query.filter_by(
                    тип='М', место=р.место, статус_код=код).first()
                if тр and тр.разряд and тр.разряд != '-':
                    for с in к.спортсмены:
                        _key = _имя_ключ.get(с.фамилия_имя_отчество.strip().lower())
                        if _key and _ранг_в(тр.разряд) > _ранг_в(_athlete_best_result.get(_key, '')):
                            _athlete_best_result[_key] = тр.разряд

    _НОРМ_РАНГИ = ['МСМК', 'МС', 'КМС', 'I', 'II', 'III']
    выполнение_разряды   = {р: 0 for р in _НОРМ_РАНГИ}
    подтверждение_разряды = {р: 0 for р in _НОРМ_РАНГИ}

    for key, с in _уник.items():
        достигнут = _athlete_best_result.get(key, '')
        if not достигнут or достигнут not in _НОРМ_РАНГИ:
            continue
        текущий = (с.разряд or '').strip()
        if _ранг_в(достигнут) > _ранг_в(текущий):
            выполнение_разряды[достигнут] += 1
        else:
            подтверждение_разряды[достигнут] += 1

    # ── Проход 6: состав команд сгруппированный по названию (для п.8) ──────────
    _teams_by_name: dict = {}
    for к in команды:
        name = (к.название or '').strip()
        _teams_by_name.setdefault(name, []).append(к)

    состав_команд = []
    for name, group in sorted(_teams_by_name.items(), key=lambda x: x[0].lower() if x[0] else ''):
        _уник_в_гр: dict = {}
        for к in group:
            for с in к.спортсмены:
                имя = с.фамилия_имя_отчество.strip().lower()
                gkey = _имя_ключ.get(имя, (имя, None))
                if gkey not in _уник_в_гр or (с.дата_рождения and not _уник_в_гр[gkey].дата_рождения):
                    _уник_в_гр[gkey] = с
        all_сп = list(_уник_в_гр.values())
        муж_к = sum(1 for с in all_сп if с.пол == 'м')
        жен_к = sum(1 for с in all_сп if с.пол == 'ж')
        субъект = next((к.субъект for к in group if к.субъект), None)
        состав_команд.append({
            'название':  name or '—',
            'субъект':   субъект,
            'муж':       муж_к,
            'жен':       жен_к,
            'всего':     len(all_сп),
        })

    # Разряды (legacy — для совместимости с шаблонами ФЦПСР/Липецк)
    разряды_мс  = sum(1 for с in уник_спортсмены if с.разряд in ('МС', 'МСМК'))
    разряды_кмс = sum(1 for с in уник_спортсмены if с.разряд == 'КМС')
    разряды_1   = sum(1 for с in уник_спортсмены if с.разряд == 'I')

    return {
        'сор':                    сор,
        'команды':                команды,
        'муж':                    муж,
        'жен':                    жен,
        'спортсмены':             спортсмены,
        'уник_спортсмены':        уник_спортсмены,
        'судьи':                  судьи,
        'субъекты':               субъекты,
        'топ_муж':                топ_муж,
        'топ_жен':                топ_жен,
        'разряды_мс':             разряды_мс,
        'разряды_кмс':            разряды_кмс,
        'разряды_1':              разряды_1,
        'кол_экипажей':           len(команды),
        'кол_муж':                len(муж),
        'кол_жен':                len(жен),
        'кол_спортсменов':        len(уник_спортсмены),
        'кол_судей':              len(судьи),
        'иногородних':            иногородних,
        'кол_субъектов':          len(субъекты),
        'школы':                  школы,
        'квал_уник':              квал_уник,
        'выполнение_разряды':     выполнение_разряды,
        'подтверждение_разряды':  подтверждение_разряды,
        'состав_команд':          состав_команд,
    }


