def _стат(sor_id):
    """Собрать статистику для отчётов."""
    сор = Соревнование.query.get(sor_id)
    команды = Команда.query.filter_by(соревнование_id=sor_id).all()
    спортсмены = Спортсмен.query.join(Команда).filter(
        Команда.соревнование_id == sor_id
    ).all()
    судьи = Судья.query.filter_by(соревнование_id=sor_id).all()

    муж = [к for к in команды if к.пол == 'м']
    жен = [к for к in команды if к.пол == 'ж']

    # Топ-3 по многоборью
    топ_муж = sorted(
        [к for к in муж if к.результат_многоборья and к.результат_многоборья.место],
        key=lambda к: к.результат_многоборья.место
    )[:3]
    топ_жен = sorted(
        [к for к in жен if к.результат_многоборья and к.результат_многоборья.место],
        key=lambda к: к.результат_многоборья.место
    )[:3]

    # Разряды присвоены
    разряды_мс  = sum(1 for с in спортсмены if с.разряд in ('МС', 'МСМК'))
    разряды_кмс = sum(1 for с in спортсмены if с.разряд == 'КМС')
    разряды_1   = sum(1 for с in спортсмены if с.разряд == 'I')

    код = сор.код_соревнований if сор else None
    субъекты = сор.субъекты if сор else []

    # Подсчёт принадлежности к спортшколам (из комиссии по допуску — поле команды)
    # Дедупликация по (ФИО, дата рождения). Если у одной записи дата не заполнена,
    # она получает дату из другой записи с тем же ФИО (нормализация ключа).
    _кат_школ = ('ДЮСШ', 'СДЮСШОР', 'СШ', 'СШОР', 'ЦСП', 'УОР')
    школы = {к: 0 for к in _кат_школ}
    школы['другие'] = 0

    # Проход 1: строим канонический ключ имя → (имя, дата)
    _имя_ключ: dict = {}
    for с in спортсмены:
        имя = с.фамилия_имя_отчество.strip().lower()
        дата = с.дата_рождения
        if имя not in _имя_ключ:
            _имя_ключ[имя] = (имя, дата)
        elif дата and _имя_ключ[имя][1] is None:
            _имя_ключ[имя] = (имя, дата)  # заполняем отсутствующую дату

    # Проход 2: лучший орг для каждого уникального ключа
    _athlete_best_org: dict = {}
    for с in спортсмены:
        имя = с.фамилия_имя_отчество.strip().lower()
        key = _имя_ключ[имя]
        орг = (с.команда.принадлежность_к_орг or '').strip()
        prev = _athlete_best_org.get(key, '')
        if орг in _кат_школ:
            _athlete_best_org[key] = орг
        elif орг and prev not in _кат_школ:
            _athlete_best_org[key] = орг
        elif key not in _athlete_best_org:
            _athlete_best_org[key] = ''

    for орг in _athlete_best_org.values():
        if орг in школы:
            школы[орг] += 1
        elif орг:
            школы['другие'] += 1

    # Дедуплицированный список уникальных спортсменов (один экземпляр на человека)
    # Используется для п.4 и п.6. Тот же канонический ключ, что и для школ.
    _уник: dict = {}  # key -> Спортсмен (первый встреченный, предпочитаем с датой)
    for с in спортсмены:
        имя = с.фамилия_имя_отчество.strip().lower()
        key = _имя_ключ[имя]
        if key not in _уник or (с.дата_рождения and not _уник[key].дата_рождения):
            _уник[key] = с
    уник_спортсмены = list(_уник.values())

    return {
        'сор':               сор,
        'команды':           команды,
        'муж':               муж,
        'жен':               жен,
        'спортсмены':        спортсмены,
        'уник_спортсмены':   уник_спортсмены,
        'судьи':             судьи,
        'субъекты':          субъекты,
        'топ_муж':           топ_муж,
        'топ_жен':           топ_жен,
        'разряды_мс':        разряды_мс,
        'разряды_кмс':       разряды_кмс,
        'разряды_1':         разряды_1,
        'кол_экипажей':      len(команды),
        'кол_муж':           len(муж),
        'кол_жен':           len(жен),
        'кол_спортсменов':   len(уник_спортсмены),
        'кол_судей':         len(судьи),
        'кол_субъектов':     len(субъекты),
        'школы':             школы,
    }


