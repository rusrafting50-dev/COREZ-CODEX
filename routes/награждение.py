# routes/награждение.py — страница Награждение и печатный диплом
from flask import Blueprint, render_template, request, redirect, url_for, flash
from models import db, Соревнование, НаграждениеПараметры, РезультатСпринт, Команда

bp_награждение = Blueprint('награждение', __name__)

МЕСТО_СЛОВО = {1: 'первое', 2: 'второе', 3: 'третье'}
МЕСТО_РОДА  = {1: 'I', 2: 'II', 3: 'III'}


def _получить_или_создать_пар(sor_id):
    пар = НаграждениеПараметры.query.filter_by(соревнование_id=sor_id).first()
    if not пар:
        пар = НаграждениеПараметры(
            соревнование_id=sor_id,
            использует_награждается=True,
            отступ_сверху=75,
            отступ_снизу=25,
            отступ_слева=15,
            отступ_справа=15,
        )
    return пар


@bp_награждение.route('/<int:sor_id>/награждение', methods=['GET', 'POST'])
def страница(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    пар = НаграждениеПараметры.query.filter_by(соревнование_id=sor_id).first()

    if request.method == 'POST':
        if not пар:
            пар = НаграждениеПараметры(соревнование_id=sor_id)
            db.session.add(пар)

        пар.использует_награждается   = request.form.get('использует_награждается') == '1'
        пар.отступ_сверху             = int(request.form.get('отступ_сверху') or 75)
        пар.отступ_снизу              = int(request.form.get('отступ_снизу') or 25)
        пар.отступ_слева              = int(request.form.get('отступ_слева') or 15)
        пар.отступ_справа             = int(request.form.get('отступ_справа') or 15)
        пар.наименование_соревнований = request.form.get('наименование_соревнований', '').strip() or None
        пар.должность_подписывающего  = request.form.get('должность_подписывающего', '').strip() or None
        пар.ио_фамилия_подписывающего = request.form.get('ио_фамилия_подписывающего', '').strip() or None

        db.session.commit()
        flash('Параметры дипломов сохранены.', 'success')
        return redirect(url_for('награждение.страница', sor_id=sor_id))

    if not пар:
        пар = _получить_или_создать_пар(sor_id)

    # Определяем комбинации (класс, пол) из фактических команд
    комбинации = (
        db.session.query(Команда.класс_судна, Команда.пол)
        .filter_by(соревнование_id=sor_id)
        .distinct()
        .order_by(Команда.класс_судна, Команда.пол)
        .all()
    )

    return render_template('награждение/награждение.html',
                           сор=сор, пар=пар, комбинации=комбинации)


@bp_награждение.route('/<int:sor_id>/награждение/диплом')
def диплом(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    пар = _получить_или_создать_пар(sor_id)

    класс = request.args.get('класс', 'R4')
    пол   = request.args.get('пол', 'м')
    место = int(request.args.get('место', 1))

    рез = (
        РезультатСпринт.query
        .join(Команда)
        .filter(
            Команда.соревнование_id == sor_id,
            Команда.класс_судна == класс,
            Команда.пол == пол,
            РезультатСпринт.место == место,
        )
        .first()
    )

    пол_название = 'мужчины' if пол == 'м' else 'женщины'
    дисциплина   = f'СПРИНТ – {класс}, {пол_название}'
    место_слово  = МЕСТО_СЛОВО.get(место, str(место))
    степень      = МЕСТО_РОДА.get(место, str(место))

    return render_template('награждение/диплом.html',
                           сор=сор, пар=пар, рез=рез,
                           класс=класс, пол=пол, место=место,
                           пол_название=пол_название,
                           дисциплина=дисциплина,
                           место_слово=место_слово,
                           степень=степень)
