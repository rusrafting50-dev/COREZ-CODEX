# routes/награждение.py — страница Награждение и печатный диплом
from flask import Blueprint, render_template, request, url_for
from models import db, Соревнование, НаграждениеПараметры, Команда
from routes.спринт import _рассчитать as _сп_рассчитать
from routes.пс import _рассчитать_итоговые as _пс_рассчитать
from routes.слалом import _рассчитать_итог as _сл_рассчитать
from routes.дг import _рассчитать_итог as _дг_рассчитать
from routes.многоборье import _рассчитать as _мб_рассчитать
from routes.зачет import _зачёт_группа

bp_награждение = Blueprint('награждение', __name__)

МЕСТО_СЛОВО = {1: 'первое', 2: 'второе', 3: 'третье'}
МЕСТО_РОДА  = {1: 'I', 2: 'II', 3: 'III'}

_ДИС_ВСЕ = [
    ('R4', 'м', '{дисц} – R4, мужчины'),
    ('R4', 'ж', '{дисц} – R4, женщины'),
    ('R6', 'м', '{дисц} – R6, мужчины'),
    ('R6', 'ж', '{дисц} – R6, женщины'),
]


def _получить_или_создать_пар(sor_id):
    пар = НаграждениеПараметры.query.filter_by(соревнование_id=sor_id).first()
    if not пар:
        пар = НаграждениеПараметры(
            соревнование_id=sor_id,
            использует_награждается=True,
            отступ_сверху=75,
            отступ_снизу=25,
            отступ_слева=15,
            отступ_справа=15,
        )
    return пар


def _комбинации(sor_id):
    rows = (
        db.session.query(Команда.класс_судна, Команда.пол)
        .filter_by(соревнование_id=sor_id)
        .distinct()
        .all()
    )
    return {(r[0], r[1]) for r in rows}


def _дисциплины(дисц_назв):
    return [
        (кл, п, заг.format(дисц=дисц_назв))
        for кл, п, заг in _ДИС_ВСЕ
    ]


def _страница_наград(sor_id, заголовок_дисц, маршрут_страница, маршрут_диплом,
                    навигация, дисц_назв, section_наград):
    сор = Соревнование.query.get_or_404(sor_id)
    пар = НаграждениеПараметры.query.filter_by(соревнование_id=sor_id).first()
    if not пар:
        пар = _получить_или_создать_пар(sor_id)

    field_наград = 'готов_' + section_наград.replace('-', '_')
    готов_наград = getattr(сор, field_наград, False)

    return render_template('награждение/награждение.html',
                           сор=сор, пар=пар,
                           комбинации=_комбинации(sor_id),
                           заголовок_дисц=заголовок_дисц,
                           маршрут_страница=маршрут_страница,
                           маршрут_диплом=маршрут_диплом,
                           навигация=навигация,
                           дисциплины=_дисциплины(дисц_назв),
                           section_наград=section_наград,
                           готов_наград=готов_наград)


# ── СПРИНТ ────────────────────────────────────────────────────────────────────

@bp_награждение.route('/<int:sor_id>/награждение', methods=['GET'])
def страница(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    навигация = [
        {'url': url_for('дистанция.страница', sor_id=sor_id), 'метка': 'Дистанция', 'стиль': 'primary'},
        {'url': url_for('документы.жеребьёвка', sor_id=sor_id), 'метка': 'Жеребьёвка и стартовый протокол', 'стиль': 'primary'},
        {'url': url_for('спринт.результаты', sor_id=sor_id), 'метка': 'Результаты', 'стиль': 'success'},
    ]
    return _страница_наград(sor_id, 'СПРИНТ', 'награждение.страница', 'награждение.диплом', навигация, 'Спринт', 'наград-спринт')


@bp_награждение.route('/<int:sor_id>/награждение/диплом')
def диплом(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    пар = _получить_или_создать_пар(sor_id)

    класс = request.args.get('класс', 'R4')
    пол   = request.args.get('пол', 'м')
    место = int(request.args.get('место', 1))

    рез_список, _, _ = _сп_рассчитать(sor_id, пол, класс)
    рез = рез_список[место - 1] if место <= len(рез_список) else None

    пол_название = 'мужчины' if пол == 'м' else 'женщины'
    дисциплина   = f'СПРИНТ – {класс}, {пол_название}'
    место_слово  = МЕСТО_СЛОВО.get(место, str(место))
    степень      = МЕСТО_РОДА.get(место, str(место))
    назад_url    = url_for('награждение.страница', sor_id=sor_id)

    return render_template('награждение/диплом.html',
                           сор=сор, пар=пар, рез=рез,
                           класс=класс, пол=пол, место=место,
                           пол_название=пол_название,
                           дисциплина=дисциплина,
                           дисциплина_строка=f'СПРИНТ – {класс}',
                           место_слово=место_слово,
                           степень=степень,
                           назад_url=назад_url)


