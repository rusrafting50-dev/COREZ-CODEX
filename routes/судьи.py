@bp_судьи.route('/<int:sor_id>/гск')
def гск(sor_id):
    """Состав ГСК — печатный документ."""
    сор = Соревнование.query.get_or_404(sor_id)
    все = Судья.query.filter_by(соревнование_id=sor_id).all()
    судьи = sorted(
        [с for с in все if с.должность in _ГСК_ПРИОРИТЕТ],
        key=lambda с: _ГСК_ПРИОРИТЕТ[с.должность]
    )
    стат = _статистика(все, сор.субъект_рф_название or '')
    сегодня = date.today()
    return render_template('судьи/гск.html',
                           сор=сор, судьи=судьи, стат=стат,
                           сегодня=сегодня)


