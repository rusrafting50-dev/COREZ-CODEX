# Должности, выводимые в Составе ГСК (в нужном порядке)
_ГСК_ДОЛЖНОСТИ = [
    'Главный судья',
    'Главный секретарь',
    'Зам. главного судьи по судейству',
    'Зам. главного судьи по орг. вопросам',
    'Начальник дистанций',
    'Начальник спасательной службы',
    'Зам. главного секретаря',
]
_ГСК_ПРИОРИТЕТ = {д: i for i, д in enumerate(_ГСК_ДОЛЖНОСТИ)}

_ДОЛЖНОСТЬ_ПРИОРИТЕТ = {д: i for i, д in enumerate(ДОЛЖНОСТИ)}

# Цвета бейджей квалификаций
КВАЛ_ЦВЕТ = {
    'ССВК': 'danger',
    'СС1К': 'warning text-dark',
    'СС2К': 'primary',
    'СС3К': 'secondary',
    'ЮС':   'info text-dark',
}


def _сортировка_судей(судьи):
    """Сортировка: по приоритету должности, затем по ФИО."""
    return sorted(судьи, key=lambda с: (
        _ДОЛЖНОСТЬ_ПРИОРИТЕТ.get(с.должность, 99),
        с.фамилия_имя_отчество
    ))


def _статистика(судьи, субъект_рф_места=''):
    """Подсчёт по квалификациям, полу и иногородним."""
    по_квал = {к: 0 for к in КВАЛИФИКАЦИИ}
    for с in судьи:
        if с.квалификация in по_квал:
            по_квал[с.квалификация] += 1
    муж = sum(1 for с in судьи if с.пол == 'м')
    жен = sum(1 for с in судьи if с.пол == 'ж')
    действующих = sum(1 for с in судьи if с.действующая_категория)
    иногородних_по_квал = {к: 0 for к in КВАЛИФИКАЦИИ}
    for с in судьи:
        if с.субъект_рф and субъект_рф_места and с.субъект_рф.strip() != субъект_рф_места.strip():
            if с.квалификация in иногородних_по_квал:
                иногородних_по_квал[с.квалификация] += 1
    иногородних = sum(иногородних_по_квал.values())
    return {'по_квал': по_квал, 'муж': муж, 'жен': жен,
            'действующих': действующих, 'всего': len(судьи),
            'иногородних': иногородних, 'иногородних_по_квал': иногородних_по_квал}


# ── JSON-поиск по базе всех соревнований ─────────────────────────────────────

@bp_судьи.route('/поиск')
def поиск():
    q = request.args.get('q', '').strip()
    if len(q) < 2:
        return jsonify([])
    записи = (Судья.query
              .filter(Судья.фамилия_имя_отчество.ilike(f'%{q}%'))
              .order_by(Судья.фамилия_имя_отчество, Судья.id.desc())
              .limit(50)
              .all())
    # Дедупликация по ФИО — наиболее актуальная запись
    seen: dict = {}
    for с in записи:
        key = с.фамилия_имя_отчество.strip().lower()
        if key not in seen:
            seen[key] = с
    результат = sorted(
        [
            {
                'фио':               с.фамилия_имя_отчество,
                'квалификация':      с.квалификация or '',
                'субъект_рф':        с.субъект_рф or '',
                'пол':               с.пол or '',
                'дата_рождения':     с.дата_рождения.isoformat()      if с.дата_рождения     else '',
                'дата_присвоения':   с.дата_присвоения.isoformat()    if с.дата_присвоения   else '',
                'дата_подтверждения':с.дата_подтверждения.isoformat() if с.дата_подтверждения else '',
                'конец_аттестации':  с.конец_аттестации.isoformat()   if с.конец_аттестации  else '',
                'номер_в_базе':      с.номер_в_базе or '',
            }
            for с in seen.values()
        ],
        key=lambda x: x['фио']
    )
    return jsonify(результат)


# ── Список ────────────────────────────────────────────────────────────────────

@bp_судьи.route('/<int:sor_id>')
def список(sor_id):
    сор   = Соревнование.query.get_or_404(sor_id)
    судьи = _сортировка_судей(
        Судья.query.filter_by(соревнование_id=sor_id).all()
    )
    стат  = _статистика(судьи, сор.субъект_рф_название or '')
    сегодня = date.today()
    return render_template('судьи/список.html',
                           сор=сор, судьи=судьи, стат=стат,
                           квал_цвет=КВАЛ_ЦВЕТ, сегодня=сегодня)


