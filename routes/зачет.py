# routes/зачет.py — зачёт субъектов РФ по сумме очков всех экипажей
from datetime import date
from flask import Blueprint, render_template, request
from models import (db, Соревнование, Субъект, КоэффициентыСубъектов)
from routes.многоборье import _очки_команды

bp_зачет = Blueprint('зачет', __name__)


def _зачёт_группа(sor_id, пол, класс=None):
    """Рассчитать зачёт субъектов для группы (пол, класс).
    Возвращает отсортированный список записей-словарей."""
    сор = Соревнование.query.get(sor_id)
    субъекты = Субъект.query.filter_by(соревнование_id=sor_id).all()
    кол_суб = сор.кол_субъектов if сор and сор.кол_субъектов else len(субъекты)

    итог = []
    for суб in субъекты:
        команды = [к for к in суб.команды if к.пол == пол]
        if класс:
            команды = [к for к in команды if к.класс_судна == класс]
        if not команды:
            continue

        оч_сп = оч_пс = оч_сл = оч_дг = оч_мб = 0.0
        for к in команды:
            s, п, сл, д = _очки_команды(к)
            оч_сп += s
            оч_пс += п
            оч_сл += сл
            оч_дг += д
            оч_мб += float(к.результат_многоборья.очки_многоборье) if к.результат_многоборья else 0.0

        итого = оч_сп + оч_пс + оч_сл + оч_дг + оч_мб
        итог.append({
            'субъект':  суб,
            'оч_сп':    оч_сп,
            'оч_пс':    оч_пс,
            'оч_сл':    оч_сл,
            'оч_дг':    оч_дг,
            'оч_мб':    оч_мб,
            'итого':    итого,
            'кол_команд': len(команды),
        })

    итог.sort(key=lambda x: -x['итого'])

    for место, запись in enumerate(итог, 1):
        запись['место'] = место
        коэф = КоэффициентыСубъектов.query.filter_by(
            место=место, кол_субъектов=min(кол_суб, 25)
        ).first()
        запись['коэффициент'] = round(коэф.коэффициент, 3) if коэф else 1.0
        запись['итого_к'] = round(запись['итого'] * запись['коэффициент'], 2)

    return итог


def _группы(sor_id):
    """Определить группы (пол × класс) с командами в соревновании."""
    from models import Команда
    команды = Команда.query.filter_by(соревнование_id=sor_id).all()
    классы = sorted({к.класс_судна for к in команды})
    полы = [('м', 'Мужские'), ('ж', 'Женские')]
    группы = []
    for пол, пол_назв in полы:
        for кл in классы:
            есть = any(к.пол == пол and к.класс_судна == кл for к in команды)
            if есть:
                группы.append((пол, пол_назв, кл))
    return группы


@bp_зачет.route('/<int:sor_id>/результаты')
def результаты(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    группы = _группы(sor_id)
    таблицы = [(пол, назв, кл, _зачёт_группа(sor_id, пол, кл)) for пол, назв, кл in группы]
    return render_template('зачет/результаты.html',
                           сор=сор, таблицы=таблицы,
                           сегодня=date.today())


@bp_зачет.route('/<int:sor_id>/протокол')
def протокол(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    группы = _группы(sor_id)
    таблицы = [(пол, назв, кл, _зачёт_группа(sor_id, пол, кл)) for пол, назв, кл in группы]
    итоговый = request.args.get('итоговый', '0') == '1'
    return render_template('зачет/протокол.html',
                           сор=сор, таблицы=таблицы,
                           итоговый=итоговый,
                           сегодня=date.today())
