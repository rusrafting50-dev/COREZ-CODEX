# routes/зачет.py — зачёт субъектов РФ по сумме очков всех экипажей
from datetime import date
from flask import Blueprint, render_template, request
from models import (db, Соревнование, Субъект, КоэффициентыСубъектов, Команда)

bp_зачет = Blueprint('зачет', __name__)

ПОЛ_НАЗВ = {'м': 'Мужчины', 'ж': 'Женщины'}


def _группы_соревнования(sor_id):
    """Вернуть список (пол, класс) групп — порядок R4М, R4Ж, R6М, R6Ж."""
    команды = Команда.query.filter_by(соревнование_id=sor_id).all()
    классы = sorted({к.класс_судна for к in команды})
    группы = []
    for кл in классы:
        for пол in ['м', 'ж']:
            if any(к.пол == пол and к.класс_судна == кл for к in команды):
                группы.append((пол, кл))
    return группы


def _очки_зс(место, кол_субъектов):
    """Очки субъекта по таблице ЗС за занятое место в дисциплине.
    кол_субъектов — число субъектов, имеющих экипажи с результатом в данной группе.
    """
    if not место or кол_субъектов < 1:
        return 0.0
    кол = max(3, min(кол_субъектов, 13))
    м = min(место, 4)
    запись = КоэффициентыСубъектов.query.filter_by(место=м, кол_субъектов=кол).first()
    return float(запись.коэффициент) if запись else 1.0


def _место_пс(команда):
    """Итоговое место команды в параллельном спринте."""
    итог = [р for р in команда.результат_пс if р.итоговое_место is not None]
    return итог[0].итоговое_место if итог else None


def _место_слалом(команда):
    """Место команды в слаломе."""
    итог = [р for р in команда.результат_слалом if р.место is not None]
    return итог[0].место if итог else None


def _кол_субъектов_по_дисциплинам(команды_гр):
    """Число СУБЪЕКТОВ с результатами в каждой дисциплине для списка команд группы."""
    def cnt(filter_fn):
        return len({к.субъект_id for к in команды_гр if к.субъект_id and filter_fn(к)})
    return {
        'сп': cnt(lambda к: к.результат_спринт and к.результат_спринт.место is not None),
        'пс': cnt(lambda к: _место_пс(к) is not None),
        'сл': cnt(lambda к: _место_слалом(к) is not None),
        'дг': cnt(lambda к: к.результат_дг and к.результат_дг.место is not None),
        'мб': cnt(lambda к: к.результат_многоборья and к.результат_многоборья.место is not None),
    }


def _очки_команды_зачёт(к, кол):
    """Сумма очков ЗС по всем пяти дисциплинам для одного экипажа.
    кол — dict {сп, пс, сл, дг, мб} с числом субъектов в группе по каждой дисциплине.
    """
    место_сп = к.результат_спринт.место if к.результат_спринт else None
    место_пс = _место_пс(к)
    место_сл = _место_слалом(к)
    место_дг = к.результат_дг.место if к.результат_дг else None
    место_мб = к.результат_многоборья.место if к.результат_многоборья else None

    return (
        _очки_зс(место_сп, кол['сп']) +
        _очки_зс(место_пс, кол['пс']) +
        _очки_зс(место_сл, кол['сл']) +
        _очки_зс(место_дг, кол['дг']) +
        _очки_зс(место_мб, кол['мб'])
    )


def _зачёт_все(sor_id):
    """Комплексный зачёт субъектов — одна запись на субъект, все группы вместе.
    Возвращает (итог_список, группы_список).
    итог_список: [{субъект, группы: {(пол,кл): {кол,баллы}},
                   итого_кол, итого_баллы, место}, ...]
    """
    субъекты = Субъект.query.filter_by(соревнование_id=sor_id).all()
    группы = _группы_соревнования(sor_id)

    # Для каждой группы (пол, класс) собрать все команды и посчитать кол_субъектов по дисциплинам
    кол_по_группам = {}
    for пол, кл in группы:
        команды_гр = [
            к for суб in субъекты
            for к in суб.команды if к.пол == пол and к.класс_судна == кл
        ]
        кол_по_группам[(пол, кл)] = _кол_субъектов_по_дисциплинам(команды_гр)

    итог = []
    for суб in субъекты:
        суб_данные = {
            'субъект':     суб,
            'группы':      {},
            'итого_кол':   0,
            'итого_баллы': 0.0,
        }
        has_crews = False
        for пол, кл in группы:
            команды = [к for к in суб.команды if к.пол == пол and к.класс_судна == кл]
            if not команды:
                суб_данные['группы'][(пол, кл)] = {'кол': 0, 'баллы': 0.0}
                continue
            has_crews = True
            кол = кол_по_группам[(пол, кл)]
            баллы = sum(_очки_команды_зачёт(к, кол) for к in команды)
            суб_данные['группы'][(пол, кл)] = {'кол': len(команды), 'баллы': round(баллы, 2)}
            суб_данные['итого_кол']   += len(команды)
            суб_данные['итого_баллы'] += баллы

        if has_crews:
            суб_данные['итого_баллы'] = round(суб_данные['итого_баллы'], 2)
            итог.append(суб_данные)

    итог.sort(key=lambda x: -x['итого_баллы'])
    for место, запись in enumerate(итог, 1):
        запись['место'] = место

    return итог, группы


def _таблица_зс():
    """Таблица ЗС: строки=кол.субъектов (убывающий), столбцы=места 1,2,3,'4 и ниже'."""
    все = КоэффициентыСубъектов.query.all()
    if not все:
        return None
    кол_nums = sorted({r.кол_субъектов for r in все}, reverse=True)
    место_nums = sorted({r.место for r in все})
    data = {(r.кол_субъектов, r.место): r.коэффициент for r in все}
    row_labels = {к: ('13 и более' if к >= 13 else ('3 и менее' if к <= 3 else str(к))) for к in кол_nums}
    col_labels = {м: ('4 и ниже' if м >= 4 else str(м)) for м in место_nums}
    return {'rows': кол_nums, 'row_labels': row_labels,
            'cols': место_nums, 'col_labels': col_labels, 'data': data}


def _зачёт_группа(sor_id, пол, класс=None):
    """Зачёт для одной группы (пол, класс) — оставлен для маршрута диплома."""
    субъекты = Субъект.query.filter_by(соревнование_id=sor_id).all()

    # Все команды группы для подсчёта кол_субъектов
    команды_гр = [
        к for суб in субъекты for к in суб.команды
        if к.пол == пол and (класс is None or к.класс_судна == класс)
    ]
    кол = _кол_субъектов_по_дисциплинам(команды_гр)

    итог = []
    for суб in субъекты:
        команды = [к for к in суб.команды if к.пол == пол]
        if класс:
            команды = [к for к in команды if к.класс_судна == класс]
        if not команды:
            continue
        баллы = sum(_очки_команды_зачёт(к, кол) for к in команды)
        итог.append({'субъект': суб, 'итого_баллы': round(баллы, 2), 'кол_команд': len(команды)})

    итог.sort(key=lambda x: -x['итого_баллы'])
    for место, запись in enumerate(итог, 1):
        запись['место'] = место
        запись['коэффициент'] = 1.0
        запись['итого_к'] = запись['итого_баллы']
    return итог




@bp_зачет.route('/<int:sor_id>/результаты')
def результаты(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    итог, группы = _зачёт_все(sor_id)
    return render_template('зачет/результаты.html',
                           сор=сор,
                           итог=итог,
                           группы=группы,
                           ПОЛ_НАЗВ=ПОЛ_НАЗВ,
                           сегодня=date.today(),
                           готов_наград=сор.готов_наград_зачет)


@bp_зачет.route('/<int:sor_id>/протокол')
def протокол(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    итоговый = request.args.get('итоговый', '0') == '1'
    портрет  = request.args.get('портрет',  '0') == '1'
    итог, группы = _зачёт_все(sor_id)
    таблица_зс = _таблица_зс() if итоговый else None
    return render_template('зачет/протокол.html',
                           сор=сор,
                           итог=итог,
                           группы=группы,
                           ПОЛ_НАЗВ=ПОЛ_НАЗВ,
                           итоговый=итоговый,
                           портрет=портрет,
                           таблица_зс=таблица_зс,
                           сегодня=date.today())
