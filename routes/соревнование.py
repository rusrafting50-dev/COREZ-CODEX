def _получить_виды(сор):
    """Распарсить JSON-список видов программы. Возвращает список dict."""
    if not сор or not сор.виды_список:
        return []
    try:
        return json.loads(сор.виды_список)
    except (ValueError, TypeError):
        return []



def _применить_виды(сор, form):
    """Сохранить виды программы из массивов формы в JSON-поле и старые поля."""
    дисц_список  = form.getlist('виды_дисциплина[]')
    пол_список   = form.getlist('виды_пол_возраст[]')
    посл2_список = form.getlist('виды_посл_2[]')
    посл3_список = form.getlist('виды_посл_3[]')
    посл4_список = form.getlist('виды_посл_4[]')
    # Дополняем до одинаковой длины
    n = len(дисц_список)
    посл2_список += [''] * n
    посл3_список += [''] * n
    посл4_список += [''] * n
    виды = [
        {
            'дисциплина':      д.strip(),
            'пол_возраст':     п.strip(),
            'последовательность': f"{посл2_список[i].strip()},{посл3_список[i].strip()},{посл4_список[i].strip()}",
        }
        for i, (д, п) in enumerate(zip(дисц_список, пол_список))
        if д.strip()
    ]
    сор.виды_список = json.dumps(виды, ensure_ascii=False) if виды else None
    # Обновить старые поля кодов для совместимости с системой результатов
    for поле in set(_ДИСЦ_К_ПОЛЮ.values()):
        setattr(сор, поле, None)
    for вид in виды:
        поле = _ДИСЦ_К_ПОЛЮ.get(вид['дисциплина'])
        if поле:
            setattr(сор, поле, КОДЫ_ВРВС.get(вид['дисциплина']))


