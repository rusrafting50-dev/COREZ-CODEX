def _применить_статус(сор, код):
    """Заполнить статус и уровень из кода соревнований."""
    сор.код_соревнований = код
    if код in СТАТУСЫ:
        сор.статус  = СТАТУСЫ[код]['статус']
        сор.уровень = СТАТУСЫ[код]['уровень']


