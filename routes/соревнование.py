def _применить_параметры_дипломов(sor_id, form):
    """Сохранить или обновить НаграждениеПараметры из данных формы."""
    пар = НаграждениеПараметры.query.filter_by(соревнование_id=sor_id).first()
    if not пар:
        пар = НаграждениеПараметры(соревнование_id=sor_id)
        db.session.add(пар)
    пар.использует_награждается   = form.get('использует_награждается') == '1'
    пар.отступ_сверху             = int(form.get('отступ_сверху') or 75)
    пар.отступ_снизу              = int(form.get('отступ_снизу') or 25)
    пар.отступ_слева              = int(form.get('отступ_слева') or 15)
    пар.отступ_справа             = int(form.get('отступ_справа') or 15)
    пар.наименование_соревнований = form.get('наименование_соревнований', '').strip() or None
    пар.должность_подписывающего  = form.get('должность_подписывающего', '').strip() or None
    пар.ио_фамилия_подписывающего = form.get('ио_фамилия_подписывающего', '').strip() or None


def _применить_статус(сор, код):
    """Заполнить статус и уровень из кода соревнований."""
    сор.код_соревнований = код
    if код in СТАТУСЫ:
        сор.статус  = СТАТУСЫ[код]['статус']
        сор.уровень = СТАТУСЫ[код]['уровень']


def _получить_программу(сор):
    """Распарсить JSON-расписание соревнования. Возвращает список dict."""
    if not сор or not сор.программа_соревнований:
        return []
    try:
        return json.loads(сор.программа_соревнований)
    except (ValueError, TypeError):
        return []


def _сохранить_программу(сор, form):
    """Сохранить расписание мероприятий из массивов формы в JSON-поле."""
    названия = form.getlist('прог_название[]')
    даты     = form.getlist('прог_дата[]')
    времена  = form.getlist('прог_время[]')
    программа = [
        {'наименование': н.strip(), 'дата': д.strip(), 'время': в.strip()}
        for н, д, в in zip(названия, даты, времена)
        if н.strip() or д.strip() or в.strip()
    ]
    сор.программа_соревнований = (
        json.dumps(программа, ensure_ascii=False) if программа else None
    )


