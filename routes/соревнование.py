@bp_соревнование.route('/<int:id>')
def карточка(id):
    сор = Соревнование.query.get_or_404(id)

    кол_спортсменов = sum(len(к.спортсмены) for к in сор.команды)

    def _есть(model, **flt):
        return model.query.filter_by(соревнование_id=id, **flt).first() is not None

    готов = {
        'организаторы': bool(сор.организатор_1 or сор.организатор_2 or
                             сор.организатор_3 or сор.организатор_4),
        'субъекты':   len(сор.субъекты) > 0,
        'команды':    len(сор.команды)  > 0,
        'спортсмены': кол_спортсменов   > 0,
        'судьи':      len(сор.судьи)    > 0,
        'спринт':     РезультатСпринт.query.filter(
            РезультатСпринт.соревнование_id == id,
            РезультатСпринт.место.isnot(None)).first() is not None,
        'пс':         РезультатПараллельногоСпринта.query.filter(
            РезультатПараллельногоСпринта.соревнование_id == id,
            РезультатПараллельногоСпринта.итоговое_место.isnot(None)).first() is not None,
        'слалом':     РезультатСлалома.query.filter(
            РезультатСлалома.соревнование_id == id,
            РезультатСлалома.место.isnot(None)).first() is not None,
        'дг':         РезультатДлиннойГонки.query.filter(
            РезультатДлиннойГонки.соревнование_id == id,
            РезультатДлиннойГонки.место.isnot(None)).first() is not None,
        'многоборье': РезультатМногоборья.query.filter(
            РезультатМногоборья.соревнование_id == id,
            РезультатМногоборья.место.isnot(None)).first() is not None,
        'зачет':      ЗачётСубъектов.query.filter(
            ЗачётСубъектов.соревнование_id == id,
            ЗачётСубъектов.место.isnot(None)).first() is not None,
    }

    return render_template('соревнование/карточка.html',
                           сор=сор, статусы=СТАТУСЫ,
                           готов=готов, кол_спортсменов=кол_спортсменов)


@bp_соревнование.route('/<int:id>/редактировать', methods=['GET', 'POST'])
def редактировать(id):
    сор = Соревнование.query.get_or_404(id)
    if request.method == 'POST':
        сор.название                      = request.form['название'].strip()
        сор.даты_проведения               = request.form.get('даты_проведения', '').strip()
        сор.место_проведения              = request.form.get('место_проведения', '').strip()
        сор.класс_судна                   = _класс_из_формы(request.form)
        сор.возрастная_группа             = request.form.get('возрастная_группа', '').strip()
        сор.кол_мужских_экипажей          = _int_or_none(request.form.get('кол_мужских_экипажей'))
        сор.кол_женских_экипажей          = _int_or_none(request.form.get('кол_женских_экипажей'))
        сор.кол_попыток_слалом            = int(request.form.get('кол_попыток_слалом') or 2)
        сор.кол_спортсменов_в_экипаже     = int(request.form.get('кол_спортсменов_в_экипаже') or 4)
        сор.кол_субъектов                 = _int_or_none(request.form.get('кол_субъектов'))
        сор.код_субъекта_рф               = _int_or_none(request.form.get('код_субъекта_рф'))
        _применить_статус(сор, request.form.get('код_соревнований', '').strip())
        _применить_виды(сор, request.form)
        db.session.commit()
        flash('Данные сохранены.', 'success')
        return redirect(url_for('соревнование.карточка', id=сор.id))
    return render_template('соревнование/форма.html', сор=сор, статусы=СТАТУСЫ)


