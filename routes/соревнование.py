_ВИДЫ_ПОЛЯ = {
    'спринт':     'код_спринт',
    'пс':         'код_параллельный_спринт',
    'слалом':     'код_слалом',
    'дг':         'код_длинная_гонка',
    'многоборье': 'код_многоборье',
}


def _применить_статус(сор, код):
    """Заполнить статус и уровень из кода соревнований."""
    сор.код_соревнований = код
    if код in СТАТУСЫ:
        сор.статус  = СТАТУСЫ[код]['статус']
        сор.уровень = СТАТУСЫ[код]['уровень']


def _применить_виды(сор, form):
    """Сохранить виды программы (коды ВРВС) из массивов формы."""
    for поле in _ВИДЫ_ПОЛЯ.values():
        setattr(сор, поле, None)
    дисц_список = form.getlist('виды_дисц[]')
    код_список  = form.getlist('виды_код[]')
    for дисц, код in zip(дисц_список, код_список):
        поле = _ВИДЫ_ПОЛЯ.get(дисц)
        if поле and код.strip():
            setattr(сор, поле, код.strip())


