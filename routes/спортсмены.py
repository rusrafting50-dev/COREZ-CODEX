# ── JSON-поиск по базе всех соревнований ─────────────────────────────────────

@bp_спортсмены.route('/поиск')
def поиск():
    """Поиск спортсмена по ФИО (AJAX). Возвращает JSON-список: локальные
    записи COREZ + живой поиск по базе сборной REGTEAM_RAFTING."""
    q = request.args.get('q', '').strip()
    if len(q) < 2:
        return jsonify([])
    записи = (Спортсмен.query
              .filter(Спортсмен.фамилия_имя_отчество.ilike(f'%{q}%'))
              .order_by(Спортсмен.фамилия_имя_отчество, Спортсмен.id.desc())
              .limit(50)
              .all())
    # Дедупликация: по ФИО берём последнюю запись (наиболее актуальные данные)
    seen: dict = {}
    for с in записи:
        key = с.фамилия_имя_отчество.strip().lower()
        if key not in seen:
            seen[key] = с
    местные = [
        {
            'фио':          с.фамилия_имя_отчество,
            'дата_рождения': с.дата_рождения.isoformat() if с.дата_рождения else '',
            'пол':          с.пол,
            'разряд':       с.разряд or '',
            'номер_в_базе': с.номер_в_базе or '',
            'источник':     'COREZ',
        }
        for с in seen.values()
    ]

    # Подмешиваем живой поиск по базе REGTEAM_RAFTING — она хранит полный
    # список спортсменов сборной (а не только когда-либо участвовавших в
    # соревнованиях COREZ). При совпадении номер_в_базе предпочитаем
    # запись REGTEAM_RAFTING как более актуальную. В офлайн-режиме внешние
    # запросы не выполняются вовсе, чтобы не ждать впустую таймаут.
    удалённые = []
    if not получить_настройки().офлайн_режим:
        удалённые = [dict(с, источник='REGTEAM_RAFTING') for с in sync_regteam_rafting.найти_спортсменов(q)]
    удалённые_номера = {с['номер_в_базе'] for с in удалённые if с.get('номер_в_базе')}
    местные = [с for с in местные if not (с['номер_в_базе'] and с['номер_в_базе'] in удалённые_номера)]

    результат = sorted(местные + удалённые, key=lambda x: x['фио'])
    return jsonify(результат)


