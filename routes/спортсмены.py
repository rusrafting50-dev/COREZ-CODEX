# ── Вспомогательные функции ───────────────────────────────────────────────────

def _занятые_номера_в_экипажах(команды, исключить_спортсмена=None) -> dict:
    """Возвращает dict {команда_id: [занятые номера_в_экипаже]}."""
    результат = {}
    for к in команды:
        занятые = []
        for с in к.спортсмены:
            if с.номер_в_экипаже and (исключить_спортсмена is None or с.id != исключить_спортсмена.id):
                занятые.append(с.номер_в_экипаже)
        результат[к.id] = занятые
    return результат


def _валидировать_состав(команда) -> list[str]:
    """Проверить состав экипажа. Возвращает список ошибок (пустой = ОК)."""
    errors = []
    мин = 4 if команда.класс_судна == 'R4' else 6
    n = len(команда.спортсмены)
    if n == 0:
        errors.append(f'Нет спортсменов в составе')
    elif n < мин:
        errors.append(f'Состав неполный: {n} из {мин}')
    for с in команда.спортсмены:
        if not с.дата_рождения:
            фам = с.фамилия_имя_отчество.split()[0] if с.фамилия_имя_отчество else '?'
            errors.append(f'{фам}: нет даты рождения')
        if not с.разряд or с.разряд == 'б/р':
            фам = с.фамилия_имя_отчество.split()[0] if с.фамилия_имя_отчество else '?'
            errors.append(f'{фам}: нет спортивного разряда')
    return errors


def _int_or_none(val):
    try:
        return int(val) if val and str(val).strip() else None
    except (ValueError, TypeError):
        return None


def _parse_date(val):
    if not val or not str(val).strip():
        return None
    try:
        return date.fromisoformat(val.strip())
    except ValueError:
        return None
