# ── Время ──────────────────────────────────────────────────────────────────────

def parse_time(val):
    """ЧЧ:ММ:СС.сс → секунды (float). None если пусто/некорректно."""
    if not val or not str(val).strip():
        return None
    val = str(val).strip().replace(',', '.')
    m = re.match(r'^(\d{1,2}):(\d{2}):(\d{2})(?:\.(\d{1,2}))?$', val)
    if not m:
        return None
    h, mm, s = int(m[1]), int(m[2]), int(m[3])
    cc = int((m[4] or '').ljust(2, '0')[:2])
    return float(h * 3600 + mm * 60 + s) + cc / 100


def format_time(secs):
    """Секунды → ЧЧ:ММ:СС.сс."""
    if secs is None:
        return ''
    secs = float(secs)
    h = int(secs // 3600)
    rest = secs % 3600
    m = int(rest // 60)
    sv = rest % 60
    si = int(sv)
    cc = min(99, round((sv - si) * 100))
    return f'{h:02d}:{m:02d}:{si:02d}.{cc:02d}'


def format_time_hms(secs):
    """Секунды → ЧЧ:ММ:СС (без сотых, для печатных протоколов)."""
    if secs is None:
        return ''
    secs = float(secs)
    h = int(secs // 3600)
    m = int((secs % 3600) // 60)
    si = int(secs % 60)
    return f'{h:02d}:{m:02d}:{si:02d}'


def format_dur(secs):
    """Секунды → М:СС.сс (для отображения длительности)."""
    if secs is None:
        return '–'
    secs = float(secs)
    neg = secs < 0
    secs = abs(secs)
    m = int(secs // 60)
    sv = secs % 60
    si = int(sv)
    cc = min(99, round((sv - si) * 100))
    return ('-' if neg else '') + f'{m}:{si:02d}.{cc:02d}'


