@bp_спринт.route('/<int:sor_id>/штраф', methods=['POST'])
def штраф(sor_id):
    """AJAX (мобильные страницы старта/финиша): изменить штраф +10с/+50с на
    старте, +50с на финише или ДК одним нажатием."""
    данные = request.get_json(silent=True) or request.form
    тип = данные.get('тип')
    try:
        команда_id = int(данные.get('команда_id'))
    except (TypeError, ValueError):
        return jsonify(ok=False, ошибка='Некорректные данные'), 400
    if тип not in ('с10', 'с50', 'ф50', 'дк'):
        return jsonify(ok=False, ошибка='Некорректные данные'), 400

    к = Команда.query.filter_by(id=команда_id, соревнование_id=sor_id).first()
    if not к:
        return jsonify(ok=False, ошибка='Команда не найдена'), 404

    рез = _получить_или_создать(к, sor_id)
    if тип == 'дк':
        рез.статус = СТАТУС_ДК if данные.get('знач') else СТАТУС_ФИНИШ
    else:
        try:
            знач = max(0, min(9, int(данные.get('знач', 0))))
        except (TypeError, ValueError):
            return jsonify(ok=False, ошибка='Некорректные данные'), 400
        поле = {'с10': 'штраф_с10', 'с50': 'штраф_с50', 'ф50': 'штраф_ф50'}[тип]
        setattr(рез, поле, знач)
    _пересчитать_лёгкий(рез)
    db.session.commit()
    return jsonify(ok=True, дк=(рез.статус == СТАТУС_ДК))


@bp_спринт.route('/<int:sor_id>/результаты/обновления')
def результаты_обновления(sor_id):
    """JSON для автообновления страницы «Результаты заездов»: время и штрафы,
    введённые с мобильных страниц старта/финиша, без перезагрузки."""
    команды = Команда.query.filter_by(соревнование_id=sor_id).all()
    данные = {}
    for к in команды:
        р = к.результат_спринт
        данные[к.id] = {
            'время_старта': format_time(р.время_старта) if р and р.время_старта else '',
            'время_финиша': format_time(р.время_финиша) if р and р.время_финиша else '',
            'с10': р.штраф_с10 if р else 0,
            'с50': р.штраф_с50 if р else 0,
            'ф50': р.штраф_ф50 if р else 0,
            'статус': р.статус if р else СТАТУС_ФИНИШ,
            'время': format_dur(р.время_прохождения) if р and р.время_прохождения else '—',
            'штраф': format_dur(р.штрафное_время) if р and р.штрафное_время else '0:00.00',
            'результат': format_dur(р.результат) if р and р.результат else '—',
        }
    return jsonify(данные)


