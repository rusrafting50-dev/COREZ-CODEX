# routes/спринт.py — дистанция СПРИНТ: ввод времён, штрафов, расчёт результатов
import re
from datetime import date
from flask import Blueprint, render_template, request, redirect, url_for, flash
from models import (db, Соревнование, Команда, РезультатСпринт,
                    ТаблицаОчков, ТаблицаРазрядов,
                    СТАТУС_ФИНИШ, СТАТУС_ДНС, СТАТУС_ДНФ, СТАТУС_ДК, СТАТУС_ПМ)

bp_спринт = Blueprint('спринт', __name__)

СТАТУСЫ_СПИСОК = [
    (СТАТУС_ФИНИШ, 'Финишировал'),
    (СТАТУС_ДНФ,   'Не финишировал'),
    (СТАТУС_ДК,    'Дисквалифицирован'),
    (СТАТУС_ПМ,    'Последнее место'),
    (СТАТУС_ДНС,   'Не стартовал'),
]

СТАТУС_ЦВЕТ = {
    СТАТУС_ФИНИШ: 'success',
    СТАТУС_ДНФ:   'warning',
    СТАТУС_ДК:    'danger',
    СТАТУС_ПМ:    'secondary',
    СТАТУС_ДНС:   'dark',
}


# ── Время ──────────────────────────────────────────────────────────────────────

def parse_time(val):
    """ЧЧ:ММ:СС.сс → секунды (float). None если пусто/некорректно."""
    if not val or not str(val).strip():
        return None
    val = str(val).strip().replace(',', '.')
    m = re.match(r'^(\d{1,2}):(\d{2}):(\d{2})(?:\.(\d{1,2}))?$', val)
    if not m:
        return None
    h, mm, s = int(m[1]), int(m[2]), int(m[3])
    cc = int((m[4] or '').ljust(2, '0')[:2])
    return float(h * 3600 + mm * 60 + s) + cc / 100


def format_time(secs):
    """Секунды → ЧЧ:ММ:СС.сс."""
    if secs is None:
        return ''
    secs = float(secs)
    h = int(secs // 3600)
    rest = secs % 3600
    m = int(rest // 60)
    sv = rest % 60
    si = int(sv)
    cc = min(99, round((sv - si) * 100))
    return f'{h:02d}:{m:02d}:{si:02d}.{cc:02d}'


def format_dur(secs):
    """Секунды → М:СС.сс (для отображения длительности)."""
    if secs is None:
        return '—'
    secs = float(secs)
    neg = secs < 0
    secs = abs(secs)
    m = int(secs // 60)
    sv = secs % 60
    si = int(sv)
    cc = min(99, round((sv - si) * 100))
    return ('-' if neg else '') + f'{m}:{si:02d}.{cc:02d}'


# ── Вспомогательные функции ────────────────────────────────────────────────────

def _по_старту(sor_id, пол):
    """Команды в стартовом порядке."""
    команды = Команда.query.filter_by(соревнование_id=sor_id, пол=пол).all()
    return sorted(команды,
                  key=lambda к: (к.стартовый_номер_спринт or 9999, к.нагрудный_номер))


def _получить_или_создать(к, sor_id):
    рез = к.результат_спринт
    if not рез:
        рез = РезультатСпринт(
            команда_id=к.id,
            соревнование_id=sor_id,
            стартовый_номер=к.стартовый_номер_спринт,
        )
        db.session.add(рез)
        db.session.flush()
    return рез


def _int0(val):
    try:
        return max(0, int(val or 0))
    except (ValueError, TypeError):
        return 0


def _рассчитать(sor_id, пол):
    """Рассчитать места/очки/разряды. Возвращает (с_местом, без_места, разряды_dict)."""
    сор = Соревнование.query.get(sor_id)
    код = сор.код_соревнований if сор else None

    с_местом = []
    без_места = []

    for к in _по_старту(sor_id, пол):
        рез = к.результат_спринт
        if not рез:
            continue

        рез.штрафное_время = (
            _int0(рез.штраф_с10) * 10 +
            _int0(рез.штраф_с50) * 50 +
            _int0(рез.штраф_ф50) * 50
        )
        рез.кол_штраф_старт = _int0(рез.штраф_с10) + _int0(рез.штраф_с50)
        рез.кол_штраф_финиш = _int0(рез.штраф_ф50)

        if рез.статус in (СТАТУС_ДК, СТАТУС_ДНФ, СТАТУС_ДНС):
            рез.результат = None
            рез.место = None
            рез.очки = 0
            без_места.append(рез)
            continue

        if рез.время_старта is not None and рез.время_финиша is not None:
            рез.время_прохождения = рез.время_финиша - рез.время_старта

        if рез.статус == СТАТУС_ПМ:
            рез.результат = None
            с_местом.append((float('inf'), рез))
        elif рез.время_прохождения is not None:
            рез.результат = рез.время_прохождения + рез.штрафное_время
            с_местом.append((рез.результат, рез))
        else:
            без_места.append(рез)

    с_местом.sort(key=lambda x: x[0])

    разряды = {}
    for i, (_, рез) in enumerate(с_местом, 1):
        рез.место = i
        оч = ТаблицаОчков.query.filter_by(дистанция='СПРИНТ', место=i).first()
        рез.очки = оч.очки if оч else 0
        if код:
            р = ТаблицаРазрядов.query.filter_by(тип='С', место=i, статус_код=код).first()
            разряды[рез.команда_id] = р.разряд if р and р.разряд and р.разряд != '-' else '—'

    db.session.commit()
    return [рез for _, рез in с_местом], без_места, разряды


