@bp_спринт.route('/<int:sor_id>/протокол-старт-word')
def протокол_старт_word(sor_id):
    from docx_utils import create_старт_спринт_docx
    портрет = request.args.get('портрет', '1') == '1'
    сор = Соревнование.query.get_or_404(sor_id)
    последовательность = (сор.последовательность_видов or 'R4-м,R4-ж,R6-м,R6-ж').split(',')
    вывод = сор.вывод_старт_протокола or 'Попарно'
    LABELS = {
        'R4-м': 'Спринт – R4, Мужчины',
        'R4-ж': 'Спринт – R4, Женщины',
        'R6-м': 'Спринт – R6, Мужчины',
        'R6-ж': 'Спринт – R6, Женщины',
    }
    DATA = {
        'R4-м': _по_старту_класс(sor_id, 'м', 'R4'),
        'R4-ж': _по_старту_класс(sor_id, 'ж', 'R4'),
        'R6-м': _по_старту_класс(sor_id, 'м', 'R6'),
        'R6-ж': _по_старту_класс(sor_id, 'ж', 'R6'),
    }
    секции = [(LABELS[код], DATA[код]) for код in последовательность if код in LABELS]
    if вывод == 'Раздельно':
        # Each section gets its own protocol block
        группы = [[с] for с in секции]
    else:
        # "Попарно": positions 0+1 → first block, 2+3 → second block (mirrors HTML template)
        group1 = секции[:2]
        group2 = секции[2:]
        группы = [g for g in [group1, group2] if g]
    return create_старт_спринт_docx(сор, группы, f'протокол_старт_спринт_{sor_id}.docx', портрет=портрет)


