    штраф_по_команде = _штрафы_по_команде_моб(команды)
    замок = session.get('киоск_спринт_старт')
    закреплено = bool(замок and замок.get('sor_id') == sor_id)
    return render_template('спринт/старт_время.html',
                           сор=сор, команды=команды,
                           время_по_команде=время_по_команде,
                           штраф_по_команде=штраф_по_команде,
                           закреплено=закреплено, format_time=format_time)


