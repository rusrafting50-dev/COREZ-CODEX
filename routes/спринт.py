# ── Результаты ────────────────────────────────────────────────────────────────

@bp_спринт.route('/<int:sor_id>/результаты', methods=['GET', 'POST'])
def результаты(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    if request.method == 'POST':
        допустимые = {s for s, _ in СТАТУСЫ_СПИСОК}
        for пол in ('м', 'ж'):
            for к in _по_старту(sor_id, пол):
                рез = _получить_или_создать(к, sor_id)
                рез.стартовый_номер = к.стартовый_номер_спринт
                рез.время_старта = parse_time(request.form.get(f'вс_{к.id}', ''))
                рез.штраф_с10 = _int0(request.form.get(f'с10_{к.id}'))
                рез.штраф_с50 = _int0(request.form.get(f'с50_{к.id}'))
                рез.время_финиша = parse_time(request.form.get(f'вф_{к.id}', ''))
                рез.штраф_ф50 = _int0(request.form.get(f'ф50_{к.id}'))
                if request.form.get(f'дк_{к.id}'):
                    рез.статус = СТАТУС_ДК
                else:
                    ст = request.form.get(f'ст_{к.id}', СТАТУС_ФИНИШ)
                    if ст in допустимые:
                        рез.статус = ст
        db.session.commit()
        flash('Данные сохранены.', 'success')
        return redirect(url_for('спринт.результаты', sor_id=sor_id))
    муж_рез, муж_без, муж_разр = _рассчитать(sor_id, 'м')
    жен_рез, жен_без, жен_разр = _рассчитать(sor_id, 'ж')
    return render_template('спринт/результаты.html',
                           сор=сор,
                           муж_рез=муж_рез, муж_без=муж_без, муж_разр=муж_разр,
                           жен_рез=жен_рез, жен_без=жен_без, жен_разр=жен_разр,
                           format_time=format_time, format_dur=format_dur,
                           ЦВЕТ=СТАТУС_ЦВЕТ, СТАТУСЫ=СТАТУСЫ_СПИСОК,
                           СТАТУС_ДК=СТАТУС_ДК, СТАТУС_ФИНИШ=СТАТУС_ФИНИШ,
                           сегодня=date.today())


# ── Печатные формы ────────────────────────────────────────────────────────────

def _по_старту_класс(sor_id, пол, класс):
    команды = Команда.query.filter_by(соревнование_id=sor_id, пол=пол, класс_судна=класс).all()
    return sorted(команды, key=lambda к: (к.стартовый_номер_спринт or 9999, к.нагрудный_номер))


@bp_спринт.route('/<int:sor_id>/протокол-старт')
def протокол_старт(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    последовательность = (сор.последовательность_видов or 'R4-м,R4-ж,R6-м,R6-ж').split(',')
    вывод = сор.вывод_старт_протокола or 'Попарно'
    муж_р4 = _по_старту_класс(sor_id, 'м', 'R4')
    жен_р4 = _по_старту_класс(sor_id, 'ж', 'R4')
    муж_р6 = _по_старту_класс(sor_id, 'м', 'R6')
    жен_р6 = _по_старту_класс(sor_id, 'ж', 'R6')
    return render_template('спринт/протокол_старт.html',
                           сор=сор,
                           муж_р4=муж_р4,
                           жен_р4=жен_р4,
                           муж_р6=муж_р6,
                           жен_р6=жен_р6,
                           последовательность=последовательность,
                           вывод=вывод,
                           format_time=format_time, сегодня=date.today())


@bp_спринт.route('/<int:sor_id>/протокол-финиш')
def протокол_финиш(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    муж = _по_старту(sor_id, 'м')
    жен = _по_старту(sor_id, 'ж')
    return render_template('спринт/протокол_финиш.html',
                           сор=сор, муж=муж, жен=жен,
                           format_time=format_time,
                           ЦВЕТ=СТАТУС_ЦВЕТ, сегодня=date.today())


@bp_спринт.route('/<int:sor_id>/протокол-результаты')
def протокол_результаты(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    муж_рез, муж_без, муж_разр = _рассчитать(sor_id, 'м')
    жен_рез, жен_без, жен_разр = _рассчитать(sor_id, 'ж')
    итоговый = request.args.get('итоговый', '0') == '1'
    портрет = request.args.get('портрет', '0') == '1'
    кл = request.args.get('класс', None)
    if кл:
        муж_рез = [р for р in муж_рез if р.команда.класс_судна == кл]
        муж_без = [р for р in муж_без if р.команда.класс_судна == кл]
        жен_рез = [р for р in жен_рез if р.команда.класс_судна == кл]
        жен_без = [р for р in жен_без if р.команда.класс_судна == кл]
    return render_template('спринт/протокол_результаты.html',
                           сор=сор,
                           муж_рез=муж_рез, муж_без=муж_без, муж_разр=муж_разр,
                           жен_рез=жен_рез, жен_без=жен_без, жен_разр=жен_разр,
                           format_time=format_time, format_dur=format_dur,
                           ЦВЕТ=СТАТУС_ЦВЕТ,
                           класс=кл, итоговый=итоговый, портрет=портрет,
                           сегодня=date.today())
