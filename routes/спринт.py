# ── Время ──────────────────────────────────────────────────────────────────────

def parse_time(val):
    """ЧЧ:ММ:СС.сс → секунды (float). None если пусто/некорректно."""
    if not val or not str(val).strip():
        return None
    val = str(val).strip().replace(',', '.')
    m = re.match(r'^(\d{1,2}):(\d{2}):(\d{2})(?:\.(\d{1,2}))?$', val)
    if not m:
        return None
    h, mm, s = int(m[1]), int(m[2]), int(m[3])
    cc = int((m[4] or '').ljust(2, '0')[:2])
    return float(h * 3600 + mm * 60 + s) + cc / 100


def format_time(secs):
    """Секунды → ЧЧ:ММ:СС.сс."""
    if secs is None:
        return ''
    secs = float(secs)
    h = int(secs // 3600)
    rest = secs % 3600
    m = int(rest // 60)
    sv = rest % 60
    si = int(sv)
    cc = min(99, round((sv - si) * 100))
    return f'{h:02d}:{m:02d}:{si:02d}.{cc:02d}'


def format_time_hms(secs):
    """Секунды → ЧЧ:ММ:СС (без сотых, для печатных протоколов)."""
    if secs is None:
        return ''
    secs = float(secs)
    h = int(secs // 3600)
    m = int((secs % 3600) // 60)
    si = int(secs % 60)
    return f'{h:02d}:{m:02d}:{si:02d}'


def format_dur(secs):
    """Секунды → М:СС.сс (для отображения длительности)."""
    if secs is None:
        return '–'
    secs = float(secs)
    neg = secs < 0
    secs = abs(secs)
    m = int(secs // 60)
    sv = secs % 60
    si = int(sv)
    cc = min(99, round((sv - si) * 100))
    return ('-' if neg else '') + f'{m}:{si:02d}.{cc:02d}'


# ── Вспомогательные функции ────────────────────────────────────────────────────

def _по_старту(sor_id, пол):
    """Команды в стартовом порядке."""
    команды = Команда.query.filter_by(соревнование_id=sor_id, пол=пол).all()
    return sorted(команды,
                  key=lambda к: (к.стартовый_номер_спринт or 9999, к.нагрудный_номер))


def _порядок_старта_общий(sor_id):
    """Все команды (оба пола, все классы) в порядке реального старта:
    по фактическому времени старта (кто уже стартовал — раньше), затем те,
    кто ещё не стартовал — по стартовому номеру жеребьёвки."""
    команды = Команда.query.filter_by(соревнование_id=sor_id).all()

    def ключ(к):
        рез = к.результат_спринт
        t = рез.время_старта if рез else None
        if t is not None:
            return (0, t, к.стартовый_номер_спринт or 9999)
        return (1, 0.0, к.стартовый_номер_спринт or 9999)

    return sorted(команды, key=ключ)


def _сейчас_секунды_дня():
    """Текущее время на сервере как секунды с полуночи (для формата ЧЧ:ММ:СС.сс)."""
    now = datetime.now()
    return now.hour * 3600 + now.minute * 60 + now.second + now.microsecond / 1_000_000


def _время_по_команде(команды, поле):
    """{команда_id: время (сек) | None} для указанного поля ('время_старта'/'время_финиша')."""
    return {к.id: (getattr(к.результат_спринт, поле) if к.результат_спринт else None) for к in команды}


def _штрафы_по_команде_моб(команды):
    """{команда_id: {'с10', 'с50', 'ф50', 'дк'}} — для мобильных страниц старта/финиша."""
    result = {}
    for к in команды:
        р = к.результат_спринт
        result[к.id] = {
            'с10': р.штраф_с10 if р else 0,
            'с50': р.штраф_с50 if р else 0,
            'ф50': р.штраф_ф50 if р else 0,
            'дк':  bool(р and р.статус == СТАТУС_ДК),
        }
    return result


def _пересчитать_лёгкий(рез):
    """Быстрый пересчёт штрафного времени/результата одной команды (без мест и
    очков — это делает _рассчитать при просмотре страницы результатов)."""
    рез.штрафное_время = (
        _int0(рез.штраф_с10) * 10 +
        _int0(рез.штраф_с50) * 50 +
        _int0(рез.штраф_ф50) * 50
    )
    рез.кол_штраф_старт = _int0(рез.штраф_с10) + _int0(рез.штраф_с50)
    рез.кол_штраф_финиш = _int0(рез.штраф_ф50)
    if рез.время_старта is not None and рез.время_финиша is not None:
        рез.время_прохождения = рез.время_финиша - рез.время_старта
    if рез.статус in (СТАТУС_ДК, СТАТУС_ДНФ, СТАТУС_ДНС):
        рез.результат = None
    elif рез.время_прохождения is not None:
        рез.результат = рез.время_прохождения + рез.штрафное_время
    else:
        рез.результат = None


def _получить_или_создать(к, sor_id):
    рез = к.результат_спринт
    if not рез:
        рез = РезультатСпринт(
            команда_id=к.id,
            соревнование_id=sor_id,
            стартовый_номер=к.стартовый_номер_спринт,
        )
        db.session.add(рез)
        db.session.flush()
    return рез


def _int0(val):
    try:
        return max(0, int(val or 0))
    except (ValueError, TypeError):
        return 0


def _рассчитать(sor_id, пол, класс=None):
    """Рассчитать места/очки/разряды. Возвращает (с_местом, без_места, разряды_dict)."""
    сор = Соревнование.query.get(sor_id)
    код = сор.код_соревнований if сор else None

    с_местом = []
    без_места = []

    for к in _по_старту(sor_id, пол):
        if класс and к.класс_судна != класс:
            continue
        рез = к.результат_спринт
        if not рез:
            continue

        рез.штрафное_время = (
            _int0(рез.штраф_с10) * 10 +
            _int0(рез.штраф_с50) * 50 +
            _int0(рез.штраф_ф50) * 50
        )
        рез.кол_штраф_старт = _int0(рез.штраф_с10) + _int0(рез.штраф_с50)
        рез.кол_штраф_финиш = _int0(рез.штраф_ф50)

        if рез.статус in (СТАТУС_ДК, СТАТУС_ДНФ, СТАТУС_ДНС):
            рез.результат = None
            рез.место = None
            рез.очки = 0
            без_места.append(рез)
            continue

        if рез.время_старта is not None and рез.время_финиша is not None:
            рез.время_прохождения = рез.время_финиша - рез.время_старта

        if рез.статус == СТАТУС_ПМ:
            рез.результат = None
            с_местом.append(((2, 0), рез))
        elif рез.статус == СТАТУС_ПЛВ:
            рез.результат = None
            sort_val = (рез.время_прохождения or 0) + рез.штрафное_время
            с_местом.append(((1, sort_val), рез))
        elif рез.время_прохождения is not None:
            рез.результат = рез.время_прохождения + рез.штрафное_время
            с_местом.append(((0, рез.результат), рез))
        else:
            без_места.append(рез)

    с_местом.sort(key=lambda x: x[0])

    всего = len(с_местом) + len(без_места)
    разряды = {}
    for i, (sort_key, рез) in enumerate(с_местом, 1):
        if sort_key[0] == 0:
            рез.место = i
            оч = ТаблицаОчков.query.filter_by(дистанция='СПРИНТ', место=i).first()
            рез.очки = оч.очки if оч else 0
            разряды[рез.команда_id] = получить_норматив(код, сор.возрастная_группа if сор else None, 'С', i)
        else:
            рез.место = всего
            оч = ТаблицаОчков.query.filter_by(дистанция='СПРИНТ', место=всего).first()
            рез.очки = оч.очки if оч else 0

    db.session.commit()
    from routes.многоборье import обновить_мб_очки
    обновить_мб_очки(sor_id)
    return [рез for _, рез in с_местом], без_места, разряды


