@bp_дг.route('/<int:sor_id>/результаты', methods=['GET', 'POST'])
def результаты(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    допустимые = {s for s, _ in СТАТУСЫ_СПИСОК}

    if request.method == 'POST':
        for пол in ('м', 'ж'):
            for к in _по_посеву(sor_id, пол):
                рез = _get_or_create(к, sor_id)
                дк  = request.form.get(f'дк_{к.id}')     == '1'
                дк_фин = request.form.get(f'дк_фин_{к.id}') == '1'
                нфн = False
                ст = request.form.get(f'ст_{к.id}', СТАТУС_ФИНИШ)
                if дк or дк_фин:
                    ст = СТАТУС_ДК
                if ст not in допустимые:
                    ст = СТАТУС_ФИНИШ
                рез.время_старта     = parse_time(request.form.get(f'вс_{к.id}', ''))
                рез.время_финиша     = parse_time(request.form.get(f'вф_{к.id}', ''))
                рез.кол_штраф_с10   = _int0(request.form.get(f'с10_{к.id}', 0))
                рез.кол_штраф_старт = _int0(request.form.get(f'кс_{к.id}', 0))
                рез.кол_штраф_финиш = _int0(request.form.get(f'кф_{к.id}', 0))
                рез.статус = ст
                # обновить секционный штраф через ШтрафСекции
                секц_кол = _int0(request.form.get(f'секц_{к.id}', 0))
                ШтрафСекции.query.filter_by(команда_id=к.id, соревнование_id=sor_id).delete()
                if секц_кол:
                    db.session.add(ШтрафСекции(
                        команда_id=к.id, соревнование_id=sor_id,
                        номер_секции=1, кол_нарушений=секц_кол
                    ))
                _пересчитать(рез, сор)
        db.session.commit()
        flash('Результаты сохранены.', 'success')
        return redirect(url_for('дг.результаты', sor_id=sor_id))

    муж_фин, муж_пм, муж_без, муж_разр = _рассчитать_итог(sor_id, 'м')
    жен_фин, жен_пм, жен_без, жен_разр = _рассчитать_итог(sor_id, 'ж')
    секц_штраф = {}
    for к in Команда.query.filter_by(соревнование_id=sor_id).all():
        _, шт = _суммировать_секции(к.id, sor_id)
        секц_штраф[к.id] = шт
    return render_template('дг/результаты.html',
                           сор=сор,
                           муж_рез=муж_фин + муж_пм, муж_без=муж_без, муж_разр=муж_разр,
                           жен_рез=жен_фин + жен_пм, жен_без=жен_без, жен_разр=жен_разр,
                           секц_штраф=секц_штраф,
                           format_time=format_time, format_dur=format_dur,
                           сегодня=date.today(),
                           готов_наград=сор.готов_наград_дг,
                           СТАТУСЫ=СТАТУСЫ_СПИСОК, СТАТУС_ДК=СТАТУС_ДК)


