def _int0(val):
    try:
        return max(0, int(val or 0))
    except (ValueError, TypeError):
        return 0


def _parse_dur(val):
    """М:СС.сс → секунды. None если пусто/некорректно."""
    if not val or not str(val).strip():
        return None
    val = str(val).strip().replace(',', '.')
    m = re.match(r'^(\d+):(\d{2})(?:\.(\d{1,2}))?$', val)
    if not m:
        return None
    mins, secs = int(m[1]), int(m[2])
    cc = int((m[3] or '').ljust(2, '0')[:2])
    return float(mins * 60 + secs) + cc / 100


