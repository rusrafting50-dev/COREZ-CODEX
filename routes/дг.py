def _слалом_результат(к):
    """Лучший результат команды в слаломе (секунды) или None."""
    best = None
    for р in к.результат_слалом:
        if р.лучший_результат and (best is None or р.лучший_результат > best):
            best = р.лучший_результат
    return best


def _по_посеву(sor_id, пол):
    """Порядок очереди выбора позиции ДГ: по сумме МБ убыванию (больше → первый выбирает).

    Тайбрейкер — очки в последней дисциплине перед ДГ (тоже убыванием).
    Если «Сумма» нет — основной ключ по единственной отображаемой дисциплине.
    """
    сор = Соревнование.query.get(sor_id)
    команды = Команда.query.filter_by(соревнование_id=sor_id, пол=пол).all()

    _кэш_поля: dict = {}

    def _поля_вида(кл, п):
        key = (кл, п)
        if key not in _кэш_поля:
            колонки = _дисц_мб_для_вида_дг(сор, кл, п)
            дисц_поля = [кол['поле'] for кол in колонки if кол.get('поле')]
            тай = дисц_поля[-1] if дисц_поля else None
            _кэш_поля[key] = (дисц_поля, тай)
        return _кэш_поля[key]

    def _прямые_очки(к):
        рм = к.результат_многоборья
        return {
            'очки_спринт': float(рм.очки_спринт or 0) if рм else 0.0,
            'очки_пс':     float(рм.очки_пс     or 0) if рм else 0.0,
            'очки_слалом': float(рм.очки_слалом or 0) if рм else 0.0,
        }

    def ключ(к):
        дисц_поля, тай_поле = _поля_вида(к.класс_судна, к.пол)
        очки = _прямые_очки(к)
        сумма = sum(очки.get(п, 0.0) for п in дисц_поля)
        тай = очки.get(тай_поле, 0.0) if тай_поле else 0.0
        return (-сумма, -тай, к.нагрудный_номер or 9999)

    return sorted(команды, key=ключ)


_МБ_ДИСЦ_MAP_ДГ = {
    'Спринт':              {'заг': 'Спринт',               'поле': 'очки_спринт'},
    'Параллельный спринт': {'заг': 'Параллельный спринт',  'поле': 'очки_пс'},
    'Слалом':              {'заг': 'Слалом',               'поле': 'очки_слалом'},
}
_МБ_ПОРЯДОК_ДГ = ['Спринт', 'Параллельный спринт', 'Слалом']
_МБ_ЖЕНСКИЕ_ДГ = ('Женщин', 'Юниорки', 'Девушки')


def _пол_вида_дг(пол_возраст):
    return 'ж' if any(k in пол_возраст for k in _МБ_ЖЕНСКИЕ_ДГ) else 'м'


def _дисц_мб_для_вида_дг(сор, класс, пол):
    """Колонки Очки Многоборье для конкретного вида ДГ.

    Определяет дисциплины, идущие ДО Длинной гонки в последовательности данного вида.
    Сумма добавляется только если дисциплин 2 и более.
    """
    перед_дг = set()
    найдена_дг = False
    try:
        виды = json.loads(сор.виды_список) if сор and сор.виды_список else []
    except (ValueError, TypeError):
        виды = []

    for вид in виды:
        if вид.get('дисциплина', '').upper() != класс.upper():
            continue
        if _пол_вида_дг(вид.get('пол_возраст', '')) != пол:
            continue
        посл_str = вид.get('последовательность', '')
        посл = ['Спринт'] + [p.strip() for p in посл_str.split(',') if p.strip()]
        if 'Длинная гонка' in посл:
            найдена_дг = True
            idx = посл.index('Длинная гонка')
            for д in посл[:idx]:
                if д in _МБ_ДИСЦ_MAP_ДГ:
                    перед_дг.add(д)

    if not найдена_дг and сор:
        результаты = (РезультатМногоборья.query
                      .join(Команда, Команда.id == РезультатМногоборья.команда_id)
                      .filter(Команда.соревнование_id == сор.id,
                              Команда.класс_судна == класс,
                              Команда.пол == пол)
                      .all())
        if any(р.очки_спринт for р in результаты):
            перед_дг.add('Спринт')
        if any(р.очки_пс for р in результаты):
            перед_дг.add('Параллельный спринт')
        if any(р.очки_слалом for р in результаты):
            перед_дг.add('Слалом')

    колонки = [_МБ_ДИСЦ_MAP_ДГ[д] for д in _МБ_ПОРЯДОК_ДГ if д in перед_дг]
    if len(колонки) >= 2:
        колонки.append({'заг': 'Сумма', 'поле': None})
    return колонки


def _дисц_мб_по_коду_дг(сор):
    """Возвращает dict {вид_код: колонки} для четырёх групп ДГ."""
