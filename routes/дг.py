def _порядок_старта_общий(sor_id):
    """Все команды (оба пола, все классы) в порядке реального старта:
    по фактическому времени старта (кто уже стартовал — раньше), затем те,
    кто ещё не стартовал — по нагрудному номеру."""
    команды = Команда.query.filter_by(соревнование_id=sor_id).all()

    def ключ(к):
        рез = к.результат_дг
        t = рез.время_старта if рез else None
        if t is not None:
            return (0, t, к.нагрудный_номер or 9999)
        return (1, 0.0, к.нагрудный_номер or 9999)

    return sorted(команды, key=ключ)


def _сейчас_секунды_дня():
    """Текущее время на сервере как секунды с полуночи (для формата ЧЧ:ММ:СС.сс)."""
    now = datetime.now()
    return now.hour * 3600 + now.minute * 60 + now.second + now.microsecond / 1_000_000


def _время_по_команде(команды, поле):
    """{команда_id: время (сек) | None} для указанного поля ('время_старта'/'время_финиша')."""
    return {к.id: (getattr(к.результат_дг, поле) if к.результат_дг else None) for к in команды}


def _штрафы_по_команде_моб(команды):
    """{команда_id: {'с10', 'кс', 'кф', 'дк'}} — для мобильных страниц старта/финиша."""
    result = {}
    for к in команды:
        р = к.результат_дг
        result[к.id] = {
            'с10': р.кол_штраф_с10 if р else 0,
            'кс':  р.кол_штраф_старт if р else 0,
            'кф':  р.кол_штраф_финиш if р else 0,
            'дк':  bool(р and р.статус == СТАТУС_ДК),
        }
    return result


def _суммировать_секции(команда_id, sor_id):
    """Вернуть (total_кол_нарушений, суммарный_штраф_секций_сек)."""
    секции = ШтрафСекции.query.filter_by(
        команда_id=команда_id, соревнование_id=sor_id
    ).all()
    кол = sum(с.кол_нарушений for с in секции)
    return кол, кол * 50


def _штрафы_секций_по_команде(sor_id, пол):
    """Все нарушения для пола: {команда_id: {номер_секции: кол_нарушений}}."""
    ids = {к.id for к in Команда.query.filter_by(соревнование_id=sor_id, пол=пол).all()}
    все = (ШтрафСекции.query
           .filter_by(соревнование_id=sor_id)
           .filter(ШтрафСекции.команда_id.in_(ids))
           .all())
    result = {}
    for с in все:
        result.setdefault(с.команда_id, {})[с.номер_секции] = с.кол_нарушений
    return result


def _пересчитать(рез, сор):
    """Пересчитать штрафы, результат и лимит для одной записи."""
    _, штраф_секций = _суммировать_секции(рез.команда_id, сор.id)
    рез.штрафное_время = (рез.кол_штраф_с10 or 0) * 10 + (рез.кол_штраф_старт + рез.кол_штраф_финиш) * 50 + штраф_секций

    if рез.время_старта is not None and рез.время_финиша is not None:
        рез.время_прохождения = рез.время_финиша - рез.время_старта

    if рез.статус in (СТАТУС_ДК, СТАТУС_ДНФ, СТАТУС_ДНС, СТАТУС_ПЛВ):
        рез.результат = None
    elif рез.время_прохождения is not None and рез.время_прохождения > 0:
        рез.результат = рез.время_прохождения + рез.штрафное_время
        пол = рез.команда.пол
        лимит = сор.лимит_время_муж if пол == 'м' else сор.лимит_время_жен
        if лимит and рез.статус == СТАТУС_ФИНИШ and рез.время_прохождения > лимит:
            рез.статус = СТАТУС_ПМ
    else:
        рез.результат = None


def _рассчитать_итог(sor_id, пол, класс=None):
    """Рассчитать итоговые места. Вернуть (финишеры, пм, без_места, разряды)."""
    сор = Соревнование.query.get(sor_id)
    код = сор.код_соревнований if сор else None
    все_команды = _по_посеву(sor_id, пол)
    команды = [к for к in все_команды if not класс or к.класс_судна == класс]

    финишеры = []
    пм = []
    без_места = []

    for к in команды:
        рез = к.результат_дг
        if not рез:
            рез = РезультатДлиннойГонки(команда_id=к.id, соревнование_id=сор.id)
            db.session.add(рез)
            db.session.flush()
        _пересчитать(рез, сор)
        if рез.статус == СТАТУС_ФИНИШ and рез.результат is not None:
            финишеры.append((рез.результат, к, рез))
        elif рез.статус in (СТАТУС_ПМ, СТАТУС_ПЛВ):
            пм.append((рез.результат or float('inf'), к, рез))
        else:
            без_места.append(рез)

    финишеры.sort(key=lambda x: x[0])
    пм.sort(key=lambda x: x[0])
    разряды = {}
    место = 1

    for _, к, рез in финишеры:
        рез.место = место
        оч = ТаблицаОчков.query.filter_by(дистанция='ДЛИННАЯ_ГОНКА', место=место).first()
        рез.очки = оч.очки if оч else 0
        разряды[к.id] = получить_норматив(код, сор.возрастная_группа if сор else None, 'П', место)
        место += 1

    for _, к, рез in пм:
        рез.место = место
        рез.очки = 0
        место += 1

    for рез in без_места:
        рез.место = None
        рез.очки = 0

    db.session.commit()
    from routes.многоборье import обновить_мб_очки
    обновить_мб_очки(sor_id)
    return (
        [рез for _, _, рез in финишеры],
        [рез for _, _, рез in пм],
        [рез for рез in без_места],
        разряды,
    )


