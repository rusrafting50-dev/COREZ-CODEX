def _слалом_результат(к):
    """Лучший результат команды в слаломе (секунды) или None."""
    best = None
    for р in к.результат_слалом:
        if р.лучший_результат and (best is None or р.лучший_результат > best):
            best = р.лучший_результат
    return best


def _по_посеву(sor_id, пол):
    """Порядок очереди выбора позиции ДГ: по сумме МБ убыванию (больше → первый выбирает)."""
    команды = Команда.query.filter_by(соревнование_id=sor_id, пол=пол).all()

    def ключ(к):
        рм = к.результат_многоборья
        сумма = float(рм.сумма_очков) if рм and рм.сумма_очков else 0.0
        return (-сумма, к.нагрудный_номер or 9999)

    return sorted(команды, key=ключ)


_МБ_ДИСЦ_MAP_ДГ = {
    'Спринт':              {'заг': 'Спринт',               'поле': 'очки_спринт'},
    'Параллельный спринт': {'заг': 'Параллельный спринт',  'поле': 'очки_пс'},
    'Слалом':              {'заг': 'Слалом',               'поле': 'очки_слалом'},
}
_МБ_ПОРЯДОК_ДГ = ['Спринт', 'Параллельный спринт', 'Слалом']
_МБ_ЖЕНСКИЕ_ДГ = ('Женщин', 'Юниорки', 'Девушки')


def _пол_вида_дг(пол_возраст):
    return 'ж' if any(k in пол_возраст for k in _МБ_ЖЕНСКИЕ_ДГ) else 'м'


def _дисц_мб_для_вида_дг(сор, класс, пол):
    """Колонки Очки Многоборье для конкретного вида ДГ.

    Определяет дисциплины, идущие ДО Длинной гонки в последовательности данного вида.
    Сумма добавляется только если дисциплин 2 и более.
    """
    перед_дг = set()
    найдена_дг = False
    try:
        виды = json.loads(сор.виды_список) if сор and сор.виды_список else []
    except (ValueError, TypeError):
        виды = []

    for вид in виды:
        if вид.get('дисциплина', '').upper() != класс.upper():
            continue
        if _пол_вида_дг(вид.get('пол_возраст', '')) != пол:
            continue
        посл_str = вид.get('последовательность', '')
        посл = ['Спринт'] + [p.strip() for p in посл_str.split(',') if p.strip()]
        if 'Длинная гонка' in посл:
            найдена_дг = True
            idx = посл.index('Длинная гонка')
            for д in посл[:idx]:
                if д in _МБ_ДИСЦ_MAP_ДГ:
                    перед_дг.add(д)

    if not найдена_дг and сор:
        результаты = (РезультатМногоборья.query
                      .join(Команда, Команда.id == РезультатМногоборья.команда_id)
                      .filter(Команда.соревнование_id == сор.id,
                              Команда.класс_судна == класс,
                              Команда.пол == пол)
                      .all())
        if any(р.очки_спринт for р in результаты):
            перед_дг.add('Спринт')
        if any(р.очки_пс for р in результаты):
            перед_дг.add('Параллельный спринт')
        if any(р.очки_слалом for р in результаты):
            перед_дг.add('Слалом')

    колонки = [_МБ_ДИСЦ_MAP_ДГ[д] for д in _МБ_ПОРЯДОК_ДГ if д in перед_дг]
    if len(колонки) >= 2:
        колонки.append({'заг': 'Сумма', 'поле': None})
    return колонки


def _дисц_мб_по_коду_дг(сор):
    """Возвращает dict {вид_код: колонки} для четырёх групп ДГ."""
    return {
        'R4-м': _дисц_мб_для_вида_дг(сор, 'R4', 'м'),
        'R4-ж': _дисц_мб_для_вида_дг(сор, 'R4', 'ж'),
        'R6-м': _дисц_мб_для_вида_дг(сор, 'R6', 'м'),
        'R6-ж': _дисц_мб_для_вида_дг(сор, 'R6', 'ж'),
    }


def _get_or_create(к, sor_id):
    рез = к.результат_дг
    if not рез:
        рез = РезультатДлиннойГонки(команда_id=к.id, соревнование_id=sor_id)
        db.session.add(рез)
        db.session.flush()
    return рез


def _суммировать_секции(команда_id, sor_id):
    """Вернуть (total_кол_нарушений, суммарный_штраф_секций_сек)."""
    секции = ШтрафСекции.query.filter_by(
        команда_id=команда_id, соревнование_id=sor_id
    ).all()
    кол = sum(с.кол_нарушений for с in секции)
    return кол, кол * 50


def _штрафы_секций_по_команде(sor_id, пол):
    """Все нарушения для пола: {команда_id: {номер_секции: кол_нарушений}}."""
    ids = {к.id for к in Команда.query.filter_by(соревнование_id=sor_id, пол=пол).all()}
    все = (ШтрафСекции.query
           .filter_by(соревнование_id=sor_id)
           .filter(ШтрафСекции.команда_id.in_(ids))
           .all())
    result = {}
    for с in все:
        result.setdefault(с.команда_id, {})[с.номер_секции] = с.кол_нарушений
    return result


def _пересчитать(рез, сор):
    """Пересчитать штрафы, результат и лимит для одной записи."""
    _, штраф_секций = _суммировать_секции(рез.команда_id, сор.id)
    рез.штрафное_время = (рез.кол_штраф_с10 or 0) * 10 + (рез.кол_штраф_старт + рез.кол_штраф_финиш) * 50 + штраф_секций

    if рез.время_старта is not None and рез.время_финиша is not None:
        рез.время_прохождения = рез.время_финиша - рез.время_старта

    if рез.статус in (СТАТУС_ДК, СТАТУС_ДНФ, СТАТУС_ДНС, СТАТУС_ПЛВ):
        рез.результат = None
    elif рез.время_прохождения is not None and рез.время_прохождения > 0:
        рез.результат = рез.время_прохождения + рез.штрафное_время
        пол = рез.команда.пол
        лимит = сор.лимит_время_муж if пол == 'м' else сор.лимит_время_жен
        if лимит and рез.статус == СТАТУС_ФИНИШ and рез.время_прохождения > лимит:
            рез.статус = СТАТУС_ПМ
    else:
        рез.результат = None


def _рассчитать_итог(sor_id, пол, класс=None):
    """Рассчитать итоговые места. Вернуть (финишеры, пм, без_места, разряды)."""
    сор = Соревнование.query.get(sor_id)
    код = сор.код_соревнований if сор else None
    все_команды = _по_посеву(sor_id, пол)
    команды = [к for к in все_команды if not класс or к.класс_судна == класс]

    финишеры = []
    пм = []
    без_места = []

    for к in команды:
        рез = к.результат_дг
        if not рез:
            рез = РезультатДлиннойГонки(команда_id=к.id, соревнование_id=сор.id)
            db.session.add(рез)
            db.session.flush()
        _пересчитать(рез, сор)
        if рез.статус == СТАТУС_ФИНИШ and рез.результат is not None:
            финишеры.append((рез.результат, к, рез))
        elif рез.статус in (СТАТУС_ПМ, СТАТУС_ПЛВ):
            пм.append((рез.результат or float('inf'), к, рез))
        else:
            без_места.append(рез)

    финишеры.sort(key=lambda x: x[0])
    пм.sort(key=lambda x: x[0])
    разряды = {}
    место = 1

    for _, к, рез in финишеры:
        рез.место = место
        оч = ТаблицаОчков.query.filter_by(дистанция='ДЛИННАЯ_ГОНКА', место=место).first()
        рез.очки = оч.очки if оч else 0
        разряды[к.id] = получить_норматив(код, сор.возрастная_группа if сор else None, 'П', место)
        место += 1

    for _, к, рез in пм:
        рез.место = место
        рез.очки = 0
        место += 1

    for рез in без_места:
        рез.место = None
        рез.очки = 0

    db.session.commit()
    from routes.многоборье import обновить_мб_очки
    обновить_мб_очки(sor_id)
    return (
        [рез for _, _, рез in финишеры],
        [рез for _, _, рез in пм],
        [рез for рез in без_места],
        разряды,
    )


