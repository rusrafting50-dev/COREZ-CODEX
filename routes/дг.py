    муж = _по_посеву(sor_id, 'м')
    жен = _по_посеву(sor_id, 'ж')
    мб_по_коду = _дисц_мб_по_коду_дг(сор)
    муж_р4 = [к for к in муж if к.класс_судна == 'R4']
    муж_р6 = [к for к in муж if к.класс_судна == 'R6']
    жен_р4 = [к for к in жен if к.класс_судна == 'R4']
    жен_р6 = [к for к in жен if к.класс_судна == 'R6']
    последовательность = (сор.последовательность_дг or 'R4-м,R4-ж,R6-м,R6-ж').split(',')
    группы_map = {
        'R4-м': ('Длинная гонка – R4, Мужчины', муж_р4, мб_по_коду.get('R4-м', [])),
        'R4-ж': ('Длинная гонка – R4, Женщины', жен_р4, мб_по_коду.get('R4-ж', [])),
        'R6-м': ('Длинная гонка – R6, Мужчины', муж_р6, мб_по_коду.get('R6-м', [])),
        'R6-ж': ('Длинная гонка – R6, Женщины', жен_р6, мб_по_коду.get('R6-ж', [])),
    }
    секции = []
    for код in последовательность:
        if код not in группы_map:
            continue
        метка, команды, мб = группы_map[код]
        if команды:
            секции.append((метка, команды, мб))
    return create_старт_дг_docx(сор, секции, f'протокол_старт_дг_{sor_id}.docx', портрет=портрет)


