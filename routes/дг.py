@bp_дг.route('/<int:sor_id>/старт', methods=['GET', 'POST'])
def старт(sor_id):
    сор = Соревнование.query.get_or_404(sor_id)
    if request.method == 'POST':
        for пол in ('м', 'ж'):
            for к in _по_посеву(sor_id, пол):
                вс = parse_time(request.form.get(f'вс_{к.id}', ''))
                if вс is not None:
                    рез = _get_or_create(к, sor_id)
                    рез.время_старта = вс
        db.session.commit()
        flash('Стартовый протокол сохранён.', 'success')
        return redirect(url_for('дг.старт', sor_id=sor_id))

    муж = _по_посеву(sor_id, 'м')
    жен = _по_посеву(sor_id, 'ж')
    мб_по_коду = _дисц_мб_по_коду_дг(сор)
    виды_все = [
        ('R4-м', 'Длинная гонка – R4, мужчины'),
        ('R4-ж', 'Длинная гонка – R4, женщины'),
        ('R6-м', 'Длинная гонка – R6, мужчины'),
        ('R6-ж', 'Длинная гонка – R6, женщины'),
    ]
    текущий_порядок = (сор.последовательность_дг or 'R4-м,R4-ж,R6-м,R6-ж').split(',')
    return render_template('дг/старт.html',
                           сор=сор, муж=муж, жен=жен,
                           мб_по_коду=мб_по_коду,
                           виды_все=виды_все,
                           текущий_порядок=текущий_порядок,
                           format_time=format_time)


