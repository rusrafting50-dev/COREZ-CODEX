    последовательность = (сор.последовательность_дг or 'R4-м,R4-ж,R6-м,R6-ж').split(',')
    вывод = сор.вывод_старт_дг or 'Попарно'
    _данные = {
        'R4-м': (муж_р4, 'Длинная гонка – R4, Мужчины'),
        'R4-ж': (жен_р4, 'Длинная гонка – R4, Женщины'),
        'R6-м': (муж_р6, 'Длинная гонка – R6, Мужчины'),
        'R6-ж': (жен_р6, 'Длинная гонка – R6, Женщины'),
    }
    _все_коды = [к for к in последовательность if к in _данные and _данные[к][0]]
    if вывод == 'Попарно':
        страницы = []
        for i in range(0, len(_все_коды), 2):
            секции = [(_данные[к][1], _данные[к][0]) for к in _все_коды[i:i+2]]
            if секции:
                страницы.append(секции)
    else:
        страницы = [[(_данные[к][1], _данные[к][0])] for к in _все_коды]
    return сор, страницы


