# ── Многоборье ────────────────────────────────────────────────────────────────
# Многоборье — не отдельная дистанция с собственным протоколом, а сумма
# очков по остальным четырём. В самом COREZ routes.многоборье._рассчитать
# показывает только команды, завершившие ВСЕ 4 дисциплины (см.
# _имеет_все_результаты) — иначе команда просто не попадает в таблицу.
# На сайте же нужно, чтобы пункт "Многоборье" появился вместе со спринтом
# и заполнялся постепенно по мере проведения остальных дисциплин — поэтому
# здесь считаем по-другому: берём текущие очки_*/сумма_очков (их держит
# актуальными обновить_мб_очки(), вызываемая после пересчёта любой
# дисциплины) для ЛЮБОЙ команды, у которой есть хотя бы один результат, и
# сортируем по сумме. Место в этой таблице предварительное — оно будет
# смещаться по мере добавления дисциплин, это ожидаемо.

def _строка_результата_мб(к, рм, место):
    def ячейка(очки, есть_данные):
        return int(очки or 0) if есть_данные else '–'

    есть_пс = any(р.итоговое_место is not None for р in к.результат_пс)
    есть_слалом = any(р.место is not None for р in к.результат_слалом)
    есть_дг = к.результат_дг is not None and к.результат_дг.место is not None

    return {
        'Команда': к.название or '–',
        'Номер': к.нагрудный_номер,
        'Субъект': к.субъект.название if к.субъект else '–',
        'Спринт': ячейка(рм.очки_спринт, к.результат_спринт is not None),
        'Парал. спринт': ячейка(рм.очки_пс, есть_пс),
        'Слалом': ячейка(рм.очки_слалом, есть_слалом),
        'Длинная гонка': ячейка(рм.очки_дг, есть_дг),
        'Сумма': int(рм.сумма_очков or 0),
        'Место': место,
    }


def _группа_результатов_мб(sor_id, пол, класс, заголовок):
    from models import Команда

    команды = Команда.query.filter_by(соревнование_id=sor_id, пол=пол, класс_судна=класс).all()
    участники = [к for к in команды if к.результат_многоборья is not None]
    if not участники:
        return None

    участники.sort(key=lambda к: -(к.результат_многоборья.сумма_очков or 0))
    rows = [
        _строка_результата_мб(к, к.результат_многоборья, место)
        for место, к in enumerate(участники, 1)
    ]
    return {
        'competition_source_id': sor_id,
        'doc_type': 'результаты_мб',
        'title': заголовок,
        'rows': rows,
    }


def собрать_результаты_мб(сор):
    группы = []
    for пол, класс, заголовок in (
        ('м', 'R4', 'Многоборье – R4, мужчины'),
        ('ж', 'R4', 'Многоборье – R4, женщины'),
        ('м', 'R6', 'Многоборье – R6, мужчины'),
        ('ж', 'R6', 'Многоборье – R6, женщины'),
    ):
        группа = _группа_результатов_мб(сор.id, пол, класс, заголовок)
        if группа:
            группы.append(группа)
    return группы


def отправить_результаты_мб(сор):
    """В отличие от остальных дисциплин, НЕ гейтится готов_наград_мб —
    пункт "Многоборье" должен появляться и обновляться на сайте сразу по
    мере поступления результатов отдельных дисциплин, а не только когда
    судья отметил многоборье полностью готовым (эта отметка и не
    предполагает, что все 4 дисциплины уже проведены — см. models.py)."""
    группы = собрать_результаты_мб(сор)
    return _отправить_протоколы(
        группы, 'Данных для многоборья пока нет — нечего отправлять.', 'Результаты многоборья',
    )


def отправить_на_сайт(сор):
    """Отправляет одно соревнование на сайт. Возвращает (успех, сообщение)."""
    if not RAFTING_CFO_API_KEY:
        return False, 'RAFTING_CFO_API_KEY не задан в .env — см. .env.example'
    if not сор.дата_начала:
        return False, 'У соревнования не заполнена дата начала — заполните на странице редактирования'

    try:
        ответ = requests.post(
            f'{RAFTING_CFO_URL}/api/sync/competitions',
            json={'items': [собрать_данные(сор)]},
            headers={'X-API-Key': RAFTING_CFO_API_KEY},
            timeout=10,
        )
    except requests.RequestException as exc:
        return False, f'Не удалось соединиться с сайтом ({RAFTING_CFO_URL}): {exc}'

    if ответ.status_code != 200:
        return False, f'Сайт ответил ошибкой {ответ.status_code}: {ответ.text[:200]}'

    данные = ответ.json()
    if данные.get('errors'):
        return False, '; '.join(данные['errors'])
    return True, 'Отправлено на сайт.'
