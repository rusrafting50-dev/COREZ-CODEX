# результаты_спортсменов.py — лучший результат каждого спортсмена на
# соревновании: лучшее итоговое место (и в каких дисциплинах) и старший
# выполненный (подтверждённый) норматив разряда. Места и нормативы — те же,
# что в «Отчёте ФРР» (routes/отчеты.py, _стат, проход 5). Отправляется в
# карточки спортсменов REGTEAM_RAFTING (sync_regteam_rafting.отправить_результаты).
from models import Команда
from нормативы import получить_норматив

_РАНГ_ВЕС = {'МСМК': 8, 'МС': 7, 'КМС': 6, 'I': 5, 'II': 4, 'III': 3, 'Iю': 2, 'IIю': 1, 'IIIю': 0}
_РАЗРЯД_ТЕКСТ = {
    'I': 'I спортивного разряда', 'II': 'II спортивного разряда', 'III': 'III спортивного разряда',
    'Iю': 'I юношеского спортивного разряда', 'IIю': 'II юношеского спортивного разряда',
    'IIIю': 'III юношеского спортивного разряда',
}


def _вес(разряд):
    return _РАНГ_ВЕС.get((разряд or '').strip(), -1)


def _ключ(фио):
    return ' '.join((фио or '').replace('ё', 'е').replace('Ё', 'Е').lower().split())


def _места_команды(к):
    """[(дисциплина, тип норматива, место, флаг участия спортсмена)]."""
    места = []
    if к.результат_спринт and к.результат_спринт.место:
        места.append(('спринт', 'С', к.результат_спринт.место, 'участие_спринт'))
    пс = min((р.итоговое_место for р in (к.результат_пс or []) if р.итоговое_место), default=None)
    if пс:
        места.append(('параллельный спринт', 'П', пс, 'участие_пс'))
    сл = min((р.место for р in (к.результат_слалом or []) if р.место), default=None)
    if сл:
        места.append(('слалом', 'П', сл, 'участие_слалом'))
    if к.результат_дг and к.результат_дг.место:
        места.append(('длинная гонка', 'П', к.результат_дг.место, 'участие_дг'))
    if к.результат_многоборья and к.результат_многоборья.место:
        места.append(('многоборье', 'М', к.результат_многоборья.место, None))
    return места


def лучшие_результаты(сор):
    """[{фио, дата_рождения, результат}] — по одному на спортсмена (по ФИО),
    только у кого есть место или норматив."""
    код, возр = сор.код_соревнований, сор.возрастная_группа
    по_спортсмену = {}
    for к in Команда.query.filter_by(соревнование_id=сор.id).all():
        места = _места_команды(к)
        класс = (к.класс_судна or '').strip()
        for с in к.спортсмены:
            з = по_спортсмену.setdefault(_ключ(с.фамилия_имя_отчество),
                                         {'спортсмен': с, 'место': None, 'дисциплины': [], 'норматив': ''})
            if с.дата_рождения and not з['спортсмен'].дата_рождения:
                з['спортсмен'] = с
            for дисциплина, тип, место, флаг in места:
                if флаг and getattr(с, флаг, True) is False:
                    continue
                подпись = f'{дисциплина} {класс}'.strip()
                if з['место'] is None or место < з['место']:
                    з['место'], з['дисциплины'] = место, [подпись]
                elif место == з['место'] and подпись not in з['дисциплины']:
                    з['дисциплины'].append(подпись)
                норматив = получить_норматив(код, возр, тип, место)
                if норматив and норматив != '—' and _вес(норматив) > _вес(з['норматив']):
                    з['норматив'] = норматив

    итог = []
    for з in по_спортсмену.values():
        с = з['спортсмен']
        части = []
        if з['место']:
            части.append(f"{з['место']} место ({', '.join(з['дисциплины'])})")
        # норматив ниже имеющегося разряда спортсмена не выполнение и не подтверждение
        if з['норматив'] and _вес(з['норматив']) >= _вес(с.разряд):
            действие = 'подтвердил' if _вес(з['норматив']) == _вес(с.разряд) else 'выполнил'
            части.append(f"{действие} норматив {_РАЗРЯД_ТЕКСТ.get(з['норматив'], з['норматив'])}")
        if части:
            итог.append({'фио': с.фамилия_имя_отчество.strip(), 'дата_рождения': с.дата_рождения,
                         'результат': '; '.join(части)})
    итог.sort(key=lambda р: р['фио'])
    return итог


def сроки_и_место(сор):
    return ', '.join(x.strip() for x in (сор.даты_проведения or '', сор.место_проведения or '') if x and x.strip())
