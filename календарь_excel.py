# календарь_excel.py — экспорт соревнований в Excel по форме «Предложения по
# включению спортивных мероприятий в Календарный план…» (лист «КП»).
# Образец — data/Шаблон КП.xlsx: шапка «СОГЛАСОВАНО», заголовок, таблица из
# 18 столбцов. Тот же формат читает импорт (routes/настройки.py, _разобрать_кп).
import copy
import math
import os
import re
from collections import Counter
from datetime import date, datetime
from io import BytesIO

import openpyxl

BASE_DIR = os.path.abspath(os.path.dirname(__file__))
ШАБЛОН = os.path.join(BASE_DIR, 'data', 'Шаблон КП.xlsx')

ВСЕРОССИЙСКИЕ_В_ЦФО = 'Всероссийские в ЦФО'
# Коды соревнований (routes/соревнование.py, СТАТУСЫ)
ФЕДЕРАЛЬНЫЕ_КОДЫ = {'ЧР', 'КР', 'ПР', 'ПРЮ', 'ВС', 'ЧФО', 'ПФО', 'МСС'}
МУНИЦИПАЛЬНЫЕ_КОДЫ = {'ЧМО', 'ПМО', 'ССМО'}

ПЕРВАЯ_СТРОКА = 13
_МЕСЯЦЫ = {'янв': 1, 'фев': 2, 'мар': 3, 'апр': 4, 'мая': 5, 'май': 5, 'июн': 6,
           'июл': 7, 'авг': 8, 'сен': 9, 'окт': 10, 'ноя': 11, 'дек': 12}
_RE_ДЕНЬ_МЕСЯЦ = re.compile(r'(\d{1,2})\s+(' + '|'.join(_МЕСЯЦЫ) + r')[а-я]*', re.IGNORECASE)
_RE_ЧИСЛОВАЯ = re.compile(r'(\d{1,2})\.(\d{1,2})\.(\d{4})')
_RE_ГОД = re.compile(r'\d{4}')


def муниципальное(с):
    return (с.код_соревнований in МУНИЦИПАЛЬНЫЕ_КОДЫ
            or 'муниципальн' in (с.уровень or '').lower())


def федеральное(с):
    return с.код_соревнований in ФЕДЕРАЛЬНЫЕ_КОДЫ


def отобрать(соревнования, год, субъект, с_муниципальными, субъекты_цфо):
    """Соревнования для выгрузки: год по дате начала; субъект РФ — региональные
    соревнования этого субъекта (муниципальные — по флагу); «Всероссийские в
    ЦФО» — всероссийские, межрегиональные и окружные в субъектах ЦФО."""
    итог = []
    for с in соревнования:
        if not с.дата_начала or с.дата_начала.year != год:
            continue
        где = (с.субъект_рф_название or '').strip()
        if субъект == ВСЕРОССИЙСКИЕ_В_ЦФО:
            if not федеральное(с) or где not in субъекты_цфо:
                continue
        else:
            if где != субъект or федеральное(с):
                continue
            if муниципальное(с) and not с_муниципальными:
                continue
        итог.append(с)
    итог.sort(key=lambda с: (с.дата_начала, с.название or ''))
    return итог


def даты(с):
    """(начало, окончание) из дата_начала и текста «сроков проведения»:
    «11 — 12 апреля 2026 года», «31 мая — 1 июня 2026 года», «11.04.2026»."""
    начало = с.дата_начала
    текст = с.даты_проведения or ''
    дни = [(int(д), int(м), int(г)) for д, м, г in _RE_ЧИСЛОВАЯ.findall(текст)]
    if not дни:
        год_м = _RE_ГОД.search(текст)
        год = int(год_м.group()) if год_м else (начало.year if начало else None)
        части = _RE_ДЕНЬ_МЕСЯЦ.findall(текст)
        # «11 — 12 апреля»: первое число без месяца берёт месяц следующего
        одиночный = re.match(r'\s*(\d{1,2})\s*[-–—]\s*\d{1,2}\s+[а-я]', текст, re.IGNORECASE)
        if год and части:
            if одиночный:
                дни.append((int(одиночный.group(1)), _МЕСЯЦЫ[части[0][1].lower()[:3]], год))
            дни += [(int(д), _МЕСЯЦЫ[м.lower()[:3]], год) for д, м in части]
    try:
        окончание = date(дни[-1][2], дни[-1][1], дни[-1][0]) if дни else None
        if not начало and дни:
            начало = date(дни[0][2], дни[0][1], дни[0][0])
    except ValueError:
        окончание = None
    if окончание is None or (начало and окончание < начало):
        окончание = начало
    return начало, окончание


def инициалы(фио):
    """«Милевский Евгений Владимирович» -> «Е. В. Милевский»; уже с
    инициалами — как есть."""
    части = (фио or '').split()
    if len(части) < 2 or any(ч.endswith('.') for ч in части):
        return (фио or '').strip()
    фамилия, *имена = части
    return ' '.join(f'{и[0]}.' for и in имена) + ' ' + фамилия


def родительный(субъект):
    """«Московская область» -> «Московской области», «город Москва» -> «города Москвы»."""
    s = (субъект or '').strip()
    if s.lower() == 'город москва':
        return 'города Москвы'
    м = re.fullmatch(r'(.+)ская область', s)
    if м:
        return f'{м.group(1)}ской области'
    return s


def _самое_частое(значения):
    значения = [з.strip() for з in значения if з and з.strip()]
    return Counter(значения).most_common(1)[0][0] if значения else ''


def _строк_текста(текст, ширина_символов):
    строки = 0
    for абзац in str(текст or '').split('\n'):
        строки += max(1, math.ceil(len(абзац.strip()) / ширина_символов))
    return строки


def сформировать(соревнования, год, субъект, вид_спорта, организация_субъекта=''):
    wb = openpyxl.load_workbook(ШАБЛОН)
    ws = wb['КП']

    # Шапка «СОГЛАСОВАНО»
    ws['B2'] = _самое_частое(с.федерация_должность for с in соревнования)
    ws['H2'] = инициалы(_самое_частое(с.федерация_руководитель for с in соревнования))
    ws['B5'] = организация_субъекта or _самое_частое(с.федерация_название for с in соревнования)
    if субъект != 'Московская область':
        ws['B7'] = '(указывается наименование региональной спортивной федерации)'

    if субъект == ВСЕРОССИЙСКИЕ_В_ЦФО:
        ws['A11'] = ('Предложения по включению спортивных мероприятий в Единый календарный план '
                     'межрегиональных, всероссийских и международных физкультурных мероприятий '
                     f'и спортивных мероприятий\nна {год} год')
        ws.row_dimensions[11].height = 63
    else:
        ws['A11'] = ('Предложения по включению спортивных мероприятий в Календарный план '
                     'физкультурных мероприятий и спортивных мероприятий\n'
                     f'{родительный(субъект)} на {год} год')

    образец_стиля = [copy.copy(ws.cell(ПЕРВАЯ_СТРОКА, c)._style) for c in range(1, 19)]
    for i, с in enumerate(соревнования):
        r = ПЕРВАЯ_СТРОКА + i
        if r > ws.max_row:
            for c in range(1, 19):
                ws.cell(r, c)._style = copy.copy(образец_стиля[c - 1])
        начало, окончание = даты(с)
        ws.cell(r, 1).value = 1 if i == 0 else f'=A{r - 1}+1'
        ws.cell(r, 2).value = с.название
        ws.cell(r, 3).value = вид_спорта
        ws.cell(r, 4).value = datetime.combine(начало, datetime.min.time()) if начало else None
        ws.cell(r, 5).value = datetime.combine(окончание, datetime.min.time()) if окончание else None
        ws.cell(r, 6).value = f'=E{r}-D{r}+1'
        ws.cell(r, 7).value = с.место_проведения
        ws.cell(r, 8).value = с.кол_участников
        ws.cell(r, 11).value = f'=J{r}*I{r}'
        строк = max(3, _строк_текста(с.название, 26), _строк_текста(с.место_проведения, 19))
        ws.row_dimensions[r].height = 15.75 * строк

    последняя = ПЕРВАЯ_СТРОКА + max(len(соревнования), 1) - 1
    ws.print_area = f'A1:R{последняя}'

    # Проверка дат D:E — в пределах выгружаемого года
    for dv in ws.data_validations.dataValidation:
        if dv.type == 'date':
            dv.formula1 = str((date(год, 1, 1) - date(1899, 12, 30)).days)
            dv.formula2 = str((date(год, 12, 31) - date(1899, 12, 30)).days)
            dv.error = f'Необходимо указать от 01.01.{год} до 31.12.{год} в числовом формате'

    buf = BytesIO()
    wb.save(buf)
    buf.seek(0)
    return buf
