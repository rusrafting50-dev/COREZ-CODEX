# sync_all_to_rafting_cfo.py — разовая отправка ВСЕХ существующих
# соревнований на сайт RAFTING_CFO (одноразовый бэкфилл).
#
# После этого новые/изменённые соревнования дальше отправляются вручную
# кнопкой "Отправить на сайт" на карточке соревнования — этот скрипт
# нужен только один раз, чтобы подтянуть то, что было создано ДО того,
# как появилась кнопка.
#
# Запуск: python sync_all_to_rafting_cfo.py
from app import app
from models import Соревнование
from sync_rafting_cfo import отправить_на_сайт

with app.app_context():
    все = Соревнование.query.all()
    if not все:
        print('Соревнований в базе нет.')
    for сор in все:
        успех, сообщение = отправить_на_сайт(сор)
        отметка = 'OK' if успех else 'ОШИБКА'
        print(f'[{отметка}] #{сор.id} «{сор.название}»: {сообщение}')
